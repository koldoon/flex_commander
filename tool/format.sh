#!/bin/sh
# Форматирование всего кода, кроме вендорной копии re_editor.
#
# `dart format` исключений не понимает вовсе: ни флага, ни `exclude` в
# analysis_options (он их просто не читает). Единственный способ обойти каталог —
# не подавать его на вход, поэтому список файлов берётся у git: заодно мимо
# проходят build/ и .dart_tool/.
#
# Отбор тот же, что у проверки в CI (README, «Tests and CI»), — там она читает,
# здесь пишет. Расходиться им нельзя: код, отформатированный `dart format .`,
# CI завалит на re_editor, а тамошние отличия от апстрима уйдут мерж-реквестом
# и переформатировать их нельзя.
set -e
cd "$(dirname "$0")/.."
git ls-files -z '*.dart' | grep -zv '^dependency/re_editor/' | xargs -0 dart format "$@"
