import 'package:fc_api/fc_api.dart';

import 'pty.dart';

/// Повышение прав — та половина, которая **делает**.
///
/// Экран о ней не знает и знать не должен: там вопрос и ответ ([Elevation] в
/// `fc_api`), а здесь — сама запись от администратора, которой нужен и
/// провайдер, и оболочка той стороны.
abstract interface class ElevatedWrites implements Elevation {
  /// Положить готовый файл на место цели от администратора.
  ///
  /// [host] — где выполнять: своя машина или сервер. Он же говорит, **чей** это
  /// `sudo`, и он же — единственное, что отличает удалённое повышение от
  /// местного.
  ///
  /// [temporary] и [target] — пути **на той же стороне**, что и [host]:
  /// временный файл кладёт туда провайдер, он это умеет.
  ///
  /// Копирует, а не переименовывает: файл, переименованный от `root`, достался
  /// бы `root` и потерял исходные права. `cp` сохраняет владельца, режим и
  /// inode цели.
  ///
  /// `false` — отказались (от подтверждения или от пароля); цель при этом не
  /// тронута. Не вышло — исключение, и тогда исходный отказ показывается как
  /// есть.
  Future<bool> copyOver({
    required ShellHost host,
    required String temporary,
    required String target,
    required ElevationRequest about,
  });
}
