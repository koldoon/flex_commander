import 'package:flutter/foundation.dart';

import 'fs_node.dart';

/// Помеченные объекты панели.
///
/// Живёт на стороне ядра, потому что говорит об узлах: пометка — это состояние
/// сеанса, а не экрана. Наружу от неё едут имена и сводка, и то и другое —
/// частью `PanelState` (`docs/spec/client-server.md`, §4.5).
///
/// [Listenable]: строка панели и её содержимое перерисовываются по изменению
/// пометки, поэтому подписка описана здесь, а не добирается приведением
/// к реализации.
abstract interface class PanelSelection implements Listenable {
  bool contains(FsNode node);

  /// Псевдоузел «..» не помечается никогда.
  ///
  /// **Один объект — одна пометка.** Ключ объекта — его путь ([FsNode.pathString]),
  /// и повторная пометка того же пути ничего не добавляет, каким бы экземпляром
  /// узла он ни пришёл. Предохранитель стоит здесь, а не у вызывающих: за
  /// пометкой ходят панель, дерево, маска и мышь, а правило у неё одно на всех
  /// (`docs/spec/panel-view-tree.md`, §7).
  void add(FsNode node);

  void remove(FsNode node);

  void toggle(FsNode node);

  void addAll(Iterable<FsNode> nodes);

  void clear();

  /// Помеченные объекты в порядке пометки — он же порядок обработки
  /// в файловых операциях.
  List<FsNode> get nodes;

  int get length;

  bool get isEmpty;

  bool get isNotEmpty;

  /// Суммарный размер помеченных объектов; объекты с неизвестным размером
  /// (каталоги) в сумму не входят.
  int get totalSize;

  /// Имена помеченных объектов — для тех, кому важно имя, а не объект.
  ///
  /// Опознавать по ним нечего: в дереве видно несколько каталогов разом, и
  /// одинаковые имена в них — разные объекты. Для опознания есть [paths].
  Set<String> get names;

  /// Пути помеченных объектов — в порядке пометки.
  ///
  /// Это и есть пометка, как её видит та сторона границы: путь опознаёт объект
  /// где угодно в дереве, а после перечитывания каталога — находит его новый
  /// экземпляр (`docs/spec/panel-view-tree.md`, §7).
  Set<String> get paths;
}
