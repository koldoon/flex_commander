/// Как источник просит себя показывать.
///
/// Живёт здесь, а не в API интерфейса, потому что говорит это **источник**, а
/// он по эту сторону границы. Наружу оба ответа уезжают снимком
/// (`SourceInfo.contentKind` и `SourceInfo.columns`): интерфейс их знает, а не
/// спрашивает (`docs/spec/client-server.md`, §4.4).
library;

import 'package:fc_api/fc_api.dart';
import 'package:flutter/foundation.dart';

import 'node_sorting.dart';
import 'tree_provider.dart';

/// Провайдер, содержимое которого рисуется не таблицей файлов.
///
/// Интерфейс, а не флаг: про флаг можно соврать, про наличие метода нельзя —
/// то же правило, что у [NodeEditor] и остального в провайдерах.
abstract interface class PanelContent {
  /// Вид содержимого: `search`, `viewer`, `image`. Под это имя модуль
  /// регистрирует то, чем оно рисуется.
  String get contentKind;
}

/// Провайдер, который просит показывать себя своим видом панели.
///
/// Тот же приём, что и [PanelContent] с [PanelExtraColumns], и по той же причине:
/// найденное — дерево, и плоским списком его не показать
/// (`docs/spec/file-search.md`, §4). Просьба живёт, пока показывают источник:
/// ушли из него — панель снова показывает вид, который выбрал человек, и его же
/// хранит в настройках. Переключить вид на месте человек всё равно может —
/// просьба источника не запрет, а умолчание (`docs/spec/panel-views.md`, §7).
abstract interface class PanelPreferredView {
  /// Имя вида — то же, под которым его объявил модуль (`PanelViewSpec.id`).
  String get preferredView;

  /// Что в этом виде раскрыто сразу — пути ветвей.
  ///
  /// Иначе находка, лежавшая на три каталога вглубь, пряталась бы за тремя
  /// нажатиями. Раскрытое источника живёт, пока его показывают, и в настройки
  /// панели не попадает: человек его не выбирал.
  Iterable<String> get openBranches;
}

/// Провайдер, показывающий **проекцию** чужого дерева: те же места, только
/// отобранное.
///
/// Находки: каталоги в них свои, но за каждым стоит настоящий, и ходят по ним
/// как по обычному дереву. Отличие ровно одно — **смена вида панель не
/// двигает**: у обычного дерева уйти в каталог под курсором это то, чего
/// человек и хотел (`docs/spec/panel-view-tree.md`, §3), а здесь это выглядит
/// как «список пропал, осталась одна строка»
/// (`docs/spec/file-search.md`, §4а, Н1).
///
/// Источник говорит о себе сам, а панель не догадывается по строке: догадка
/// однажды ошиблась бы, а спросить — дёшево.
abstract interface class PanelVirtualBranches {}

/// Провайдер, у которого есть собственное имя — вместо пути.
///
/// Находки зовутся `Find "TODO"`, а не каталогом, в котором искали: панель
/// показывает **список**, и путь на его месте сбивает с толку
/// (`docs/spec/panel-header.md`, §3).
///
/// Спрашивают имя **у источника**, а не ставят его снаружи просьбой: снимать
/// поставленное было бы некому ровно тогда, когда работа кончилась, а человек
/// ушёл. Сменился провайдер — сменилось и имя, само собой.
abstract interface class PanelSourceTitle {
  String get sourceTitle;
}

/// Провайдер, который сам называет, куда ведёт `..`.
///
/// Нужен там, где корень источника ни в чём не лежит: находки не подвешены в
/// чужое дерево, и родителя, из которого вывелся бы выход, у них нет. Пусто —
/// выходить некуда (`docs/spec/file-search.md`, §4.6).
abstract interface class PanelExitPath {
  String get exitPath;
}

/// Провайдер, содержимое которого меняется само.
///
/// Находки прибывают, пока идёт обход, и список растёт без единого нажатия.
/// Панель узнаёт об этом от источника — а не перечитывается по таймеру,
/// заведённому где-то в стороне: таймер жил дольше показа и дёргал панель,
/// давно ушедшую в обычный каталог (`docs/spec/file-search.md`, §4.7).
abstract interface class PanelSourceChanges {
  /// О чём говорит: «во мне прибавилось». Слушать и отписываться — дело
  /// панели.
  Listenable get changes;
}

/// Провайдер, который наполняется работой.
///
/// Источник только **называет** работу — имя и доводы; заводит её тот, кто
/// источник открыл: окно поиска сразу, панель при восстановлении по просьбе
/// человека. Правило «работа рождается заявкой с экрана» от этого не страдает
/// (`docs/spec/client-server.md`, §5.4), а поиск не строит для фона ничего
/// своего: полоска, список работ, вопросы и отмена у него общие со всеми.
abstract interface class PanelFilledByWork {
  /// Чем наполнять: заявка целиком, собранная из адреса источника.
  OperationSpec get work;

  /// Наполнен ли уже: пусто — работу ещё не заводили.
  bool get filled;
}

/// Провайдер, который отдаёт узлы в **своём** порядке и просит его не менять.
///
/// Находки: они прибывают по ходу обхода, и всякая сортировка вставляла бы
/// новое в середину — уже прочитанное на экране переезжало бы с каждой пачкой.
/// Порядок обхода спокоен: новое всегда в конце.
///
/// Просьба, а не запрет: щёлкнув по заголовку, человек получает сортировку —
/// он её и попросил. Своей настройки панели он этим не меняет, как и с видом.
abstract interface class PanelNaturalOrder {}

/// Провайдер, которому мало тех колонок, что показаны у каталога.
///
/// Тот же приём, что и [PanelContent], и по той же причине: список находок —
/// не каталог, и колонка пути в нём не прихоть, а единственное, чем строки
/// различаются. Раскладка панели при этом не трогается: человек её настраивал
/// под свои каталоги, и уход в находки не должен её переписывать.
///
/// Просит **имена**, а не раскладку: собрать чужую разметку источнику нечем —
/// умолчаний в ядре нет вовсе, их знают объявления модулей
/// (`docs/spec/column-registry.md`, §6). Названные колонки включает поверх
/// раскладки тот, кто рисует, и никуда их не сохраняет.
abstract interface class PanelExtraColumns {
  /// Без чего этот источник не читается: `{'path'}`.
  Set<String> get extraColumns;

  /// Чем сортировать эту колонку; null — тем, что объявлено в реестре.
  ///
  /// Своя колонка без своего сравнения бесполезна: сортировать её ядру нечем,
  /// а знает о ней только источник (`docs/spec/panel-node-list.md`, §5).
  NodeComparator? comparatorOf(String column);
}

/// Объявленные колонки — ядровой половиной.
///
/// Колонка расщеплена надвое общим идентификатором: здесь заголовок, ширина и
/// **сравнение**, на экране — заголовок, ширина и **ячейка**. Иначе нельзя:
/// узлы живут в изоляте и наружу не ездят, а колбэк через порт не поедет
/// (`docs/spec/client-server.md`, §3). Поэтому одно и то же объявление модуль
/// регистрирует по разу на каждой стороне
/// (`docs/spec/column-registry.md`, §3.2).
abstract interface class ColumnSorting {
  /// Всё объявленное — в порядке объявления.
  List<ColumnSpec> get declared;

  ColumnSpec? find(String id);

  /// Чем сравнивать; null — сравнения нет, порядок задаст доводчик по имени.
  NodeComparator? comparatorOf(String id);

  /// Правило сортировки, которое эта сборка и правда умеет.
  ///
  /// Колонка, которой никто не объявлял, и колонка, объявленная
  /// несортируемой, заменяются на имя. Одно место на всё приложение: раньше
  /// это проверяли и разбор настроек, и `sortBy`, а разбору взять реестр
  /// негде (`docs/spec/column-registry.md`, §5).
  SortSpec sanitize(SortSpec spec);
}
