/// Как источник просит себя показывать.
///
/// Живёт здесь, а не в API интерфейса, потому что говорит это **источник**, а
/// он по эту сторону границы. Наружу оба ответа уезжают снимком
/// (`SourceInfo.contentKind` и `SourceInfo.columns`): интерфейс их знает, а не
/// спрашивает (`docs/spec/client-server.md`, §4.4).
library;

import 'package:fc_api/fc_api.dart';

import 'node_sorting.dart';
import 'tree_provider.dart';

/// Провайдер, содержимое которого рисуется не таблицей файлов.
///
/// Интерфейс, а не флаг: про флаг можно соврать, про наличие метода нельзя —
/// то же правило, что у [NodeEditor] и остального в провайдерах.
abstract interface class PanelContent {
  /// Вид содержимого: `search`, `viewer`, `image`. Под это имя модуль
  /// регистрирует то, чем оно рисуется.
  String get contentKind;
}

/// Провайдер, который просит показывать себя своим видом панели.
///
/// Тот же приём, что и [PanelContent] с [PanelColumns], и по той же причине:
/// найденное — дерево, и плоским списком его не показать
/// (`docs/spec/file-search.md`, §4). Просьба живёт, пока показывают источник:
/// ушли из него — панель снова показывает вид, который выбрал человек, и его же
/// хранит в настройках. Переключить вид на месте человек всё равно может —
/// просьба источника не запрет, а умолчание (`docs/spec/panel-views.md`, §7).
abstract interface class PanelPreferredView {
  /// Имя вида — то же, под которым его объявил модуль (`PanelViewSpec.id`).
  String get preferredView;

  /// Что в этом виде раскрыто сразу — пути ветвей.
  ///
  /// Иначе находка, лежавшая на три каталога вглубь, пряталась бы за тремя
  /// нажатиями. Раскрытое источника живёт, пока его показывают, и в настройки
  /// панели не попадает: человек его не выбирал.
  Iterable<String> get openBranches;
}

/// Провайдер, который отдаёт узлы в **своём** порядке и просит его не менять.
///
/// Находки: они прибывают по ходу обхода, и всякая сортировка вставляла бы
/// новое в середину — уже прочитанное на экране переезжало бы с каждой пачкой.
/// Порядок обхода спокоен: новое всегда в конце.
///
/// Просьба, а не запрет: щёлкнув по заголовку, человек получает сортировку —
/// он её и попросил. Своей настройки панели он этим не меняет, как и с видом.
abstract interface class PanelNaturalOrder {}

/// Провайдер, который просит показывать себя не теми колонками, что каталог.
///
/// Тот же приём, что и [PanelContent], и по той же причине: список находок —
/// не каталог, и колонка пути в нём не прихоть, а единственное, чем строки
/// различаются. Раскладка панели при этом не трогается: человек её настраивал
/// под свои каталоги, и уход в находки не должен её переписывать.
abstract interface class PanelColumns {
  ColumnLayout get columns;

  /// Чем сортировать эту колонку; null — сравнением по умолчанию.
  ///
  /// Своя колонка без своего сравнения бесполезна: сортировать её ядру нечем,
  /// а знает о ней только источник. Поэтому сравнение приходит оттуда же,
  /// откуда раскладка (`docs/spec/panel-node-list.md`, §5).
  NodeComparator? comparatorOf(FsColumn column);
}
