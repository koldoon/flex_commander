/// Показ текста во весь экран — общий для просмотрщика и редактора.
///
/// Здесь то, чем эти два экрана устроены одинаково: само поле, оформление из
/// темы, таблица языков подсветки, сочетания клавиш, поиск и его команды.
/// Разница между экранами — в одном `readOnly` и в праве писать.
///
/// Отдельно от `fc_ui_kit`, потому что это **не** общий интерфейс приложения:
/// панелям, окнам и кнопкам показ текста не нужен, а вместе с ним им достался
/// бы и `re_editor`. Не модуль: регистрировать нечего, библиотекой пользуются.
///
/// Об именах: `code` здесь только там, где речь и правда о языке — таблица
/// языков и цвета токенов. Просмотрщик и редактор не инструменты для кода, они
/// служат чтению и правке любых текстовых документов.
