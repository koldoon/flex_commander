import 'dart:typed_data';

/// Значки, которые об объектах знает сама система.
///
/// Тот же значок, что человек видит в Finder: свой у `Safari.app`, документный
/// у `report.pdf`, стандартный у папки. Нарисовать такое из Flutter нельзя —
/// это умеет только настоящая машина, поэтому реализация живёт в раннере
/// (`docs/spec/file-icons.md`, §5).
///
/// **Три вопроса, а не один** — по убыванию точности:
///
/// * **по пути** — только так видно своё лицо пакета (`*.app`), тома и файла с
///   назначенной иконкой. Дорого: каждая строка — свой вопрос;
/// * **по расширению** — у обычного файла значок только от него и зависит,
///   и тысяча `.txt` в каталоге стоит одного вопроса вместо тысячи. Пути для
///   этого не нужно вовсе, поэтому так спрашивают и про файл на сервере;
/// * **по роду** — папка или просто файл, когда сказать больше нечего.
///
/// Ответ — байты `png` или null: значка нет, платформа не умеет, путь не
/// существует. Null не беда — иконка возьмётся следующим правилом.
///
/// **Значки всегда свои, здешние.** Спрашивая про файл на сервере, мы
/// спрашиваем, чем **эта** машина показала бы такой файл: чужих сопоставлений
/// нам никто не расскажет, да и человек смотрит на свой экран.
abstract interface class SystemIcons {
  /// Значок этого объекта.
  ///
  /// [pixels] — сторона квадрата **в пикселях экрана**, а не в точках: значок
  /// отрисовывается под тот экран, на котором его покажут.
  Future<Uint8List?> forPath(String path, {required int pixels});

  /// Значок по расширению — без точки, в том виде, в каком он в имени.
  Future<Uint8List?> forExtension(String extension, {required int pixels});

  /// Значок рода: папка или просто файл.
  Future<Uint8List?> forKind(SystemIconKind kind, {required int pixels});
}

/// Род объекта — то немногое, что известно, когда нет ни пути, ни расширения.
enum SystemIconKind { folder, file }
