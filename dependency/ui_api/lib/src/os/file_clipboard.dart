import 'package:fc_api/fc_api.dart';

/// Файлы в буфере обмена (`docs/spec/file-clipboard.md`).
///
/// Отдельно от текстового [ClipboardService]: файлы к его двум методам не
/// сводятся, а знают о них разные — текст нужен просмотрщику и окну сведений,
/// файлы файловым командам.
///
/// Нет службы — нет и команд буфера: клавиши свободны, в палитре их не видно,
/// всё остальное работает. Ровно так же ведёт себя перетаскивание
/// ([DragAndDrop]).
abstract interface class FileClipboard {
  /// Положить объекты в буфер; [move] — намерение перенести, а не копировать.
  ///
  /// Строками, а не адресами: системной половине нужен **настоящий** путь
  /// объекта и его имя — по ним файл кладётся в буфер системы, а у того, у
  /// кого настоящего пути нет (архив, сервер), отдаётся обещанием. Своей же
  /// половине нужен адрес приложения, и он в строке тоже есть.
  Future<void> writeFiles(List<FileEntry> entries, {required bool move});

  /// Что в буфере сейчас; null — там лежат не файлы.
  Future<ClipboardFiles?> readFiles();
}

/// Файлы, лежащие в буфере.
class ClipboardFiles {
  const ClipboardFiles({required this.addresses, this.move = false, this.ours = false});

  /// Адреса — в том виде, в каком их разберёт панель, куда вставляют.
  ///
  /// Наши — адреса приложения (`ssh://…`, путь внутри архива); чужие — путями
  /// системы, других там не бывает.
  final List<String> addresses;

  /// Перенести, а не скопировать.
  ///
  /// Намерение живёт по эту сторону: системный буфер его не несёт, и чужая
  /// запись в буфер его гасит (`docs/spec/file-clipboard.md`, §5).
  final bool move;

  /// Положили их мы сами.
  final bool ours;

  bool get isEmpty => addresses.isEmpty;
}
