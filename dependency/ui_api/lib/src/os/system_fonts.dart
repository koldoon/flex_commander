/// Шрифт, установленный в системе.
class SystemFont {
  const SystemFont({required this.family, required this.fixedPitch});

  /// Название семейства — то самое, что пишут в теме.
  final String family;

  /// Моноширинный: этим и отбирают шрифт для списка файлов, где размеры и даты
  /// обязаны стоять столбцами.
  ///
  /// Спрашивается у системы, а не угадывается по названию: `Menlo` и `Monaco`
  /// моноширинные, а `Monotype Corsiva` — нет.
  final bool fixedPitch;
}

/// Какие шрифты стоят в системе.
///
/// Вещь платформенная (сквозное правило 2): из Flutter перечня установленных
/// шрифтов не узнать вовсе. Службы нет — значит, спросить некого, и шрифт
/// набирают руками; так и было до неё (`docs/spec/theme-editor.md`, §12).
abstract interface class SystemFonts {
  /// Перечень семейств; пусто — система не ответила.
  ///
  /// Спрашивается один раз при запуске и держится: набор шрифтов за время
  /// работы приложения не меняется, а ждать ответа посреди раскрытия списка
  /// было бы нечем.
  List<SystemFont> get installed;

  /// Спросить систему и запомнить ответ.
  Future<void> refresh();
}
