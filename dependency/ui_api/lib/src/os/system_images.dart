import 'dart:typed_data';

/// Картинка, которую разобрала система.
///
/// Размеры и формат — **настоящие**, от исходного файла, а не от того, во что
/// его пересжали для показа: в плашке человек должен видеть `2860×3814 · HEIC`,
/// а не `JPEG` (`docs/spec/image-viewer.md`, §12).
class SystemImage {
  const SystemImage({required this.width, required this.height, required this.format, this.bytes});

  final int width;
  final int height;

  /// Имя формата исходника — `HEIC`, `TIFF`; пусто — система не назвала.
  final String format;

  /// Чем показывать; null — точек больше, чем просили, и распаковки не было.
  ///
  /// Предел остаётся у просмотрщика: он его и передаёт. Система, увидев
  /// превышение, не тратится на распаковку — отвечает одними размерами, а
  /// отказ словами складывает тот, кто спрашивал.
  final Uint8List? bytes;
}

/// Разбор картинок, которых не умеет Flutter.
///
/// `HEIC` — родной формат снимков с телефона: Skia его не декодирует, а
/// система декодирует. Тем же путём когда-нибудь пойдут `tiff` и `avif`
/// (`docs/spec/image-viewer.md`, §12).
///
/// Службы нет — просмотрщик отказывает ровно теми же словами, что и до неё.
abstract interface class SystemImages {
  /// Картинка, которую Flutter не умеет, — в ту, которую умеет.
  ///
  /// **Байтами, а не путём**: так `HEIC` открывается из архива и с сервера
  /// тоже, тем же путём, каким туда попадают `png` и `jpeg`. Возвращает null,
  /// если система тоже не разобрала.
  Future<SystemImage?> readable(Uint8List bytes, {required int maxPixels});
}
