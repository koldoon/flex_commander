import 'package:fc_api/fc_api.dart';

/// Наборы выбора, объявленные приложением (`docs/spec/key-presets.md`).
///
/// Служба ядра: её спрашивает список наборов. Модуль о ней не знает — он
/// только объявляет свой набор, как объявляет команды и привязки.
///
/// **Встроенный набор не свой**: выбрать и выгрузить его можно, а обновить или
/// удалить — нет, и имя его занято навсегда.
abstract interface class PresetCatalog {
  List<Preset> get presets;
}
