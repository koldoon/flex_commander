import 'package:fc_api/fc_api.dart';

/// Наборы клавиш, объявленные приложением (`docs/spec/keymaps.md`).
///
/// Служба экрана: её спрашивает раздел «Keyboard». Модуль о ней не знает — он
/// только объявляет свой набор, как объявляет команды и привязки.
///
/// **Встроенный набор не свой**: выбрать, поправить и выгрузить его можно, а
/// удалить — нет, и имя его занято навсегда.
abstract interface class KeymapCatalog {
  List<Keymap> get keymaps;
}
