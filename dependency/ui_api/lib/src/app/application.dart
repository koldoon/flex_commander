/// Приложение целиком — то, чем оперируют команды.
///
/// Аналог `IApplication` референса. Вместе с [Panel] и [PanelSelection] это и
/// есть API для написания команд: всё, что команде нужно знать о приложении,
/// описано здесь, а как это устроено внутри — её не касается.
///
/// [Listenable] — часть контракта, а не подробность реализации: тот, кто рисует
/// приложение или следит за ним из модуля, подписывается на интерфейс и не
/// обязан знать про `AppController`.
abstract interface class Application implements Listenable {
  Panel get left;

  Panel get right;

  /// Активная панель — источник операции.
  Panel get activePanel;

  /// Пассивная панель — приёмник операции.
  Panel get passivePanel;

  /// Действия приложения и клавиши за ними.
  ///
  /// Через него модуль ставит свои команды, а нижняя панель узнаёт, что висит
  /// на `F5` прямо сейчас.
  CommandService get commands;

  /// Оформление приложения: какое есть и какое выбрано.
  ThemeService get theme;

  /// Заведённые работы: их показывают статусные области.
  Operations get operations;

  /// Завести длительную работу — заявкой.
  ///
  /// Единственный вход для всего долгого: копирование, упаковка, подсчёт.
  /// Работа рождается там, где живут источники, а команда только называет её и
  /// приносит доводы значениями (`docs/spec/client-server.md`, §5.4).
  ///
  /// Возвращается обычная [Operation]: запустить заявкой, следить за `status`,
  /// отвечать на `requests`, прерывать `cancel()`. Что она идёт по ту сторону
  /// границы, ни окну работы, ни статусной области знать не нужно.
  /// [runId] — своё имя работе; подаёт его тот, кому оно нужно и потом:
  /// поиск показывает находки той же работы, а полоска в статусной области
  /// зовёт её так же, как ядро. Без имени работа получит своё.
  ///
  /// [onFound] — куда класть найденное по ходу дела. Ради одной работы: поиск.
  /// У остальных ответ один — исход.
  Operation<OperationSpec, void> runOperation({String? runId, void Function(List<FileEntry> entries)? onFound});

  /// Оболочка того места, где стоит панель, — тоже разговором.
  ///
  /// Оболочка **одна на место**, и живёт она в ядре: там псевдотерминал, там
  /// же аренда источника — `htop`, запущенный на сервере, обязан дожить до
  /// своего конца, даже если панель ушла оттуда сразу. Сюда приезжает канал:
  /// байты наружу, клавиши внутрь, размер окна, конец.
  ///
  /// [panel] null — своя машина: греют оболочку заранее, когда панелей ещё нет.
  /// Не вышло — [FsError]: клавишу нажали, и молчать нельзя.
  Future<ShellChannel> openShell({Panel? panel, String? directory, int columns, int rows});

  /// Ошибки, которые никто не поймал: показать человеку, а не только записать
  /// в журнал.
  Errors get errors;

  /// Всплывающие сообщения: сказать о том, что случилось и уже закончилось.
  Toasts get toasts;

  /// Вопрос о секрете, который сейчас на экране, и ответ на него.
  ///
  /// Спрашивает **ядро** — секрет нужен тому, кто работает с источником, — а
  /// здесь только показ (`docs/spec/client-server.md`, §7.3). Модуль получает
  /// ту же службу через `services.resolve<CredentialPrompt>()`.
  CredentialPrompt get credentials;

  /// Повышение прав: сделать то, на что обычных прав не хватило.
  ///
  /// Рядом с секретами и по той же причине: спросить может только тот, у кого
  /// есть экран, а обнаруживает нужду тот, кто до экрана не дотягивается.
  Elevation get elevation;

  /// Как имя делится на имя и расширение — **для показа**.
  ///
  /// Одно на приложение: две панели, показывающие одно имя по-разному, — это не
  /// гибкость, а недосмотр. Тот, кто спрашивает «что это за файл», берёт
  /// `extensionOf` и этой службы не касается.
  FileNaming get fileNaming;

  /// Чем рисуется содержимое панелей.
  PanelViewports get viewports;

  /// Объявленные провайдеры сведений, по убыванию приоритета.
  ///
  /// Списком, как и просмотрщики: спрашивает их окно сведений, а ядро только
  /// хранит и упорядочивает.
  List<NodeInfoProvider> get nodeInfoProviders;

  /// Объявленные просмотрщики, по убыванию приоритета.
  ///
  /// Список, а не «найди подходящий»: ядро складывает и упорядочивает, а
  /// спрашивает `accepts` тот, кто открывает, — оболочка просмотра. Решать за
  /// неё ядру нечем: про типы файлов оно не знает ничего.
  List<ViewerSpec> get viewers;

  /// Чем рисуются состояния: панель, просмотрщик, заявка от работы.
  ///
  /// Вид ищется по самому состоянию, а не по имени вида: связь между ними
  /// проверяет компилятор, и модуль, объявивший состояние, объявляет и вид.
  Views get views;

  /// Рабочая область: что где стоит и кому принадлежит ввод.
  ///
  /// Сами файловые панели — такое же содержимое области, как просмотрщик или
  /// результаты поиска: ядро не решает, чем показывать файлы.
  ApplicationView get view;

  void activate(Panel panel);

  /// Переключить активную панель.
  void toggleActivePanel();

  /// Доля ширины окна под левой панелью.
  double get splitRatio;

  void setSplitRatio(double value);

  /// Сколько каталогов обходится за раз при подсчёте размеров.
  ///
  /// Настройка ядра, а не модуля, — и потому у неё свой доступ, а не раздел.
  int get sizeScanConcurrency;

  void setSizeScanConcurrency(int value);

  /// Последняя известная геометрия окна.
  WindowGeometry? get windowGeometry;

  /// Содержимое объекта **по его пути** — мимо панелей и того, где они стоят.
  ///
  /// Отличается от `panel.contentOf` тем, кого спрашивают: панель отвечает о
  /// строке своего нынешнего списка, а здесь ядро разбирает путь заново — и
  /// откроет то, из чего читает, даже если панель ушла оттуда. Нужно тому, кто
  /// читает **после** жеста: перетаскиванию наружу.
  ///
  /// Разбор ведёт **корень дерева**, а не панель, и это не мелочь: путь,
  /// пришедший со стороны, к месту, где стоит панель, отношения не имеет. Тот
  /// разбор однажды уже соврал — `/Users/koldoon/note.txt`, разобранный
  /// панелью на сервере, искался **на сервере**.
  Content contentAt(FileEntry entry);

  /// Перетаскивание мышью; null — модуля нет, и мышью ничего не таскают.
  ///
  /// Необязательная возможность, поэтому и тип необязательный: панели
  /// спрашивают её перед тем, как объявить себя приёмником, и без неё работают
  /// ровно как раньше.
  DragAndDrop? get dragAndDrop;

  /// Само окно: подвинуть, развернуть.
  ///
  /// Нужно шеллу: системной полосы заголовка у окна нет, полосу рисует он, и
  /// жесты на ней доводить до окна — его дело.
  WindowService get window;

  /// Раздел настроек модуля. Имя — идентификатор модуля.
  SettingsScope moduleSettings(String namespace);

  /// Запуск: восстановление окна и каталогов.
  Future<void> start();

  /// Завершение: сохранение настроек и остановка операций.
  Future<void> shutdown();
}
