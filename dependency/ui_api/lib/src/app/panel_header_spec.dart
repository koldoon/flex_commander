import 'package:flutter/widgets.dart';

import 'session.dart';

/// Заголовок панели: чем показан адрес того, что в ней.
///
/// Спецификация — `docs/spec/panel-header.md`.
///
/// **Не то же, что `PanelViewSpec`**: там речь о том, как показан каталог —
/// таблицей, деревом, кратким списком, — а здесь о том, как показан его адрес.
/// И не то же, что `viewport`: тот отвечает на вопрос «что в панели», и решает
/// его источник.
///
/// Объявляется целиком не заголовок, а **содержимое плашки**: сама плашка со
/// слотом под стрелки истории и припиской справа остаётся панельной, иначе
/// каждый новый вид адреса начинался бы с того, что теряет стрелки (§2 спеки).
class PanelHeaderSpec {
  const PanelHeaderSpec({required this.id, required this.title, required this.build, this.description = ''});

  /// Устойчивое имя для настроек: `path`, `crumbs`.
  final String id;

  /// Название для человека — английское, оно же ключ перевода
  /// (`docs/spec/localization.md`, §3).
  final String title;

  /// Одна строка о том, чем этот заголовок отличается.
  final String description;

  /// Чем набрать адрес. Что именно набирать и сколько под это места, сказано
  /// доводом.
  final Widget Function(BuildContext context, PanelHeaderView view) build;
}

/// Всё, что заголовку нужно знать, чтобы себя нарисовать.
///
/// Значением, а не набором доводов: заголовков будет несколько, и добавить
/// сведение, не переписав их все, можно только так.
class PanelHeaderView {
  const PanelHeaderView({required this.panel, required this.text, required this.width, required this.style});

  /// Чей адрес показываем.
  final Session panel;

  /// Что показать: заголовок, выставленный командой, иначе путь сессии.
  ///
  /// Решает это панель, а не заголовок: `headerText` главнее пути
  /// (`docs/spec/panel-node-list.md`), и повторять это правило в каждом
  /// заголовке значит однажды повторить его неверно.
  final String text;

  /// Сколько места осталось под адрес — после слота и приписки.
  ///
  /// Считает его плашка: она же их и ставит. Пользоваться этой мерой заголовок
  /// не обязан — звенья сворачивают середину по-своему, — но спрашивать
  /// раскладку ему не нужно (§4 спеки).
  final double width;

  /// Чем набирать: цвет уже учитывает, активна ли панель.
  final TextStyle style;
}

/// Заголовки, объявленные модулями.
abstract interface class PanelHeaders {
  /// Все объявленные — в порядке объявления модулей.
  List<PanelHeaderSpec> get available;

  /// Заголовок по имени; null — такого не объявлял никто.
  ///
  /// Панель на этом не спотыкается: не нашла — показывает путь строкой, а имя
  /// из настроек не стирает (`docs/spec/panel-header.md`, §6).
  PanelHeaderSpec? byId(String id);
}
