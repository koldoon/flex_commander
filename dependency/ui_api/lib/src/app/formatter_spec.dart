import 'package:fc_api/fc_api.dart';

import 'content_types.dart';

/// Чем привести текст файла в читаемый вид.
///
/// Объявляет модуль, а спрашивают **два** экрана: показ текста рисует
/// отформатированную копию, редактор правит документ на месте. Ради этого
/// реестр и заведён — умение одно, работы разные, и знать друг о друге экранам
/// незачем (`docs/spec/formatters.md`, §2).
class FormatterSpec {
  const FormatterSpec({
    required this.id,
    required this.title,
    required this.accepts,
    required this.format,
    this.priority = 0,
  });

  /// Устойчивое имя: `json`, `xml`. Уходит в настройки и в отказы.
  final String id;

  /// Название для человека — «JSON». По-английски: это ключ перевода, русский
  /// приходит словарём модуля.
  final String title;

  /// Больше — раньше спрашивают. При равном — порядок объявления модулей.
  final int priority;

  /// Берётся ли за такой файл.
  ///
  /// Решение **по имени**, а разбор — в [format]: тот же раздел обязанностей,
  /// что у просмотрщиков. Иначе текст разбирается дважды — сперва чтобы
  /// ответить «моё ли», потом чтобы отформатировать.
  ///
  /// [type] — тип содержимого, **если он уже известен** экрану; спрашивать его
  /// ради ответа никто не станет: определение типа читает файл, а файл здесь
  /// уже прочитан.
  final bool Function(FileEntry entry, ContentType? type) accepts;

  /// Отформатировать.
  ///
  /// Чистая функция текста: ни файла, ни узла, ни состояния. Бросает
  /// [FormatException] с местом, если разобрать не вышло, — место увидит
  /// человек (§6).
  final String Function(String text) format;
}
