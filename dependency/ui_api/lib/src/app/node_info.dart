import 'package:fc_api/fc_api.dart';

import 'content_types.dart';
import 'viewer_spec.dart';

/// Строка сведений: подпись и значение.
///
/// Значение — уже строка: провайдер знает, как показать своё, лучше чем окно.
/// Размер в байтах покажет один, выдержку в долях секунды другой, и общего
/// правила для них нет.
class NodeInfoRow {
  const NodeInfoRow(this.label, this.value);

  final String label;
  final String value;
}

/// Раздел сведений: заголовок и строки под ним.
class NodeInfoSection {
  const NodeInfoSection({required this.title, required this.rows});

  final String title;
  final List<NodeInfoRow> rows;
}

/// Кто-то, кому есть что сказать об узле.
///
/// Окно сведений само не знает ничего: оно показывает и размечает, а
/// рассказывают провайдеры — объявленные модулями, как и просмотрщики. Поля
/// самой модели (имя, путь, даты, права) приходят таким же провайдером и
/// ничем не привилегированы.
/// Откуда об объекте узнают: байты и атрибуты.
///
/// Одна ручка вместо двух замыканий: провайдеру сведений бывает нужно и то и
/// другое, а спрашивать он умеет только у того, кому строка принадлежит, —
/// панели. Что там за границей, ему знать незачем.
///
/// Заводится под каждую строку: соседа по списку можно спросить, не выходя в
/// панель, — так листает альбом просмотрщик картинок.
abstract interface class NodeSource {
  /// Байты объекта — потоком. Открывается лениво: показ решает сам, читать ли
  /// ему и с какого места.
  Content get content;

  /// Атрибуты объекта: режим, даты, владелец, расширенные.
  ///
  /// Спрашиваются у источника **заново**, а не берутся из строки списка: там
  /// они с последнего чтения каталога.
  ///
  /// Источник, который о них не знает, отвечает [NodeAttributes.unknown];
  /// отказ приходит [FsError] — о нём и говорят, а не заменяют пустотой.
  Future<NodeAttributes> attributes();
}

abstract interface class NodeInfoProvider {
  /// Устойчивое имя: `basics`, `image`, `xattr`.
  String get id;

  /// Больше — выше в окне. При равном порядок объявления модулей.
  int get priority;

  /// Берётся ли за такой узел.
  ///
  /// Тот же вопрос и в том же виде, что у просмотрщика ([ViewerSpec.accepts]):
  /// два реестра рядом должны спрашиваться одинаково, иначе их придётся
  /// помнить по отдельности.
  ///
  /// От ответа зависит не только показ, но и смысл ошибки: не взялся — раздела
  /// нет вовсе; взялся и не смог — это **сведение о файле**, а не о
  /// приложении.
  bool accepts(FileEntry entry, ContentType? type);

  /// Что известно об узле. Пусто — сказать нечего, и раздела не будет.
  ///
  /// Исключение отсюда — законный ответ: «взялся и не смог». Оно доходит до
  /// человека строкой в разделе этого провайдера.
  Future<List<NodeInfoSection>> describe(FileEntry entry, NodeSource source);
}
