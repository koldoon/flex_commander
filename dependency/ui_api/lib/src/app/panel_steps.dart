/// Шаг курсора по месту: на сколько строк списка он сдвигается вбок и вниз.
///
/// Объявляет вид, читают команды. Команда не спрашивает «какой сейчас вид» —
/// она спрашивает «на сколько шагать» (`docs/spec/panel-view-icons.md`, §6).
///
/// **Одним значением, а не двумя полями.** Их всегда выставляют вместе, одной
/// строкой в сборке вида, и разъехаться им нельзя: вид, назвавший шаг вбок и
/// забывший шаг вниз, оставил бы вертикальные клавиши от прежней раскладки.
class PanelSteps {
  /// Обычный список: вбок ходить нечем, вниз — строка.
  ///
  /// Так живут таблица, дерево и находки: `Left` и `Right` достаются тому, кто
  /// объявлен следом, — началу и концу списка.
  const PanelSteps.list() : across = 0, down = 1;

  /// Раскладка столбцами (краткий вид): вбок — через весь столбец, вниз —
  /// строка.
  const PanelSteps.columns(this.across) : down = 1;

  /// Сетка (вид «Значки»): вбок — соседняя плитка, вниз — целый ряд.
  const PanelSteps.grid(this.down) : across = 1;

  /// Сколько строк списка вбок; 0 — вбок ходить нечем.
  final int across;

  /// Сколько строк списка вниз; 1 — обычная строка, и своей команды не нужно.
  final int down;

  @override
  bool operator ==(Object other) => other is PanelSteps && other.across == across && other.down == down;

  @override
  int get hashCode => Object.hash(across, down);

  @override
  String toString() => 'PanelSteps(across: $across, down: $down)';
}
