import 'session.dart';

/// Набор: то, что показывают в панели как одно
/// (`docs/spec/panel-sessions.md`, §2).
///
/// Сессия в нём одна, а у комбинированного вида две — дерево и список. Наборы
/// лежат одним списком на приложение, и **любой можно показать в любой
/// панели** — хоть в обеих сразу: сессия от этого не удваивается, а значит не
/// удваиваются ни соединение, ни распакованный архив.
///
/// Заводит, закрывает, показывает и называет наборы приложение
/// ([Application.openPanel] и соседние); ряд и окно выбора только рисуют.
abstract interface class Panel {
  /// Показанная сессия набора: ею он и представляется.
  Session get session;

  /// Все сессии набора, в порядке столбцов.
  List<Session> get sessions;

  /// Имя, данное человеком; пусто — набор зовётся по каталогу.
  String get name;
}
