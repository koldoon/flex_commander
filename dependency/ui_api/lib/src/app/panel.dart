import 'package:fc_api/fc_api.dart';
import 'package:fc_core_api/fc_core_api.dart';
import 'package:flutter/foundation.dart';

import 'panel_selection.dart';
import 'viewport.dart';

enum PanelStatus { idle, loading, error }

/// Панель файлового менеджера — то, чем оперируют команды.
///
/// Аналог `IPanel` референса: описывает, что панель умеет, но не то, как она
/// это делает и как себя рисует. Команды пишутся против этого интерфейса,
/// поэтому их не придётся трогать ни при смене реализации панели, ни при
/// появлении второй разновидности панели (дерево каталогов, результаты поиска).
///
/// [ViewportState] — часть контракта, а не украшение: панель это то, что стоит
/// в области, и достать её оттуда должен уметь модуль, который про модуль
/// панелей ничего не знает. Отсюда же следует, что результаты поиска и дерево
/// каталогов — обычные реализации [Panel], и всё, что работает с панелью,
/// работает и с ними.
///
/// [Listenable] приходит вместе с ним: панель уведомляет об изменениях, и
/// подписаться может любой, кому она досталась, — виджет ядра или содержимое,
/// нарисованное модулем.
abstract interface class Panel implements ViewportState {
  /// Откуда панель берёт содержимое **сейчас**.
  ///
  /// Меняется вместе с каталогом: войдя в архив, панель показывает его
  /// провайдера, а не тот, с которого начинала.
  TreeProvider get provider;

  /// Редактор дерева, если провайдер умеет изменять содержимое; иначе null —
  /// например, у архива, открытого только на просмотр. С него начинается
  /// любая файловая операция.
  ///
  /// Это движок переноса, а не сам провайдер: обход, конфликты и прогресс —
  /// общие для всех источников, провайдер даёт только примитивы ([NodeEditor]).
  /// Поэтому приёмник может оказаться из другого провайдера, и команду это
  /// не касается.
  TreeEditor? get editor;

  // --- каталог ---

  DirectoryNode? get directory;

  /// Отсортированное содержимое каталога.
  List<FsNode> get nodes;

  PanelStatus get status;

  FsError? get error;

  /// Идёт длительная операция.
  bool get busy;

  /// Панель активна: в ней курсор и ввод с клавиатуры.
  bool get active;

  /// Текст, выставленный командой; null — панель показывает объект под курсором.
  String? get statusText;

  void setStatusText(String? text);

  /// Чем рисуется содержимое панели сейчас.
  ///
  /// `files` — штатная таблица файлов. Провайдер, которому нужна другая
  /// картинка, объявляет свой вид ([PanelContent]), а модуль регистрирует то,
  /// чем этот вид рисуется.
  String get contentKind;

  /// Заголовок панели, выставленный командой; null — показывается путь
  /// текущего каталога.
  ///
  /// Нужен тому, кто заполняет панель не каталогом: результатам поиска, ветке
  /// соединения, списку закладок.
  String? get headerText;

  void setHeaderText(String? text);

  /// Открыть каталог. Отменяет незавершённое чтение этой же панели.
  Future<void> open(DirectoryNode dir);

  /// Открыть каталог по строке пути. false — путь недоступен или это не каталог.
  ///
  /// [allowConnect] — можно ли ради этого подключаться к источнику по адресу
  /// (`ssh://user@host/srv`). false нужен восстановлению состояния при запуске:
  /// сохранённый адрес означал бы обращение к сети на каждом запуске — вопрос
  /// о пароле поверх ещё не восстановленного окна, а с недоступным сервером
  /// ещё и ожидание до истечения времени подключения. Панель должна
  /// восстанавливаться мгновенно, а поход на сервер — быть отдельным
  /// решением человека. Сохранённый адрес в этом случае считается
  /// недоступным, и панель открывается там, где всегда.
  Future<bool> openPath(String path, {bool allowConnect = true});

  /// Стать ещё одним арендатором того источника, в котором панель стоит
  /// сейчас; null — это общий корень, и арендовать нечего.
  ///
  /// Нужно длительным работам: пока они идут, панель вправе уйти куда угодно —
  /// хоть выйти из архива, — а тот, из кого работа читает, обязан дожить до её
  /// конца. Отпускать полагается в `finally`.
  ProviderLease? leaseProvider();

  /// Разбор строки пути — через всю цепочку провайдеров, как это делает
  /// [openPath]. Нужен командам, которым путь задают параметром.
  ///
  /// Узел приходит **вместе с арендой** всего, что смонтировано ради него, и
  /// отпустить её обязан тот, кто просил: путь может пройти через архив,
  /// который ради него и откроют, а панель о нём ничего не знает.
  Operation<String, ResolvedNode> resolvePath();

  /// Войти в объект под курсором. Возвращает узел, в который войти нельзя
  /// (обычный файл); null, если переход выполнен.
  Future<FsNode?> enterCurrent();

  /// На уровень вверх; курсор встаёт на объект, через который вошли.
  Future<void> goUp();

  /// Перечитать текущий каталог, сохранив курсор и пометку.
  Future<void> reload();

  /// Прервать текущую операцию.
  void cancel();

  /// Выполнить работу от имени панели.
  ///
  /// Панель на это время становится занятой ([busy]): клавиатура ей больше не
  /// принадлежит — проходят только `Esc`, прерывающий работу, и `Tab`,
  /// уводящий на соседнюю панель. Ход дела панель показывает своей строкой
  /// состояния ([statusText]) — теми же вехами, какими показывает чтение
  /// каталога.
  ///
  /// Это для работы, которую человек **заказал явно** и от которой ждёт нового
  /// экрана: чтение файла на просмотр и на правку. Тому, что панель делает
  /// попутно, занятость не годится: обход размеров идёт фоном и мешать не
  /// должен, а у быстрого просмотра панели и вовсе нет — он ею и заменён.
  ///
  /// Результат возвращается вызывающему; отмена приходит [OperationCanceled],
  /// отказ источника — [FsError]. Панель их не толкует: сказать о неудаче —
  /// дело того, кто работу заказал. Содержимое панели при этом не трогается —
  /// список файлов виден всё время чтения.
  ///
  /// Принимает **тело**, а не готовую работу, ради цепочек: шагов у дела бывает
  /// несколько — спросить права, потом прочитать, — и все они должны быть
  /// одной занятостью и одной целью для `Esc`. Внутри тела вложенные работы
  /// заводятся через [TaskOperation.delegate]: ход дела они отдают наверх, а
  /// отмена идёт к ним встречно. Окно посреди тела — обычный `await`: работе до
  /// него дела нет.
  ///
  /// Тело захватывает то, что ему нужно, замыканием — в отличие от [Operation],
  /// которой полагается получать на вход одни данные. Разница не в небрежности:
  /// та доктрина бережёт **фоновые** работы, переживающие свою панель, а эта
  /// живёт ровно пока человек ждёт, и панель у неё та самая.
  Future<R> runWork<R>(Future<R> Function(TaskOperation<void, R> op) body, {String status});

  // --- курсор ---

  int get cursorIndex;

  FsNode? get currentNode;

  /// Сколько строк помещается в видимой части списка; от этого считается шаг
  /// PgUp/PgDn. Значение выставляет таблица.
  int get pageSize;

  set pageSize(int value);

  void moveCursor(int delta);

  void moveCursorPage(int direction);

  void setCursorIndex(int index);

  void setCursorToFirst();

  void setCursorToLast();

  void setCursorToName(String name);

  // --- пометка ---

  PanelSelection get selection;

  /// Суммарный размер помеченных объектов вместе с содержимым каталогов.
  ///
  /// Размер файлов известен сразу, каталоги обходятся фоном, поэтому значение
  /// растёт по ходу подсчёта.
  int get selectionSize;

  /// Подсчёт [selectionSize] закончен.
  bool get selectionSizeIsFinal;

  /// Инвертировать пометку объекта под курсором и сдвинуть курсор вниз.
  void toggleCurrentMark();

  void markAll();

  /// Посчитать размеры **всех** каталогов текущего каталога.
  ///
  /// Той же очередью, что и размер помеченного: пул обходов один, и посчитанное
  /// лежит в самих узлах — иначе помеченное и посчитанное показывали бы разные
  /// числа.
  ///
  /// Отличие от пометки одно, но существенное: попрошенное считается **до
  /// конца**, что бы дальше ни делали с пометкой. Иначе первое же нажатие
  /// `Space` отменяло бы весь подсчёт.
  void measureDirectories();

  // --- вид ---

  ColumnLayout get columns;

  void setColumnLayout(ColumnLayout layout);

  SortSpec get sort;

  /// Сортировка по колонке: та же колонка меняет направление.
  void sortBy(FsColumn column);

  bool get showHidden;

  Future<void> setShowHidden(bool value);

  /// Текущее состояние панели в виде сохраняемых настроек.
  PanelSettings get settings;
}
