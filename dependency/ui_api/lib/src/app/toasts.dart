import 'package:flutter/foundation.dart';

/// Короткое сообщение, которое показывается само и само же исчезает.
///
/// Для того, что случилось **и уже закончилось**: режим переключён, путь
/// скопирован, настройки перечитаны. О длительной работе рассказывает полоса
/// фоновых работ ([BackgroundTasks]), об ошибке, требующей решения, — окно
/// команды. Тост ничего не спрашивает и ничем не управляет: его можно не
/// заметить, и ничего не сломается.
@immutable
class Toast {
  const Toast({required this.id, required this.message, this.failed = false});

  /// Свой у каждого показа.
  ///
  /// Нужен тому, кто рисует: два одинаковых сообщения подряд — это два показа,
  /// и второй должен «моргнуть», а не остаться незамеченным. По тексту их не
  /// различить, а переключение скрытых файлов туда-обратно даёт именно такую
  /// пару.
  final int id;

  final String message;

  /// Сообщение об отказе: не вышло того, что просили.
  ///
  /// Красным, а не обычным: у остальных тостов новость нейтральная — «сделано»,
  /// — и одинаковый вид сделал бы отказ незаметным ровно там, где заметить его
  /// и нужно.
  final bool failed;

  @override
  String toString() => message;
}

/// Всплывающие сообщения приложения.
///
/// Показывается **одно, последнее**: сообщения короткие и не требуют ответа,
/// а очередь из них заставляла бы дочитывать историю вместо работы. Новое
/// сообщение заменяет предыдущее и заново заводит время показа.
abstract interface class Toasts implements Listenable {
  /// Сообщение, которое видно сейчас; null — не показывается ничего.
  Toast? get current;

  /// Показать сообщение. Само исчезнет — убирать не нужно.
  void show(String message);

  /// Сказать, что не вышло: то же сообщение, но красным.
  ///
  /// Отдельным вызовом, а не флагом у [show]: «сделано» и «не вышло» — разные
  /// новости, и место, которое их путает, легко проглядеть.
  ///
  /// Тостом, а не строкой в окне: сообщение внутри формы отъедает у неё место
  /// и двигает поля ровно тогда, когда в них собираются что-то поправить.
  void fail(String message);

  /// Убрать досрочно: пользователь щёлкнул по сообщению или ушёл из места,
  /// к которому оно относилось.
  void hide();
}
