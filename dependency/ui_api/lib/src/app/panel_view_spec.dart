import 'package:flutter/widgets.dart';

import 'session.dart';

/// Вид панели: чем показать каталог.
///
/// Спецификация — `docs/spec/panel-views.md`.
///
/// **Не то же, что `PanelViewports`**: там речь о том, **что** в панели —
/// каталог, находки, просмотрщик, — и решает это источник. Здесь о том, **как**
/// показан каталог, и решает это человек (§3).
///
/// Значение, а не служба: объявить вид — не значит распорядиться. Что из
/// объявленного показывать, решает панель по своей настройке.
class PanelViewSpec {
  const PanelViewSpec({
    required this.id,
    required this.title,
    required this.build,
    this.description = '',
    this.options,
    this.fillsFrame = false,
  });

  /// Устойчивое имя для настроек: `table`, `brief`, `tree`.
  final String id;

  /// Название для человека — английское, оно же ключ перевода
  /// (`docs/spec/localization.md`, §3).
  final String title;

  /// Одна строка о том, чем этот вид отличается: её читают в окне выбора.
  final String description;

  /// Чем рисовать. Тот же вид работает в любой панели: какая именно — сказано
  /// доводом.
  final Widget Function(BuildContext context, Session panel) build;

  /// Занимает ли вид раму целиком — вместе с местом под плашкой пути.
  ///
  /// Обычно под плашкой оставлено поле, и не зря: список начинается строкой, и
  /// накрывать её заголовком нельзя. Но вид, который **листается целиком** —
  /// сетка значков, — от этого только теряет: сверху остаётся полоса фона, а
  /// прокрутка упирается в неё вместо того, чтобы уводить содержимое под
  /// плашку. Такой вид сам отводит место сверху — тем же полем, только внутри
  /// прокрутки (`docs/spec/panel-views.md`, §3).
  final bool fillsFrame;

  /// Настройки **этого** вида — их показывает окно выбора под списком: сколько
  /// колонок, какого размера значки, показывать ли миниатюры.
  ///
  /// null — настраивать нечего, и места под них окно не отводит. Правки идут
  /// **в черновик** и применяются по «OK» (`docs/spec/panel-views.md`, §7):
  /// выбранный вид не обязан быть включённым, и трогать живьём то, что панель
  /// показывает сейчас, настройкам другого вида не за чем. Панель, для которой
  /// окно открыли, лежит в самом черновике: колонки таблицы у левой и правой
  /// свои, и «настройка вида» тут значит «настройка **этого** вида **этой**
  /// панели».
  final Widget Function(BuildContext context, ViewOptionsDraft draft)? options;
}

/// Черновик настроек вида: то, что окно выбора соберёт и применит по «OK».
///
/// Черновик один и принадлежит **выбранному** виду: ушёл курсор на другую
/// строку — окно заводит новый, а собранное прежним пропадает, потому что
/// включат теперь не его (`docs/spec/panel-views.md`, §7).
///
/// Значения окно не хранит: где они живут, знает только тот виджет, который их
/// показывает, — колонки в панели, столбцы краткого вида в разделе модуля.
/// Поэтому здесь лежит не значение, а дело: «вот что сделать, когда нажмут».
class ViewOptionsDraft {
  ViewOptionsDraft(this.panel);

  /// Панель, для которой открыли окно.
  final Session panel;

  VoidCallback? _apply;

  /// Собранного нет — применять нечего: окно открыли и ничего не тронули.
  bool get isEmpty => _apply == null;

  /// Объявить, что сделать по «OK». Последнее сказанное и применяется: виджет
  /// зовёт это на каждую правку, а применяется правка один раз.
  void onApply(VoidCallback apply) => _apply = apply;

  /// Применить собранное — **до** смены вида: у комбинированного вида столбец
  /// списка рождается клоном панели уже после неё
  /// (`docs/spec/panel-view-combined.md`, §7).
  void apply() => _apply?.call();
}

/// Виды панели, объявленные модулями.
abstract interface class PanelViews {
  /// Все объявленные виды в порядке объявления модулей.
  List<PanelViewSpec> get available;

  /// Вид по имени; null — такого не объявлял никто.
  ///
  /// Панель на этом не спотыкается: не нашла — рисует таблицей, а имя из
  /// настроек не стирает (`docs/spec/panel-views.md`, §6).
  PanelViewSpec? byId(String id);
}
