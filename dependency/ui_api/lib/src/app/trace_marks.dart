import 'package:flutter/foundation.dart';

/// Временная трассировка пометки — включается сборкой, а не настройкой.
///
/// Заведена ради одной беды: в дереве, если помечать удерживая `Space`,
/// помеченное начинает гаснуть. Причин нашлось три, и все три — про отставание
/// подтверждений (`docs/spec/client-server.md`, §5.5); проверками закрыты все,
/// но воспроизводится беда только живьём, на настоящем диске и настоящем порту.
/// Если повторится ещё раз — вот чем смотреть:
///
///     flutter run --dart-define=FC_TRACE_MARKS=true
///
/// Выключенная, она не стоит ничего: `const` условие выкидывает и вызов, и
/// строку целиком ещё при сборке. Постоянного журнала в приложении нет и не
/// заводится — это не он, а **щуп** под одну беду, которая на петле не
/// воспроизводится вовсе: там ядро отвечает в том же кадре.
///
/// Она себя уже оправдала: три захода по догадкам закрыли три настоящие щели,
/// но не ту, что мучила человека, — а трассировка показала причину с первого же
/// прогона. Поэтому и остаётся: расхождение сторон границы ловится только так.
const bool traceMarksEnabled = bool.fromEnvironment('FC_TRACE_MARKS');

/// Строка собирается **лениво**: выключенная трассировка не должна стоить даже
/// склейки.
void traceMarks(String Function() line) {
  if (traceMarksEnabled) {
    debugPrint('#marks ${line()}');
  }
}
