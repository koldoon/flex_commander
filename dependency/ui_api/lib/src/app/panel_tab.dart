import 'panel.dart';

/// Вкладка панели: то, что человек считает одной панелью.
///
/// Внутри у неё столбцы — сессии (`docs/spec/panel-tabs.md`, §3), — но снаружи
/// она представляется показанным: его каталог в заголовке, его пометка в целях
/// операций. Заводит, закрывает и показывает вкладки приложение
/// ([Application.openTab] и соседние), а ряд вкладок только рисует.
abstract interface class PanelTab {
  /// Показанный столбец: им вкладка и представляется.
  Panel get panel;

  /// Закреплённая: уход из неё открывает новую рядом.
  bool get pinned;
}
