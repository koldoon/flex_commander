import 'package:fc_api/fc_api.dart';
import 'package:flutter/foundation.dart';

import 'node_info.dart';
import 'viewport.dart';

/// Сессия — одно **место**, с которым работают: каталог, курсор, пометка, вид.
///
/// То, чем оперируют команды. Панель при этом — место на **экране**, где
/// сессию показывают; сессия живёт своей жизнью и переживает то, что её
/// перестали показывать: её каталог, её аренда источника, её распакованный
/// архив остаются при ней.
///
/// Аналог `IPanel` референса: описывает, что сессия умеет, но не то, как она
/// это делает и как рисуется. Команды пишутся против этого интерфейса, поэтому
/// их не придётся трогать ни при смене реализации, ни при появлении второй
/// разновидности содержимого — дерева каталогов, результатов поиска.
///
/// **Сессия говорит значениями.** Строка списка — это [FileEntry], а не узел:
/// дерево живёт в ядре, и сюда приезжает ровно то, чем строку рисуют и по чему
/// её называют обратно (`docs/spec/client-server.md`, §4). Всё, что сессия
/// показывает, — снимок последнего, о чём рассказало ядро.
///
/// [ViewportState] — часть контракта, а не украшение: показанная сессия это то,
/// что стоит в области, и достать её оттуда должен уметь модуль, который про
/// модуль панелей ничего не знает.
///
/// [Listenable] приходит вместе с ним: сессия уведомляет об изменениях, и
/// подписаться может любой, кому она досталась, — виджет ядра или содержимое,
/// нарисованное модулем.
/// Чем кончилось раскрытие вглубь.
class PanelExpansion {
  const PanelExpansion({required this.opened, required this.stopped});

  /// Сколько ветвей раскрылось (или свернулось).
  final int opened;

  /// Упёрлось в предел: дальше человек раскрывает сам.
  final bool stopped;
}

abstract interface class Session implements ViewportState {
  /// Личность сессии: по ней её знает ядро.
  PanelId get id;

  /// Откуда панель берёт содержимое **сейчас**: схема, умения, вид содержимого.
  ///
  /// Снимок, а не сам источник: панель показывает то, что ей прислали.
  /// Меняется вместе с каталогом — войдя в архив, панель отвечает о нём.
  SourceInfo get source;

  // --- где панель стоит ---

  /// Куда пойдёт операция — путь под курсором, а не то, что показано.
  ///
  /// У списка каталога это и есть показанный каталог; у дерева — каталог ветви
  /// под курсором; у находок — каталог найденного объекта. Панель показывает
  /// **список узлов**, и один каталог её содержимое больше не описывает
  /// (`docs/spec/panel-node-list.md`).
  String get currentPath;

  /// Имя показанного каталога — последнее звено пути.
  String get directoryName;

  /// Тот же каталог так, как его назовёт **сама оболочка**; пусто — выполнять
  /// здесь негде.
  ///
  /// На своей машине это [path] и есть. На `ssh://` путь панели — адрес, а
  /// оболочка стоит на сервере и про адреса не слышала. Приезжает готовым:
  /// как выглядит его путь, знает только сам источник.
  String get shellDirectory;

  /// Есть ли куда подниматься. У корня источника — нет.
  bool get canGoUp;

  /// Показать этой панелью находки работы — списком, смонтированным в ядре.
  ///
  /// Список находок — источник, а не выдумка окна: узлы в нём настоящие и
  /// принадлежат своим провайдерам, поэтому копирование, удаление, `F3` и `F4`
  /// работают над ними без единой правки. Живут они там же, где источники, —
  /// сюда приезжают строками, как всякий список.
  ///
  /// Возвращает `false`, если показывать нечего: работу забыли, или она ничего
  /// не нашла.
  Future<bool> showFound(String runId, {String title});

  /// Имена в каталоге по пути — не трогая того, что показано.
  ///
  /// Ровно для дополнения по `Tab`: строка спрашивает, что лежит рядом, а
  /// панель остаётся там, где стояла. Скрытые не отсеиваются — решает тот, кто
  /// спросил. `~` разбирает источник: домашний каталог у сервера свой.
  Future<List<FileEntry>> namesIn(String path);

  /// Строки вида — то, что панель показывает сейчас.
  ///
  /// Не «содержимое каталога»: строки собирает цепочка «источник → мапперы →
  /// сортировка → фильтры», и каталог там лишь частый случай источника
  /// (`docs/spec/panel-node-list.md`, §3).
  List<FileEntry> get entries;

  PanelPhase get phase;

  FsError? get error;

  /// Идёт длительная операция.
  bool get busy;

  /// Панель активна: в ней курсор и ввод с клавиатуры.
  bool get active;

  /// Текст, выставленный командой; null — панель показывает объект под курсором.
  String? get statusText;

  void setStatusText(String? text);

  /// Заголовок панели, выставленный командой; null — показывается путь текущего
  /// каталога.
  ///
  /// Нужен тому, кто заполняет панель не каталогом: результатам поиска, ветке
  /// соединения, списку закладок.
  String? get headerText;

  void setHeaderText(String? text);

  /// Показать каталог, **не открывая** его: курсор вида встал на объект, и
  /// каталог панели теперь тот, в котором объект лежит.
  ///
  /// Для видов со своей навигацией — дерева и будущих столбцов
  /// (`docs/spec/panel-views.md`, §4). Панель при этом не занята, пометка
  /// остаётся, а тот же каталог не перечитывается: за курсором вида идёт
  /// каталог, а не ожидание (`docs/spec/panel-view-tree.md`, §3).
  ///
  /// [name] — имя объекта под курсором вида: на него встаёт курсор панели, и
  /// без пометки он же цель `F5`.
  void follow(String directory, {String name});

  /// Открыть каталог по строке пути. false — путь недоступен или это не каталог.
  ///
  /// [allowConnect] — можно ли ради этого подключаться к источнику по адресу
  /// (`ssh://user@host/srv`). false нужен восстановлению состояния при запуске:
  /// сохранённый адрес означал бы обращение к сети на каждом запуске — вопрос
  /// о пароле поверх ещё не восстановленного окна, а с недоступным сервером
  /// ещё и ожидание до истечения времени подключения.
  Future<bool> openPath(String path, {bool allowConnect = true});

  /// Содержимое строки: байты, лежащие за границей.
  ///
  /// Открывается лениво — показ решает сам, читать ли ему и с какого места.
  /// Умеет ли источник отдавать байты вообще, говорит снимок
  /// (`SourceInfo.canStream`).
  Content contentOf(FileEntry entry);

  /// Откуда об этой строке узнают: байты и атрибуты одной ручкой.
  ///
  /// Нужна тем, кто о строке **рассказывает**, а не показывает её: провайдеру
  /// сведений бывает нужно и то и другое, и таскать за собой два замыкания он
  /// не должен.
  NodeSource sourceOf(FileEntry entry);

  /// Атрибуты строки: режим, даты, владелец, расширенные атрибуты.
  ///
  /// Спрашиваются **заново**, а не берутся из [FileEntry.attributes]: там
  /// режим с последнего чтения каталога, и править по нему значило бы вернуть
  /// файлу права, которых у него уже нет.
  ///
  /// Источник, который об атрибутах не знает ничего, отвечает
  /// [NodeAttributes.unknown]; отказ приходит [FsError] — о нём человеку
  /// говорят, а не заменяют пустыми полями.
  Future<NodeAttributes> readAttributes(FileEntry entry);

  /// Дадут ли записать в эту строку.
  ///
  /// Спрашивают до правки: узнать об отказе после часа работы значит остаться
  /// с текстом, который некуда деть.
  Future<bool> canWriteTo(FileEntry entry);

  /// Войти в строку списка: каталог, архив, ссылка на каталог.
  ///
  /// Возвращает то, во что войти нельзя (обычный файл), — им займётся команда;
  /// null, если переход выполнен.
  Future<FileEntry?> enter(FileEntry entry);

  /// Войти в объект под курсором.
  Future<FileEntry?> enterCurrent();

  /// На уровень вверх; курсор встаёт на объект, через который вошли.
  Future<void> goUp();

  /// Перечитать текущий каталог, сохранив курсор и пометку.
  Future<void> reload();

  /// Прервать текущую операцию.
  void cancel();

  // --- курсор ---

  int get cursorIndex;

  FileEntry? get currentEntry;

  /// Сколько строк помещается в видимой части списка; от этого считается шаг
  /// PgUp/PgDn. Значение выставляет таблица.
  ///
  /// Остаётся на этой стороне и через границу не едет: шаг страницей — про
  /// показ, а список у этой стороны на руках.
  int get pageSize;

  set pageSize(int value);

  /// Сколько строк в столбце, если вид раскладывает список столбцами;
  /// `0` — столбцов нет вовсе.
  ///
  /// Выставляет вид, читает команда хода по столбцам: она не спрашивает «какой
  /// сейчас вид», она спрашивает «есть ли тут столбцы»
  /// (`docs/spec/panel-view-brief.md`, §6).
  int get columnRows;

  set columnRows(int value);

  void moveCursor(int delta);

  void moveCursorPage(int direction);

  void setCursorIndex(int index);

  void setCursorToFirst();

  void setCursorToLast();

  void setCursorToName(String name);

  // --- пометка ---

  /// Помеченное — путями объектов, в порядке пометки.
  ///
  /// Путями, а не местами в списке: список перечитывают, и связывать пометку с
  /// местом в нём значило бы терять её на каждом обновлении каталога. И не
  /// именами: в дереве видно несколько каталогов разом, а имя опознаёт объект
  /// только внутри одного (`docs/spec/panel-view-tree.md`, §7).
  Set<String> get markedPaths;

  bool isMarked(FileEntry entry);

  /// Заменить пометку целиком.
  void setMarks(Set<String> paths);

  void mark(FileEntry entry);

  void unmark(FileEntry entry);

  void markAll();

  void clearMarks();

  /// Помеченное, а если не помечено ничего — объект под курсором, **строками
  /// этого списка**.
  ///
  /// То, что видно и нарисовано: строку рисуют, тянут мышью, показывают в
  /// списке — для всего этого нужен видимый объект. Помеченного в других
  /// каталогах здесь нет: значений чужих строк у этой стороны не бывает вовсе.
  /// За полными целями — [allTargets] (`docs/spec/operation-targets.md`, §4).
  List<FileEntry> get targets;

  /// Пути всех целей: пометка, а без пометки — строка под курсором.
  ///
  /// Не врёт никогда: пути помеченного приезжают полностью, где бы оно ни
  /// лежало. Отсюда и счёт в заголовках окон — без обращения к ядру. Псевдострока
  /// «..» целью не бывает: пути у неё нет.
  Set<String> get targetPaths;

  /// Есть ли над чем работать.
  ///
  /// Правило «..» целью не бывает живёт здесь, а не в каждой команде: шесть
  /// одинаковых проверок однажды разошлись бы (`docs/spec/operation-targets.md`, §4).
  bool get hasTargets;

  /// Цели значениями — **все**, включая помеченное в других каталогах.
  ///
  /// Просьбой к ядру: значения чужих строк живут там. Спрашивают их те, кому
  /// мало пути, — окно «откуда», окно сведений, перечитывание задетых каталогов.
  /// Снимок на момент вопроса; заголовки и проверки на него не опираются, чтобы
  /// окно вставало сразу (`docs/spec/operation-targets.md`, §2).
  Future<List<FileEntry>> allTargets();

  /// Посчитанный размер каталога по пути; null — не посчитан.
  ///
  /// Числа приезжают **в строках** (`FileEntry.size`), а этот вопрос остаётся
  /// для тех, кому нужен размер пути, которого в строках нет.
  int? sizeOf(String path);

  /// Инвертировать пометку объекта под курсором и сдвинуть курсор вниз.
  /// Инвертировать пометку объекта под курсором.
  ///
  /// [step] — сдвинуть ли курсор вниз следом: так несколько файлов подряд
  /// помечаются одной клавишей. Пометка на месте (`Shift-Space`) не сдвигает.
  void toggleCurrentMark({bool step = true});

  /// Суммарный размер помеченных объектов вместе с содержимым каталогов.
  ///
  /// Размер файлов известен сразу, каталоги обходятся фоном, поэтому значение
  /// растёт по ходу подсчёта.
  int get markedSize;

  /// Подсчёт [markedSize] закончен.
  bool get markedSizeIsFinal;

  /// Посчитать размеры **всех** каталогов текущего каталога.
  ///
  /// Отличие от пометки одно, но существенное: попрошенное считается **до
  /// конца**, что бы дальше ни делали с пометкой.
  void measureDirectories();

  // --- вид ---

  /// Разложены ли строки правилом [sort].
  ///
  /// false — порядок источника: находки идут так, как их нашли. Смотрит на это
  /// заголовок: каретка над колонкой обещала бы порядок, которого нет
  /// (`docs/spec/file-search.md`, §4).
  bool get sorted;

  ColumnLayout get columns;

  void setColumnLayout(ColumnLayout layout);

  /// Чем набираются строки: содержимое каталога или дерево.
  ///
  /// Говорит это **вид** ([showRows]): ядро не знает ни одного вида по имени,
  /// оно знает набор строк (`docs/spec/panel-node-list.md`, §3).
  RowsKind get rows;

  /// Попросить набор строк — вид говорит это, когда встаёт.
  Future<void> showRows(RowsKind kind);

  /// Насколько список был промотан в прошлый запуск.
  ///
  /// Положение, а не настройка: вид начинает с него, а не подматывает к
  /// курсору заново (`docs/spec/panel-view-tree.md`, §5).
  double get scrollOffset;

  /// Запомнить прокрутку — вид говорит это, когда она устоялась.
  void setScrollOffset(double offset);

  /// Раскрыть или свернуть ветвь по пути.
  ///
  /// Путём, а не строкой: строки живут путями, а узлы после чтения другие.
  /// Раскрыть или свернуть ветвь по пути — на один шаг.
  void setExpanded(String path, {required bool expanded});

  /// Сходить по ссылке: курсор встаёт на то, куда она ведёт.
  ///
  /// false — идти некуда: строка не ссылка или ссылка битая. В дереве ссылку не
  /// раскрывают — она увела бы в цикл, — а сходить по ней можно
  /// (`docs/spec/panel-view-tree.md`, §4а).
  Future<bool> followLink(String path);

  /// То же **вместе со всем, что под ней**; пустой путь значит всё дерево.
  ///
  /// С ответом: раскрытие читает по дороге и упирается в предел, а сказать об
  /// этом надо тому, кто просил, — тостом, один раз
  /// (`docs/spec/panel-view-tree.md`, §6а).
  Future<PanelExpansion> expandDeep(String path, {required bool expanded});

  SortSpec get sort;

  /// Сортировка по колонке: та же колонка меняет направление.
  void sortBy(FsColumn column);

  bool get showHidden;

  Future<void> setShowHidden(bool value);

  /// Чем панель показывает каталог: имя вида из объявленных модулями.
  ///
  /// Выбор человека и настройка **этой** панели. Что показано — каталог,
  /// находки, просмотрщик — говорит `source.contentKind`, и оно главнее
  /// (`docs/spec/panel-views.md`, §3).
  String get view;

  Future<void> setView(String view);

  /// Выполнить работу от имени панели.
  ///
  /// Панель на это время становится занятой ([busy]): клавиатура ей больше не
  /// принадлежит — проходят только `Esc`, прерывающий работу, и `Tab`,
  /// уводящий на соседнюю панель. Ход дела панель показывает своей строкой
  /// состояния.
  ///
  /// Это для работы, которую человек **заказал явно** и от которой ждёт нового
  /// экрана: чтение файла на просмотр и на правку.
  Future<R> runWork<R>(Future<R> Function(TaskOperation<void, R> op) body, {String? status});
}
