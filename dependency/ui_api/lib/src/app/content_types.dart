import 'package:fc_api/fc_api.dart';

/// Семья, к которой относится тип, — грубее самого типа.
///
/// Нужна тому, кто пишет правило: «любой картинке — иконку картинки» одной
/// строкой вместо перечисления девяти форматов. Перечислением, а не строкой:
/// набор закрыт, и опечатка в нём должна ловиться компилятором.
enum ContentGroup {
  image,
  archive,
  executable,
  document,
  audio,
  video,
  font,

  /// Текст любого рода: разбор кодировки — дело того, кто его покажет.
  text,

  /// Ничего не совпало. Это **ответ**, а не его отсутствие: «не знаем, что
  /// это» и «ещё не смотрели» — разные состояния, и путать их нельзя, иначе
  /// неизвестное перечитывалось бы вечно.
  binary,
}

/// Что за файл — по его первым байтам, а не по имени.
class ContentType {
  const ContentType(this.id, {required this.title, required this.group});

  /// Устойчивое имя: по нему пишутся правила иконок, и менять его нельзя.
  final String id;

  /// Название для человека: `PNG image`, `Zip archive`.
  final String title;

  final ContentGroup group;

  /// Равенство по имени: тип — это значение, а не экземпляр таблицы.
  @override
  bool operator ==(Object other) => other is ContentType && other.id == id;

  @override
  int get hashCode => id.hashCode;

  @override
  String toString() => 'ContentType($id)';
}

/// Чем узнают, что за файл перед нами.
///
/// Служба **экранная**: тип нужен показу — иконке, колонке, окну сведений, — а
/// ядру он не нужен ни для чего. Байты через границу уже ходят
/// (`Panel.contentOf` → [Content]), и второго пути к ним заводить незачем
/// (`docs/spec/content-types.md`, §3).
abstract interface class ContentTypes {
  /// Известный тип или null — ещё не смотрели.
  ///
  /// Спрашивается на каждой перерисовке строки и потому обязана быть дешёвой:
  /// это чтение из кэша, а не начало работы.
  ContentType? known(FileEntry entry);

  /// Определить: читает начало файла.
  ///
  /// [open] даёт байты и зовётся, только если дело дошло до чтения. Кто
  /// спрашивает, тот и знает, у кого спрашивать: строка списка принадлежит
  /// панели, и байты у неё берутся `panel.contentOf` — не `app.contentAt`,
  /// который разбирает путь заново корнем дерева
  /// (`docs/spec/content-types.md`, §5).
  ///
  /// [stillWanted] спрашивают перед самым чтением: строка, уехавшая с экрана,
  /// пока запрос стоял в очереди, читаться не должна. Ответ в этом случае —
  /// null, и ничего не запоминается.
  ///
  /// Повторный вопрос про то же самое отдаёт то же обещание, а не открывает
  /// файл второй раз.
  Future<ContentType?> detect(FileEntry entry, Content Function() open, {bool Function()? stillWanted});
}
