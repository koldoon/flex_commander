import 'package:flutter/painting.dart';

/// Цвета приложения по ролям, а не по названиям.
///
/// Здесь только роли: что именно красится этим цветом. Сами значения приносит
/// тема — API не решает, как приложению выглядеть, он лишь называет места,
/// которые нужно покрасить. Оформление по умолчанию живёт в модуле
/// `fc_default_theme`.
///
/// Тема, правящая немногое, наследуется от него и переопределяет нужное; тема,
/// пишущая своё целиком, наследуется **отсюда**. Разница в том, что случится с
/// забытой ролью: в первом случае она молча достанется чужому оформлению, во
/// втором её потребует компилятор (`docs/spec/macos-themes.md`, §4).
abstract class FcColors {
  const FcColors();

  /// Фон окна.
  Color get windowBackground;

  // --- панель ---

  /// Панель поверх фона окна: белый с прозрачностью 5%.
  Color get panelBackground;

  /// Обводка панели и линейки внутри неё: белый 15%.
  Color get panelBorder;

  /// Вертикальные линейки между колонками и линия над строкой состояния.
  Color get columnDivider;

  // --- список файлов ---

  Color get rowText;

  /// Каталоги и файлы в референсе одного цвета: тип виден по иконке.
  Color get directoryText;

  Color get sizeText;

  Color get secondaryText;

  Color get headerText;

  /// Курсор рисуется только в активной панели.
  Color get cursorBackground;

  Color get cursorText;

  /// Помеченная строка: подсветка фона (белый 8%) и полоса у левого края.
  Color get markedBackground;

  Color get markedBar;

  /// Погасшая ячейка метки «где показан набор» — на плашке набора в полосе
  /// заголовка (`docs/spec/panel-sessions.md`, §14).
  ///
  /// Горящая ячейка — [markedBar]; погасшая — она же, высветленная к белому
  /// и непрозрачная. Прозрачная тень того же цвета на синей плашке серела:
  /// оранжевый и синий гасят друг друга. Нужна светлая, но заметно отличная
  /// от горящей — тогда пара читается как две панели.
  ///
  /// С умолчанием: тема, написанная до этой роли, обязана продолжать работать.
  Color get sideMarkOff => Color.lerp(markedBar, const Color(0xFFFFFFFF), 0.6)!;

  /// Иконка типа объекта приглушена (`alpha="0.6"` у `iconLabel`).
  Color get icon;

  Color get iconSelected;

  // --- плашка пути ---

  Color get pathBackground;

  Color get pathBorder;

  Color get pathText;

  /// Пассивная панель в референсе плашкой не отличалась, но панелей две и
  /// понимать, какая из них принимает клавиши, нужно: у пассивной плашка
  /// приглушена.
  /// Промежуточные крошки пути на плашке активной панели.
  ///
  /// Своя роль, а не [secondaryText]: та принадлежит **списку файлов** и
  /// подобрана к его фону. Пока плашка была тёмно-синей, как и панель, разницы
  /// не возникало; у оформления, где плашка залита акцентом, вторичная подпись
  /// списка оказывается на ней чужой — вплоть до чёрного по синему.
  ///
  /// С умолчанием, а не обязательная: тема, написанная до разделения, продолжает
  /// красить крошки тем же, чем красила.
  Color get pathSecondaryText => secondaryText;

  Color get pathInactiveBackground;

  Color get pathInactiveText;

  // --- нижняя панель ---

  Color get functionButtonBackground;

  Color get functionButtonText;

  Color get functionKeyNumber;

  // --- окна команд ---

  Color get dialogBackground;

  Color get dialogTitleBackground;

  Color get dialogTitleText;

  /// Заголовок раздела в тексте — справка, настройки, документы.
  ///
  /// Своя роль, а не [dialogTitleText]: тот рассчитан на полосу заголовка окна,
  /// а раздел стоит на фоне содержимого. По умолчанию они совпадают.
  Color get headingText => dialogTitleText;

  /// Полосы спектра в просмотре звука (`docs/spec/audio-viewer.md`, §7).
  ///
  /// Своя роль, хоть по умолчанию и акцент: так решено с пользователем, а
  /// перекрасить спектр, не трогая кнопок, должно быть можно.
  Color get spectrumBar => buttonPrimaryBackground;

  /// Заливка кнопки полосы заголовка под указателем — акцент, как у кнопки
  /// подтверждения.
  Color get dialogTitleButtonHover => buttonPrimaryBackground;

  /// Значок на этой заливке — подписью кнопки подтверждения: заливка та же.
  Color get dialogTitleButtonHoverText => buttonPrimaryText;

  Color get dialogLabel;

  Color get dialogText;

  /// Затемнение под окном команды.
  Color get dialogBarrier;

  /// Область списка внутри окна команды: находки поиска.
  ///
  /// **Не панельные роли, хотя список тот же.** Панель стоит на фоне окна
  /// приложения, а список — в окне команды, у которого фон свой и посветлее;
  /// цвет, подобранный под первый, ко второму не идёт. И не поле ввода: в нём
  /// набирают, а здесь ходят курсором по файлам.
  ///
  /// С умолчанием, а не обязательные: тема, написанная до появления окна
  /// находок, обязана продолжать работать, и поле ввода — разумное «то же
  /// самое».
  Color get dialogListBackground => inputBackground;

  Color get dialogListBorder => inputBorder;

  /// Строка заголовков таблицы на плашке — «Было | Станет» группового
  /// переименования.
  ///
  /// Темнее самой плашки, чтобы заголовки читались шапкой, а не первой строкой
  /// данных: линеек между строками у такой таблицы нет. По умолчанию — плашка,
  /// **положенная на фон окна** (у оформлений macOS она полупрозрачная, и
  /// затемнять её саму значило бы затемнять и то, что под ней), под чёрным: в
  /// тёмном оформлении на четверть — меньше шаг не виден, в светлом на 6 % —
  /// больше шапка становится серой полосой.
  Color get dialogListHeaderBackground => _shadedPlate(dialogListBackground, dialogBackground);

  // --- кнопки окна команды ---

  Color get buttonBackground;

  /// Кнопка подтверждения (`s|Button.default`).
  Color get buttonPrimaryBackground;

  Color get buttonText;

  /// Подпись кнопки подтверждения.
  ///
  /// Своя роль, а не [buttonText]: заливки у двух кнопок разные, и подпись
  /// обязана следовать за своей. Пока обе заливки тёмные, одного цвета хватало —
  /// но у оформления, где обычная кнопка белая, а подтверждающая залита
  /// акцентом, читаемой подписи на обеих одним цветом не бывает.
  ///
  /// С умолчанием, а не обязательная: тема, написанная до этого разделения,
  /// обязана продолжать работать, и подпись обычной кнопки — то самое «то же
  /// самое», которым она и была.
  Color get buttonPrimaryText => buttonText;

  /// Тонкая обводка кнопок: чёрный 4%.
  Color get buttonBorder;

  /// Затемнение нажатой кнопки: чёрный 20%.
  Color get buttonPressed;

  // --- поле ввода ---

  Color get inputBackground;

  Color get inputBorder;

  Color get inputText;

  Color get inputHint;

  /// Выделение текста в поле ввода (`focusedTextSelectionColor`).
  Color get inputSelection;

  /// Обводка того, что сейчас в фокусе: поля, флажка, кнопки.
  ///
  /// Обводка, а не подсветка фона: фон уже занят — у поля свой, у кнопки заливка
  /// скина, у нажатой затемнение. Обводка ложится поверх любого из них и ничего
  /// не перекрашивает.
  ///
  /// С умолчанием, а не обязательная: тема, написанная до появления фокуса,
  /// обязана продолжать работать, и рамка поля — разумное «то же самое».
  Color get focusRing => inputBorder;

  /// Тень под кнопкой, полосой заголовка и самим окном: чёрный 25 %
  /// (`DropShadowFilter alpha="0.25"`).
  Color get shadow;

  /// Тень под встроенным элементом: кнопкой, полем цвета, флажком.
  ///
  /// Своя роль, а не [shadow]: тень отделяет **плавающее** — окно, подсказку,
  /// всплывающее сообщение, — а кнопка никуда не всплывает, она лежит в форме.
  /// Пока оформление тёмное, разница незаметна: тень на тёмном почти не видна
  /// обеим. На светлом она видна обеим, и элементу она не нужна вовсе —
  /// у него есть заливка, отличная от подложки.
  ///
  /// С умолчанием, а не обязательная: тема, написанная до разделения, продолжает
  /// работать с одной тенью на всё.
  Color get controlShadow => shadow;

  /// Тень под миниатюрой файла — плотнее оконной.
  ///
  /// Снята с собственного значка macOS: система рисует под бумагой документа
  /// чистый чёрный, и у самого края он виден на треть с лишним
  /// (`docs/spec/file-thumbnails.md`, §9). Оконной четверти для этого мало:
  /// миниатюра лежит на фоне панели, а не поверх окна, и подложка под ней
  /// должна читаться так же, как под системным значком рядом.
  ///
  /// С умолчанием: тема, написанная до этой роли, обязана продолжать работать.
  Color get iconShadow => shadow;

  // --- подсветка синтаксиса ---
  //
  // Роли, а не готовая тема подсветки: цвет решает оформление приложения, а не
  // библиотека, которой его разбирают. Ролей нарочно немного — просмотрщик не
  // редактор, и различать сорок видов токенов в нём незачем; всё, что не
  // названо здесь, рисуется обычным цветом строки.

  /// Ключевые слова языка: `if`, `class`, `return`.
  Color get syntaxKeyword;

  /// Строковые литералы вместе с кавычками.
  Color get syntaxString;

  /// Числа.
  Color get syntaxNumber;

  /// Комментарии.
  Color get syntaxComment;

  /// Имена типов, классов и функций в объявлениях.
  Color get syntaxType;

  /// Готовые значения языка: `true`, `null`, встроенные имена.
  Color get syntaxLiteral;

  /// То, что стоит вокруг кода: аннотации, директивы, заголовки разделов.
  Color get syntaxMeta;

  // --- терминал ---
  //
  // Цвета, которыми программа красит **свой** вывод. Живут в теме по той же
  // причине, что и всё остальное: одно и то же приглашение показывают два
  // места — развёрнутый терминал и строка команд под панелями, — и разойтись
  // им нельзя (`docs/spec/shell-prompt.md`, §5).

  /// Шестнадцать цветов ANSI по номерам: 0–7 обычные, 8–15 яркие.
  ///
  /// Списком, а не ролями: у этих цветов роли в интерфейсе нет вовсе, у них
  /// есть **номер** — программа просит «цвет 4», а не «цвет ошибки». Порядок
  /// тот же, что у терминала: чёрный, красный, зелёный, жёлтый, синий,
  /// пурпурный, голубой, белый — и те же восемь яркими.
  List<Color> get terminalAnsi;

  /// Чем набран вывод, не назвавший своего цвета.
  Color get terminalText;

  /// Курсор в развёрнутом терминале.
  Color get terminalCursor;

  /// Выделенное мышью в развёрнутом терминале.
  Color get terminalSelection;

  // --- прочее ---

  /// Полоса хода работы: обводка и заливка одного цвета.
  Color get progress;

  Color get error;
}

/// Плашка на фоне окна, затемнённая под шапку таблицы
/// ([FcColors.dialogListHeaderBackground]).
Color _shadedPlate(Color plate, Color ground) {
  final flat = Color.alphaBlend(plate, ground);
  final shade = flat.computeLuminance() > 0.5 ? 0x0F : 0x40;
  return Color.alphaBlend(Color.fromARGB(shade, 0, 0, 0), flat);
}
