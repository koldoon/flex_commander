/// Шрифты темы по ролям.
///
/// Интерфейс приложения набирается обычным шрифтом, код и терминал —
/// моноширинным, список файлов — своим, по умолчанию тем же моноширинным, чтобы
/// имена, размеры и даты стояли ровными столбцами. Какими именно — решает тема.
abstract class FcFonts {
  const FcFonts();

  /// Шрифт интерфейса: заголовки, подписи, кнопки, окна команд.
  String get ui;

  /// Моноширинный шрифт: врезки кода в markdown, терминал, командная строка,
  /// просмотрщик и редактор текста.
  ///
  /// Им моноширинный нужен по существу — код без него не читается, терминал не
  /// работает, — и выбор шрифта панелей до них не доходит: у списка файлов
  /// своя роль, [list] (`docs/spec/list-font.md`).
  String get fixed;

  /// Шрифт списка файлов: строки панелей во всех видах, дерево каталогов в
  /// окнах выбора файла.
  ///
  /// Любой, не обязательно моноширинный: столбцы размеров и дат держат
  /// табличные цифры набора (`FcTheme.listStyle`). По умолчанию — [fixed]:
  /// тема, не назвавшая шрифт списка, выглядит как раньше.
  String get list => fixed;

  /// Чем набрать список, если [fixed] в системе не стоит.
  ///
  /// Роль отдельная, потому что [fixed] может быть **не свой**: тема вправе
  /// назвать шрифт, который приложение с собой не возит, и тогда на чужой
  /// машине его может не оказаться. Без запасного списка подстановку делает
  /// система, а она берёт свой обычный шрифт — пропорциональный, и столбцы
  /// размеров и дат перестают стоять столбцами.
  ///
  /// Пустой список — «подставляй что хочешь»: тема со своим шрифтом в ресурсах
  /// в запасе не нуждается.
  List<String> get fixedFallback;
}
