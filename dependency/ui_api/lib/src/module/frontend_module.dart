/// Экранная половина модуля: то, что живёт там, где рисуют.
///
/// Источника у этой стороны нет, и объявить здесь провайдер невозможно — таких
/// методов у [FrontendRegistry] попросту не существует. Модуль, которому нужно
/// и то и другое, реализует ещё и `FcBackendModule`, но **другим классом и в
/// другой библиотеке** (`docs/spec/client-server.md`, §8).
abstract interface class FcFrontendModule implements FcModule {
  /// Объявление того, что модуль даёт интерфейсу.
  ///
  /// Зовётся один раз при сборке интерфейса — **до** того, как появится
  /// [Application]. Здесь только объявления: никакой работы, никаких обращений
  /// к другим службам. Работа, которую нужно сделать при запуске, — это
  /// стартовая команда ([FrontendRegistry.startup]).
  void installFrontend(FrontendRegistry registry);
}

/// Куда экранная половина модуля складывает то, что предлагает.
///
/// Только запись: реестр объявлений существует ровно на время сборки. Читать
/// зависимости здесь нельзя — их ещё нет; для этого фабрикам приходит
/// [FcServices], а командам — [FcContext].
abstract interface class FrontendRegistry {
  /// Службы интерфейса.
  ///
  /// Обращаться к ним можно **только из фабрик**: во время
  /// [FcFrontendModule.installFrontend] их ещё нет, а к моменту, когда фабрику
  /// позовут, — уже есть.
  FcServices get services;

  /// Раздел настроек этого модуля — под его же именем.
  ///
  /// Как и службы, читается не во время объявления, а позже: настройки к тому
  /// моменту уже прочитаны. Обычное место для этого — стартовая команда
  /// ([startup]).
  SettingsScope get settings;

  /// Действие приложения. Фабрика зовётся на каждый запуск: команда хранит
  /// состояние исполнения, поэтому экземпляр у запуска свой.
  void command(FcCommandFactory factory);

  /// Клавиша за действием.
  ///
  /// Порядок задаёт приоритет: раньше объявленная привязка выигрывает.
  /// Модули устанавливаются в порядке списка, привязки — в порядке вызовов.
  void binding(KeyBinding binding);

  /// Команда, которую интерфейс выполняет один раз при запуске — после сборки
  /// приложения и до первого кадра.
  ///
  /// Так модуль делает то, что нельзя сделать в
  /// [FcFrontendModule.installFrontend]: прочитать свои настройки, восстановить
  /// прошлое состояние, подписаться. Ошибка стартовой команды не роняет запуск.
  void startup(FcCommandFactory factory);

  /// Оформление.
  void theme(FcThemeSpec spec);

  /// Чем рисовать содержимое панели для источников, объявивших этот вид.
  void viewport(String kind, PanelViewportBuilder builder);

  /// Провайдер сведений об узле: что этот модуль знает о файле.
  ///
  /// Окно сведений собирается из объявленного точно так же, как показ — из
  /// объявленных просмотрщиков: ядро складывает, порядок задаёт приоритет, а
  /// что показать, решает не оно.
  void nodeInfo(NodeInfoProvider Function(FcContext context) factory);

  /// Просмотрщик: чем и для каких файлов открывать `F3`.
  ///
  /// Объявляет модуль, а выбирает оболочка просмотра — по убыванию приоритета.
  void viewer(ViewerSpec spec);

  /// Чем рисовать состояние типа [S].
  ///
  /// Ключ — точный тип: связь «состояние ↔ вид» проверяет компилятор. Два вида
  /// на один тип — ошибка сборки, а не тихая победа последнего.
  void view<S extends Object>(StateViewBuilder<S> builder);

  /// Из чего состоит раздел настроек этого модуля — чтобы ядро нарисовало
  /// окно настроек.
  ///
  /// Фабрика, а не готовая схема: во время объявления настройки ещё не
  /// прочитаны, и строить её тогда нечем. Зовётся, когда окно открывают.
  void settingsSchema(SettingsSchema Function() factory);

  /// Служба для интерфейса и других модулей: разрешается по типу через
  /// [FcServices].
  void service<T extends Object>(T Function(FcServices services) factory);
}

/// Что можно спросить во время работы. Приходит фабрикам команд.
///
/// Отдельный тип, а не флаг: до сборки приложения [app] не существует, и
/// обращение к нему из фабрики службы должно быть невозможно, а не
/// «нежелательно».
abstract interface class FcContext implements FcServices {
  Application get app;
}

/// Как создать действие модуля.
///
/// Не путать с [AppCommandFactory] реестра: та не принимает ничего и живёт уже
/// внутри собранного приложения. Модуль же пишет фабрику, которой нужны
/// зависимости, — их и приносит [FcContext].
typedef FcCommandFactory = AppCommand Function(FcContext context);
