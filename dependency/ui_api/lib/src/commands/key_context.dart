/// Где живёт привязка: в каком разделе окна настройки клавиш она стоит и с кем
/// спорит за нажатие (`docs/spec/key-bindings.md`, §2).
///
/// **Не задан — привязка внутренняя.** В окне её нет, и переназначить её
/// нельзя: ходьба курсором, `Enter` на применение, `Esc` на закрытие и отмену,
/// набор буквами для быстрого поиска — это общее поведение, а не выбор.
/// Переназначь такое, и приложение перестанет вести себя как приложение.
///
/// Контекст **не заменяет** `KeyBinding.inContent`: действует ли привязка
/// сейчас, по-прежнему решает замыкание — типы экранов объявлены в модулях, и
/// ядру они неизвестны. Перечисление отвечает на два других вопроса: в каком
/// разделе строка стоит и с кем она спорит. Спор сравнивается **по значению**,
/// а не тождеством замыкания: `KeyBinding.inState<S>` создаёт новое замыкание
/// на каждый вызов, и спор двух привязок просмотрщика иначе не обнаружить.
enum KeyContext {
  panel('File panels'),
  textViewer('Text viewer'),
  imageViewer('Image viewer'),
  editor('Text editor'),
  commandLine('Command line'),

  /// Клавиша принадлежит приложению целиком и отнимает нажатие у всех
  /// остальных контекстов — поэтому спорит с каждым из них.
  everywhere('Everywhere');

  const KeyContext(this.title);

  /// Заголовок раздела — по-английски, как все строки интерфейса: английский
  /// текст это ключ перевода, русский приходит словарём модуля.
  final String title;
}
