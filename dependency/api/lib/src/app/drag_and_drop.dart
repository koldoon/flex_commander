import 'package:flutter/widgets.dart';

import '../tree/fs_node.dart';

/// Что тащат: пути из системы или узлы дерева изнутри приложения.
///
/// Оба сразу не бывает, но приёмнику всё равно, что именно приехало: он
/// спрашивает то, чем умеет пользоваться. Из Finder приходят пути — узлов у
/// системы нет и быть не может; из панели поедут узлы — у них есть провайдер, и
/// терять его, сводя всё к строке пути, нельзя: путь внутри архива снаружи
/// ничего не значит.
class DropPayload {
  const DropPayload({this.paths = const [], this.nodes = const [], this.moves = false});

  /// Переносить, а не копировать: человек держит `Shift`.
  ///
  /// Решает это система, а не мы: она же рисует у курсора значок — «плюс» у
  /// копии, стрелку у переноса, — и спрашивает у источника, позволено ли ему
  /// вообще расставаться с объектами. Наружу мы, например, отдаём только копию.
  final bool moves;

  /// Пути настоящей файловой системы — то, что даёт система.
  final List<String> paths;

  /// Узлы дерева — то, что даёт панель.
  final List<FsNode> nodes;

  bool get isEmpty => paths.isEmpty && nodes.isEmpty;
}

/// Куда попадёт брошенное — ответ приёмника на вопрос «что у тебя вот здесь».
///
/// Null вместо [DropSpot] означает «сюда нельзя», и это же выключает подсветку:
/// человек видит отказ до того, как отпустит кнопку.
class DropSpot {
  const DropSpot({required this.destination, this.node});

  /// Путь каталога, в который лягут объекты.
  final String destination;

  /// Объект списка, который надо подсветить; null — подсвечивается вся область.
  ///
  /// Разница видна человеку: бросок на строку-каталог кладёт **в неё**, а
  /// бросок мимо строк — в каталог, открытый в панели.
  final FsNode? node;
}

/// Перетаскивание мышью. Нет службы — нет и перетаскивания.
///
/// **Хозяин** ([target] и [source] принимают его одинаковым) — это место, из
/// которого тащат и в которое бросают: у нас это панель. Место, где жест
/// начался, себе же приёмником не бывает: перетащить из панели в неё саму
/// значит скопировать каталог сам в себя, а рамка вокруг источника только
/// сбивает с толку — она обещает работу, которой не будет.
///
/// Лежит среди контрактов приложения, а не платформенных служб, хотя приносит
/// её платформенный модуль: разговор здесь идёт **о виджетах** — обернуть
/// область приёмником, строку источником, — а платформенное всё осталось по ту
/// сторону службы.
///
/// Панели не знают, кто и как перетаскивает: они лишь объявляют себя приёмником
/// и источником. Поэтому исполнителя можно заменить целиком — своей нативной
/// частью, чужим плагином, а внутри приложения и вовсе средствами Flutter, — не
/// трогая ни строчки в панелях.
abstract interface class DragAndDrop {
  /// Область, принимающая перетаскивание.
  ///
  /// [spotAt] отвечает, что лежит под курсором **сейчас**, в местных
  /// координатах области; [builder] рисует содержимое и получает то, что над
  /// ним, — null, когда над ним ничего не тащат.
  Widget target({
    required Object owner,
    required DropSpot? Function(Offset local) spotAt,
    required Future<void> Function(DropSpot spot, DropPayload payload) onDrop,
    required Widget Function(BuildContext context, DropSpot? hovered) builder,
  });

  /// Обернуть содержимое в источник перетаскивания.
  ///
  /// Узлы спрашиваются **в момент захвата**, а не при сборке виджета: пометка
  /// меняется, а строка списка от этого не пересобирается.
  Widget source({required Object owner, required Widget child, required List<FsNode> Function() nodes});
}
