import 'package:flutter/foundation.dart';

import '../commands/app_command.dart';
import 'panel.dart';

/// Места на экране.
///
/// Перечень закрытый: модуль приносит **содержимое** области, но не само
/// место — шелл не разложит область, о которой не знает, а доля ширины под
/// левой областью уже предполагает ровно левое и правое.
///
/// Ряд функциональных кнопок и рама окна областями не являются: это обвязка
/// шелла, а не место, куда что-то ставят.
enum ViewportPosition {
  /// Область левой панели. Если левая и правая чем-то заняты, между ними
  /// появляется перетаскиваемый разделитель.
  left,

  /// Область правой панели.
  right,

  /// Область под левой панелью. Вместе с [left] образует столбец из двух
  /// виджетов; если содержимое не поставлено, области нет вовсе.
  ///
  /// Здесь показывают **работу** — и только ту, что явно отправили в фон с
  /// этой панели. Про **содержимое** (объект под курсором, сводка по пометке)
  /// говорит строка внутри самой панели, а не эта область.
  leftStatus,

  /// Аналогично [leftStatus], но для правой панели.
  rightStatus,

  /// Область под панелями, но перед функциональными кнопками. Не занята —
  /// не рендерится совсем. Обычно занята командной строкой.
  bottom,

  /// Поверх панелей, но ниже функциональных кнопок: полноэкранные просмотрщик,
  /// редактор, терминал. Кнопки при этом меняют своё назначение в контексте
  /// того, что показано.
  ///
  /// Стопка здесь может быть **пустой**: сняли последний слой — и видно панели.
  /// Так же пустеют статусные области; не пустеет только панельная, потому что
  /// панель нельзя убрать, её можно лишь заменить.
  fullscreen;

  /// Противоположная область: источник ↔ приёмник файловой операции.
  /// У областей без пары — она сама.
  ViewportPosition get opposite => switch (this) {
    left => right,
    right => left,
    leftStatus => rightStatus,
    rightStatus => leftStatus,
    _ => this,
  };

  bool get isPanelArea => this == left || this == right;

  /// Статусная область этой панели; null — у этой области своей нет.
  ///
  /// Нужна тем, кто показывает что-то **под** панелью, не занимая её саму:
  /// быстрый поиск, ход работы, будущие полосы. Спрашивают её у области
  /// панели, а не выбирают руками: `left` и `leftStatus` должны сходиться
  /// всегда, а два места, где это записано, однажды разойдутся.
  ViewportPosition? get status => switch (this) {
    left => leftStatus,
    right => rightStatus,
    _ => null,
  };
}

/// Данные области: то, что в ней показано.
///
/// Вид для них регистрируется **по типу** (`FcRegistry.view<S>`), а не по
/// имени: связь «состояние ↔ вид» проверяет компилятор, потерять вид
/// невозможно. Устойчивого идентификатора у состояния поэтому нет — как нет и
/// сериализации содержимого областей: при запуске в [ViewportPosition.left] и
/// [ViewportPosition.right] всегда панели.
///
/// [Listenable] — часть контракта: содержимое меняется, и вид подписывается на
/// него обычным `ListenableBuilder`.
abstract interface class ViewportState implements Listenable {
  /// Забирает ли содержимое системный фокус, когда его область активна.
  ///
  /// Панелям он не нужен: какая область активна, знает приложение, а нажатия
  /// разбирает ранний обработчик. Редактору нужен — внутри поле ввода, и
  /// события должны до него доходить. Умолчания нет намеренно: забыть ответить
  /// на этот вопрос нельзя.
  bool get takesKeyboard;

  /// Состояние убрали: отпустить всё, что оно держало.
  ///
  /// Зовёт ядро — и при замене содержимого, и при снятии наложения, и при
  /// выходе из приложения. Дальше экземпляр не используется.
  ///
  /// Панели есть что отпускать: аренда провайдера. Правку файла из архива не
  /// закончить, если архив закрылся под ней, — поэтому отпускает тот, кто
  /// держал, и ровно тогда, когда его убрали.
  void close();
}

/// Содержимое, внутри которого стоит другое содержимое.
///
/// Так устроен быстрый просмотр: в области стоит он, а показывает он то, что
/// выбрал просмотрщик, — и меняет это, когда курсор переходит на файл другого
/// рода. Наследованием тут не обойтись: под курсором рядом с `readme.md`
/// лежит `logo.png`, и меняется не файл, а сам показ.
abstract interface class ViewportHost implements ViewportState {
  /// Что показано внутри; null — показывать нечего (каталог, отказ, ошибка).
  ViewportState? get inner;
}

/// Самое внутреннее содержимое: то, что человек и правда видит.
///
/// Спрашивают все, кому важно «что сейчас показано»: разбор привязок клавиш —
/// иначе `F2` в быстром просмотре достался бы хозяину, который о переносе
/// строк не знает, — и поиск, который ищет в показанном тексте.
ViewportState innermost(ViewportState state) {
  final inner = state is ViewportHost ? state.inner : null;
  return inner == null ? state : innermost(inner);
}

/// Область на экране: что в ней показано сейчас.
class ViewPort {
  const ViewPort({required this.position, required this.state});

  final ViewportPosition position;

  /// Верх стопки: наложение, если оно есть, иначе то, что стоит в области.
  final ViewportState state;

  bool get takesKeyboard => state.takesKeyboard;
}

/// Рабочая область приложения: что где стоит и кому принадлежит ввод.
///
/// Одна модель раскладки вместо двух: и полноэкранные виды, и содержимое
/// панелей — это состояния в областях, и рисуются они одним механизмом.
abstract interface class ApplicationView implements Listenable {
  /// Что показано в области; null — область пуста и не рисуется.
  ViewportState? contentAt(ViewportPosition position);

  /// Вся стопка области, снизу вверх.
  ///
  /// Нужна там, где показывают **не только верхнее**: статусная область под
  /// панелью выкладывает свою стопку столбцом, а не прячет одно за другим.
  List<ViewportState> stackAt(ViewportPosition position);

  /// Панель, показанная в области **сейчас**, — верх её стопки; null, если
  /// там не панель.
  ///
  /// Верх, а не дно: наложение скрывает панель целиком. Пока поверх правой
  /// области показан просмотрщик, копировать туда нечего — и `F5` становится
  /// невыполнимой сама собой, без отдельной проверки. Что показано, то и есть.
  ///
  /// «Панель есть» — ещё не «в неё можно писать»: результаты поиска панелью
  /// остаются, и копировать из них можно, а приёмником они быть не могут,
  /// потому что их провайдер не реализует записи.
  Panel? panelAt(ViewportPosition position);

  /// Заменяет то, что стоит в области, — дно её стопки.
  ///
  /// Прежнее закрывается ([ViewportState.close]) и не возвращается: это выбор,
  /// а не временное перекрытие. Так меняют вид панели — таблица, дерево,
  /// миниатюры.
  void setViewportContent(ViewportPosition position, ViewportState state);

  /// Кладёт временное содержимое **поверх** того, что в области стоит.
  ///
  /// Под наложением всё живо: каталог, курсор, пометка, колонки, аренда, — и
  /// [popViewportContent] открывает ровно то, что было. Так показывают
  /// просмотрщик, редактор, быстрый просмотр и результаты поиска.
  ///
  /// Повторное наложение того же вида — замена верхнего слоя, а не второй
  /// слой поверх первого: два просмотрщика друг над другом не стопка, а
  /// недосмотр.
  void pushViewportContent(ViewportPosition position, ViewportState state);

  /// Снимает верхнее наложение и закрывает его. На дне не снимает ничего.
  void popViewportContent(ViewportPosition position);

  /// Область, в которой стоит это содержимое; null — его нигде не видно.
  ///
  /// Спрашивает тот, кому важно **место**, а не он сам: показ в области панели
  /// рисует внешний край рамки со своей стороны, и сторону эту он узнаёт
  /// только так — сам о себе он знает лишь то, что показывает.
  ViewportPosition? positionOf(ViewportState content);

  /// Достаются ли клавиши этому содержимому прямо сейчас.
  ///
  /// Спрашивать может и то, что стоит **внутри** хозяина: вид показа не знает,
  /// в области он или в быстром просмотре, а фокус просить обязан одинаково.
  ///
  /// Один вопрос вместо трёх домыслов. До него каждый считал сам: панель
  /// сравнивала свой признак активности, быстрый просмотр искал себя по
  /// областям, а показ текста получал ответ параметром — и разойтись им было
  /// проще простого. Разошлись: обе плашки горели ярко, и куда ушёл ввод, было
  /// не видно.
  ///
  /// **Ответ бывает утвердительным сразу у двоих, и это не ошибка.** Пока ввод
  /// у командной строки, `F1`…`F12` и стрелки достаются панели — правило живёт
  /// в разборе привязок (`CommandRegistry.bindingFor`), а здесь повторено,
  /// потому что вопрос тот же самый: кому сейчас клавиша. Панель в этот момент
  /// и правда ими распоряжается — курсор ходит, — и приглушать её нельзя.
  ///
  /// **Полоса под активной панелью отвечает за себя сама.** Областью она не
  /// бывает, активной не станет, но набор забрать может — так устроен быстрый
  /// поиск, — и тогда клавиши у неё. Спрашивается при этом [
  /// ViewportState.takesKeyboard] самого содержимого: полоса хода работы
  /// клавиш не берёт и светиться не должна. Полос на экране две, своя у каждой
  /// стороны, и ровно поэтому вопрос «достаются ли клавиши **мне**» нельзя
  /// подменять вопросом «идёт ли набор вообще».
  bool takesKeys(ViewportState content);

  /// Область, которой принадлежит ввод.
  ///
  /// Не системный фокус Flutter, а состояние приложения: панель рисует курсор
  /// активной, потому что она названа здесь. От неё же считается контекст
  /// привязок клавиш.
  ViewportPosition get activeArea;

  /// Панель-источник: последняя из [ViewportPosition.left] и
  /// [ViewportPosition.right], которой принадлежал ввод.
  ///
  /// Отдельно от [activeArea], потому что ввод уходит и туда, где панели
  /// нет, — в полноэкранный просмотрщик, в будущую командную строку, — а
  /// источник файловой операции при этом никуда не девается.
  ViewportPosition get sourceArea;

  /// Единственный вход: выставляет [activeArea] и просит системный фокус для
  /// виджета области. Двумя вызовами эти состояния разъедутся.
  void setFocus(ViewportPosition position);

  /// Открытые окна, снизу вверх: последнее показанное — верхнее.
  ///
  /// Стопка, а не список: окно вправе поднять дочернее — выбор каталога,
  /// подтверждение, — и клавиши принадлежат верхнему.
  List<DialogSpec> get dialogs;

  /// Показывает окно и возвращает его идентификатор — по нему же закрывать.
  ///
  /// Окно **не область**: ни [activeArea], ни [sourceArea] оно не меняет.
  /// Поэтому команда, запущенная из списка команд, видит ту же панель, что и
  /// клавиша, — хотя ввод в этот момент был в окне списка.
  String showDialog(DialogSpec spec);

  void closeDialog(String dialogId);
}
