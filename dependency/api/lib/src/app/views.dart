import 'package:flutter/widgets.dart';

/// Чем рисуется состояние: объект данных отдельно, вид отдельно.
///
/// Живёт в API по той же причине, что [Screen.build] и [PanelViewportBuilder]:
/// это контракт про то, **чем рисовать**, и виджеты здесь допустимы.
typedef StateViewBuilder<S extends Object> = Widget Function(BuildContext context, S state);

/// Объявленный вид: на какой тип, как его узнать и чем рисовать.
///
/// Проверка отдельно от типа, потому что вид объявляют и на **интерфейс**:
/// `view<Panel>(…)` — а придёт `PanelController`, и по типу они не совпадут.
class StateView {
  const StateView({required this.stateType, required this.matches, required this.build});

  /// Тип, на который вид объявлен. Ключ реестра: второй вид на тот же тип —
  /// ошибка сборки.
  final Type stateType;

  /// Подходит ли вид этому состоянию: `(state) => state is S`.
  final bool Function(Object state) matches;

  final StateViewBuilder<Object> build;
}

/// Виды: какому состоянию чем рисоваться.
///
/// Одним механизмом рисуются разные вещи: содержимое областей и окна заявок,
/// которые операция выставляет, упёршись в вопрос. И там, и там объект данных
/// приносит модуль, а ядро только находит, чем его показать.
abstract interface class Views {
  /// Чем рисовать это состояние; null — вида для него не объявляли.
  ///
  /// Сначала ищется вид, объявленный ровно на его тип; не нашёлся — тот,
  /// которому состояние подходит. Двух подходящих быть не должно: это значит,
  /// что вид зависит от порядка модулей в списке, а он там стоит ради
  /// приоритета привязок клавиш.
  ///
  /// null, а не заглушка: что делать с необъявленным видом, решает тот, кто
  /// спрашивает. Области рисуют пустое место — модуль могли отключить, а место
  /// показать что-то обязано; заявка без вида — ошибка, потому что вопрос без
  /// вида означает работу, которая встала навсегда.
  StateViewBuilder<Object>? builderFor(Object state);
}
