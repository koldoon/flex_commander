/// Что приложение знает о своей сборке.
///
/// Значением, а не службой: сведения не меняются ни на ходу, ни между
/// запросами — их спрашивают один раз и передают дальше как есть.
///
/// **Платформенное за интерфейсом** (сквозное правило 2): версия лежит в
/// `Info.plist`, путь знает сам бандл, архитектуру — собранный двоичный файл.
/// Читает это `fc_platform`, а пользуются все — справка, отчёт об ошибке и
/// обновление (`docs/spec/build-info.md`).
class BuildInfo {
  const BuildInfo({this.version = '', this.build = '', this.bundlePath = '', this.architecture = ''});

  /// Сборка, о которой ничего не известно: запуск не из бандла — проверки и
  /// `flutter run`.
  static const BuildInfo unknown = BuildInfo();

  /// Версия выпуска: `0.0.77`. Пусто — узнать не вышло.
  ///
  /// У сборки с машины разработчика здесь `1.0.0` из `pubspec.yaml`: выпуск
  /// проставляет версию сам, из тега.
  final String version;

  /// Номер сборки — номер прогона, которым её собрали.
  final String build;

  /// Каталог `.app`; пусто — приложение запущено не из бандла.
  final String bundlePath;

  /// `arm64` или `x64`.
  final String architecture;

  /// Известно ли о себе хоть что-то.
  bool get isKnown => version.isNotEmpty;

  /// Как это показывают человеку: `0.0.77 (сборка 128)`.
  ///
  /// Номер сборки в скобках, а не через плюс: плюс читается как часть версии, а
  /// это разные вещи — версию называет тег, номер сборки — прогон.
  String describe({String buildWord = 'build'}) {
    if (version.isEmpty) {
      return '';
    }
    return build.isEmpty ? version : '$version ($buildWord $build)';
  }
}
