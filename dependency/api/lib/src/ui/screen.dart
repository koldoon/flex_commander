import 'package:flutter/widgets.dart';

/// Полноэкранный режим приложения: файловые панели, просмотрщик, редактор,
/// результаты поиска.
///
/// Живёт рядом с [PanelViewports] и по той же причине: это контракт про то,
/// **чем рисовать**, а виджеты в API допустимы только здесь.
///
/// Экран занимает всё, что выше ряда функциональных кнопок, — ряд остаётся на
/// месте всегда и показывает команды того экрана, который сейчас виден. Этим
/// экран отличается от окна команды: то рисуется поверх всего, забирает
/// клавиши целиком и существует ровно на время одного запуска команды.
///
/// Панели с файлами — такой же экран, как и остальные, и живут в модуле:
/// ядро не знает, чем показывают файлы, и поэтому рядом со встроенным видом
/// можно поставить свой — дерево, три панели, список результатов.
abstract interface class Screen {
  /// Устойчивое имя: к нему привязываются клавиши ([KeyBinding.screen]).
  String get id;

  /// Берёт ли экран фокус клавиатуры себе.
  ///
  /// Панелям он не нужен: какая из них активна, знает приложение, а нажатия
  /// разбирает общий обработчик. Просмотрщику нужен — прокрутку стрелками и
  /// `PgUp`/`PgDn` разбирает сам `Scrollable`, и до него события должны
  /// доходить. Явное свойство, а не догадки по содержимому, — как
  /// [AppCommand.dialogTakesFocus].
  bool get takesFocus => false;

  Widget build(BuildContext context);
}

/// Экраны приложения: стопка, из которой виден верхний.
///
/// Стопка, а не одно значение: просмотрщик открывается **поверх** панелей и,
/// закрываясь, возвращает то, что было под ним. Кто открыл экран, тот его и
/// закрывает — по имени.
abstract interface class Screens implements Listenable {
  /// Общеизвестное имя экрана с файловыми панелями.
  ///
  /// Живёт в API по той же причине, что и [PanelViewports.files]: привязки
  /// клавиш объявляют, в каком экране они действуют, а модуль навигации не
  /// должен ради этого зависеть от модуля панелей.
  static const String files = 'files';

  /// Экран, который виден сейчас; null — показывать нечего.
  Screen? get active;

  /// Открывает экран поверх текущего. Повторное открытие того же имени
  /// заменяет прежний: два просмотрщика друг над другом — это не стопка,
  /// а недосмотр.
  void open(Screen screen);

  /// Закрывает экран по имени. Того, чего нет, закрывать нечего — это не
  /// ошибка: команда закрытия может прийти и после того, как экран уже ушёл.
  void close(String id);
}
