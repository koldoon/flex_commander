/// Шрифты темы.
///
/// Те же, что в референсе (`resources/styles/typo.css`): интерфейс — Ubuntu,
/// списки файлов — Consolas. Они лежат в `assets/fonts` приложения, поэтому оно
/// выглядит одинаково на любой системе, а не только там, где эти шрифты
/// установлены. Тема со своими шрифтами приносит их своими ресурсами
/// (`packages/<имя>/fonts/...`).
class FcFonts {
  const FcFonts({this.ui = 'Ubuntu', this.fixed = 'Consolas'});

  /// Шрифт интерфейса: заголовки, подписи, кнопки, окна команд.
  final String ui;

  /// Шрифт списка файлов: имена, размеры и даты стоят ровными столбцами.
  final String fixed;
}
