/// Размеры интерфейса по ролям, а не по числам.
///
/// Здесь только то, **что** измеряется: высота строки, поля, кегль. Сами числа
/// приносит тема — оформление по умолчанию живёт в модуле `fc_default_theme`.
///
/// Числа — точками экрана, как их понимает Flutter: за разные dpi отвечает он,
/// а не тема. Общего коэффициента у набора нет нарочно — с ним половину
/// значений приходилось бы читать через умножение в уме, а другую половину
/// как есть.
abstract class FcMetrics {
  const FcMetrics();

  // --- окно (Main.mxml) ---

  /// Полоса вверху окна вместо системной: за неё окно двигают, в ней стоит
  /// светофор macOS.
  ///
  /// Системной полосы у окна нет вовсе — содержимое занимает его целиком, —
  /// поэтому высоту назначает тема. Ниже светофора её ставить нельзя: кнопки
  /// накроют содержимое, и двигать окно станет не за что.
  double get windowTitleBarHeight;

  /// Отступ от полосы до панелей: `top="20"`.
  double get windowTopPadding;

  /// Поля слева и справа: от края окна до панелей, полосы и ряда кнопок.
  ///
  /// Одна величина на всё содержимое окна, а не на одни панели: кнопки стоят
  /// под панелями и обязаны кончаться там же, где они, — иначе ряд выпирает
  /// за края того, что подписывает.
  ///
  /// Ноль — законное значение и сейчас умолчание: в референсе полей нет, окно
  /// занято содержимым целиком. Величина всё равно заведена: это про вид, а
  /// вид принадлежит теме — как и зазор между панелями.
  double get windowSidePadding;

  /// Зазор между панелями: `width / 2 - 10` у обеих.
  double get panelGap;

  /// Просвет между рабочей областью и нижней панелью кнопок.
  ///
  /// Ставит его шелл, когда под панелями пусто: это внешняя рамка окна, и
  /// полноэкранный просмотрщик отбит от кнопок ровно так же, как панели. Занята
  /// полоса — просветы отмеряет она сама ([commandLineGap]), а рамка ей не
  /// прибавляется.
  double get functionBarGap;

  /// Воздух вокруг командной строки — с обеих сторон.
  ///
  /// Отдельно от [functionBarGap], хотя оба про просветы внизу окна, и вместе
  /// они не складываются: где стоит строка, рамку отмеряет она, где не стоит —
  /// шелл. Пока величина была одна, настроить их порознь было нельзя:
  /// подобрали по строке — разъехалась рамка в полноэкранном, где строки нет
  /// вовсе; вернули рамку — строка отошла от кнопок дальше, чем от панелей.
  double get commandLineGap;

  /// Отступ от низа окна: `bottom="15"` у списка кнопок.
  double get windowBottomPadding;

  // --- панель (FilesPanel.mxml) ---

  /// Плашка с путём: `height="60"`, скругление `radiusX="5"`.
  /// Она наполовину заходит на верхнюю рамку панели — рамка начинается с
  /// `top="30"`, то есть ровно с середины плашки.
  double get pathHeaderHeight;
  double get pathHeaderRadius;

  /// Насколько плашка уже панели: `maxWidth="{width - 100}"`.
  double get pathHeaderMinInset;

  /// Скругление углов панели.
  ///
  /// Применяется, **только пока рамка замкнута**: у панели, прижатой к краю
  /// окна, внешняя сторона не рисуется вовсе, и скруглять там нечего — угол
  /// вышел бы обрубленным. Появились поля ([windowSidePadding]) — появилось и
  /// скругление.
  double get panelRadius;

  /// Отступ от рамки панели до строки заголовков: `top="80"` при рамке с 30.
  double get panelTopPadding;

  /// От заголовков до первой строки: список начинается с `top="135"`.
  double get headerRowHeight;

  /// Строка списка: `height="50"` у `FileItemRenderer`, `gap="2"` в раскладке.
  double get rowHeight;
  double get rowGap;

  /// Высота строки состояния внизу панели.
  ///
  /// В точках экрана, а не в единицах разметки: это про то, сколько места
  /// занимает строка текста, — как и ширина захвата разделителя.
  double get statusBarHeight;

  /// Поля внутри панели: заголовки `left="30"`, содержимое строки `right="40"`.
  double get panelLeftPadding;
  double get panelRightPadding;

  /// Поля строки состояния и плашки пути: `left="20"` у обеих меток.
  double get labelPadding;

  /// Зазор между колонками: `gap="30"` у заголовков, `gap="20"` у строки.
  double get columnGap;

  /// Полоса, отмечающая помеченный объект у левого края строки: `width="8"`.
  double get markedBarWidth;

  /// Отступ от края строки до иконки: `left="30"`.
  double get iconLeftPadding;

  /// Просвет от иконки до имени.
  ///
  /// Имя стоит на `left="{iconLabel.width + 50}"`, сама иконка — на `left="30"`,
  /// то есть между ними 20 единиц. Плюс пробел, зашитый в каждый глиф
  /// (`"\uf07b "` в `icon.as`): он входит в `iconLabel.width`.
  ///
  /// По этой арифметике выходит 28, но на глаз просвет великоват: `Icon` во
  /// Flutter отводит глифу квадрат по кеглю, а папка уже своего квадрата, и
  /// этот запас добавляется к просвету сам. Отсюда 19.
  double get iconGap;

  /// Ширина колонки с иконкой: отступ слева, глиф и просвет до имени.
  ///
  /// Поле ячейки имени ([cellPadding]) — часть того же просвета, поэтому оно
  /// вычитается: иначе имя отойдёт от иконки дальше, чем в референсе.
  double get iconColumnWidth;

  // --- нижняя панель (FunctionKeyRenderer) ---

  /// Высота кнопки: `rowHeight="55"`.
  double get functionButtonHeight;

  /// Скругление кнопки: `radiusX="5"`.
  double get functionButtonRadius;

  /// Ширина колонки с номером клавиши: `width="50"` у метки номера.
  ///
  /// Шире исходного: в референсе там стояла одна цифра, а у нас — `F1`…`F10`.
  double get functionKeyNumberWidth;

  /// Просвет между кнопкой и её номером: кнопка начинается с `left="55"`.
  double get functionKeyNumberGap;

  /// Зазор между кнопками: `horizontalGap="20"`.
  double get functionButtonGap;

  /// На сколько ряд кнопок шире остального содержимого — с каждой стороны.
  ///
  /// Ряд стоит ближе к краям окна, чем панели над ним: кнопки — рисованная
  /// клавиатура, и им место у самого края, а не в общей рамке. Вычитается из
  /// [windowSidePadding]; больше него не бывает — ряд не вылезает за окно.
  double get functionBarSideOutset;

  /// Поле справа у ряда кнопок: `paddingRight="30"`.
  double get functionBarRightPadding;

  // --- окна команд (TitledPopupPanelSkin) ---

  /// Скругление окна: `radiusX="10"`.
  double get dialogRadius;

  /// Доля ширины окна приложения, которую занимает окно команды.
  ///
  /// Ширина именно доля, а не размер содержимого: в окне копирования по ходу
  /// работы меняются имена файлов, и от них окно «прыгало» бы на каждом файле.
  double get dialogWidthFactor;

  /// То же для палитры команд — она шире остальных окон.
  ///
  /// Палитра это список, а список хочет ширины: в строке стоят название,
  /// описание и клавиши, и в половине экрана описание обрывалось бы
  /// многоточием у большинства команд. У окна с формой такой нужды нет — там
  /// поля, а не строки.
  double get paletteWidthFactor;

  /// Пределы для этой доли: `minWidth="1000" maxWidth="2000"` у диалогов
  /// референса.
  double get dialogMinWidth;
  double get dialogMaxWidth;

  /// Полоса заголовка: `left="20"` у метки.
  double get dialogTitlePadding;

  /// Высота полосы заголовка: `top="25"` + кегль `h5` (34) + `bottom="25"`.
  ///
  /// Задана высотой, а не полями: иначе к 25 сверху и снизу прибавился бы ещё
  /// межстрочный просвет, который Flutter кладёт внутрь строки, и полоса вышла
  /// бы выше референсной.
  double get dialogTitleHeight;

  /// Содержимое: `padding="20" paddingLeft="40"`.
  double get dialogPadding;
  double get dialogHorizontalPadding;

  /// Отступ от полосы заголовка до первой строки содержимого.
  ///
  /// Больше обычного [dialogPadding]: к нему в референсе добавляется смещение
  /// первой строки формы — `baseline="maxAscent:10"` в `SimpleFormItemSkin`.
  double get dialogContentTopPadding;

  /// Между строками содержимого и между кнопками: `gap="20"`.
  double get dialogGap;

  /// Между строками одного поля: имя, объём и полоса стоят теснее, чем поля
  /// друг от друга, — иначе блок рассыпается на три отдельные строки.
  double get dialogLineGap;

  /// Просвет **над строкой без подписи** — флагом, сообщением, полосой.
  ///
  /// Больше обычного [dialogGap], как в референсе: такая строка не продолжает
  /// столбец полей, а стоит под ним. С одинаковым просветом она читается как
  /// ещё одно поле, у которого забыли подпись.
  double get dialogWideRowGap;

  /// Между настройками в окне настроек.
  ///
  /// Своя мера, а не [dialogWideRowGap] с тем же числом: настройка — не строка
  /// формы, а блок из подписи, объяснения и управления, и просвет между
  /// блоками должен читаться заметнее, чем просветы внутри блока. Совпади они
  /// сегодня числом — разъедутся завтра, и будет непонятно, какое из них
  /// править.
  double get settingsBlockGap;

  /// Перед заголовком раздела в окне настроек.
  ///
  /// Больше, чем между настройками: заголовок отделяет чужие настройки от
  /// своих, и это самая крупная граница в окне.
  double get settingsSectionGap;

  /// Линия над рядом кнопок: `height="2"`.
  double get dialogDividerHeight;

  /// Ширина колонки подписей в форме окна.
  double get dialogLabelWidth;

  /// Предел ширины столбца подписей в форме.
  ///
  /// Столбец меряется по самой широкой подписи, а это значит, что одна длинная
  /// способна съесть форму: значения и пояснения ужмутся в остаток и начнут
  /// переноситься по слову. Предел возвращает это в берега — подпись
  /// переносится сама.
  ///
  /// Отдельно от [dialogLabelWidth]: та задаёт ширину **поля** (короткого
  /// ввода, числа), и менять её ради столбца нельзя.
  double get dialogLabelMaxWidth => dialogLabelWidth * 1.6;

  /// Предел ширины ячейки в таблице справки: дальше строка переносится.
  ///
  /// Без него одно длинное значение — путь или описание — растянуло бы окно до
  /// полей экрана, а таблица со столбцами по содержимому под тесной разметкой
  /// не ужимается, а вылезает наружу.
  double get helpCellMaxWidth;

  /// Поле от края окна приложения до окна справки.
  ///
  /// Единственный размер, взятый не из референса: справки там не было вовсе.
  /// Считается в точках экрана, а не в единицах разметки: это отступ от края
  /// окна, а не часть рисунка.
  double get dialogScreenInset;

  /// Какую долю окна приложения дозволено занять окну команды.
  ///
  /// Ширину окно берёт **по содержимому** — рама облегает то, что ей дали, — а
  /// это лишь предел: справка с длинными описаниями иначе растянулась бы от
  /// края до края, и читать её пришлось бы, поворачивая голову.
  double get dialogMaxScreenFactor;

  /// Сколько окна остаётся видно, когда его утащили за край.
  ///
  /// Окно отодвигают, чтобы посмотреть, что под ним, — и увести его совсем за
  /// край можно только по недосмотру: обратно оно уже не вернётся, потому что
  /// тянут за полосу заголовка. Считается в точках экрана, а не в единицах
  /// разметки: это про то, за что можно ухватиться пальцем.
  double get dialogDragKeepVisible;

  /// Тень окна: `DropShadowFilter distance="5" blurX="15" blurY="15"`.
  double get dialogShadowOffset;
  double get dialogShadowBlur;

  // --- всплывающее сообщение ---

  /// Поля внутри сообщения. Меньше, чем у окна команды: там форма, здесь
  /// одна строка.
  double get toastPadding;
  double get toastHorizontalPadding;

  /// На сколько сообщение поднято над низом окна — чтобы не налезать на ряд
  /// функциональных кнопок.
  double get toastBottomOffset;

  // --- кнопка окна команды (RegularButtonSkin) ---

  /// `height="60"`, `radiusX="8"`, метка с полями `left="40"`.
  double get buttonHeight;
  double get buttonRadius;
  double get buttonHorizontalPadding;

  /// Тень под кнопкой и под полосой заголовка окна:
  /// `DropShadowFilter blurY="2" blurX="0" distance="1" angle="90"`.
  ///
  /// Как и [strokeWidth], в точку толщиной: тень тоньше точки исчезла бы
  /// совсем, поэтому уменьшать её вместе с остальным нельзя.
  double get buttonShadowOffset;
  double get buttonShadowBlur;

  // --- поле ввода (TextInputBorderedSkin) ---

  /// `height="70"`, `radiusX="8"`, текст с `left="22"`.
  /// Сторона квадрата флажка и кружка переключателя: с кегль текста, чтобы
  /// метка и знак стояли на одной линии.
  double get checkboxSize;

  /// Зазор между знаком и его меткой.
  double get checkboxGap;

  double get inputHeight;
  double get inputRadius;
  double get inputHorizontalPadding;

  // --- полоса хода работы (ProgressBar.mxml) ---

  /// `height="30"`, скругление в половину высоты, заливка с отступом `4`.
  double get progressHeight;
  double get progressInset;

  // --- общее ---

  /// Отступ полосы прокрутки от рамки того, что она прокручивает.
  ///
  /// Полоса стоит по краю панели, а не по краю содержимого: у узкого файла
  /// иначе она висела бы посреди пустого места.
  double get scrollbarInset;

  /// Толщина обводок: `weight="2"` в референсе, а на экране — точка.
  ///
  /// Пропорции референса здесь не в счёт: линия тоньше точки размылась бы, а в
  /// референсе она чёткая.
  double get strokeWidth;

  /// Толщина обводки фокуса.
  ///
  /// Рисуется она **поверх** элемента, а не рамкой: рамка входит в размер, и
  /// кнопка от неё раздавалась бы на глазах. Поэтому и толщина своя: обводке
  /// поверх приходится быть заметнее обычной линии, иначе она сливается с той,
  /// что уже нарисована под ней.
  ///
  /// С умолчанием: тема, написанная до появления фокуса, обязана работать.
  double get focusRingWidth => strokeWidth * 2;

  /// Размер шрифта: в референсе `h5` — `fontSize: 34px`.
  double get fontSize;

  /// Иконка — глиф того же кегля, что и текст (`styleName="h5 ... icon"`).
  double get iconSize;

  /// Поле внутри ячейки таблицы: половина зазора между колонками.
  double get cellPadding;

  /// Насколько опущено содержимое **строки списка** — иконка вместе
  /// с текстом — относительно её подсветки.
  ///
  /// Оптическая поправка в точках экрана, а не число референса: при точном
  /// совпадении границ содержимое выглядит прижатым к верху строки. Курсор
  /// и полоса пометки при этом остаются на месте — они держат границы строки.
  double get rowContentVerticalNudge;

  /// Насколько опущен текст **строки списка** относительно её иконки.
  ///
  /// В референсе иконка стоит на `verticalCenter="0"`, а группа с текстом — на
  /// `verticalCenter="2"`. Это не случайность: у моноширинных шрифтов базовая
  /// линия на некоторых кеглях смещена, и без поправки текст не встаёт на одну
  /// линию с иконкой.
  ///
  /// Только к списку файлов: остальное набрано Ubuntu, и там базовая линия
  /// обычная. Величина поправки — часть темы, а не константа: замерена она была
  /// на Consolas, а список набирается тем, что стоит у пользователя.
  double get rowTextVerticalNudge;

  /// Ширина области захвата разделителя панелей и границ колонок.
  /// Не уже [panelGap]: иначе разделитель было бы труднее подцепить, чем видно.
  double get resizeHandleWidth;

  /// Минимальная ширина панели при перетаскивании разделителя.
  double get minPanelWidth;
}
