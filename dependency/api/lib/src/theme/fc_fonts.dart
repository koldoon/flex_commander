/// Шрифты темы по ролям.
///
/// Интерфейс приложения и список файлов набираются разными шрифтами: первый —
/// обычным, второй — моноширинным, чтобы имена, размеры и даты стояли ровными
/// столбцами. Какими именно — решает тема.
abstract class FcFonts {
  const FcFonts();

  /// Шрифт интерфейса: заголовки, подписи, кнопки, окна команд.
  String get ui;

  /// Шрифт списка файлов.
  String get fixed;

  /// Чем набрать список, если [fixed] в системе не стоит.
  ///
  /// Роль отдельная, потому что [fixed] может быть **не свой**: тема вправе
  /// назвать шрифт, который приложение с собой не возит, и тогда на чужой
  /// машине его может не оказаться. Без запасного списка подстановку делает
  /// система, а она берёт свой обычный шрифт — пропорциональный, и столбцы
  /// размеров и дат перестают стоять столбцами.
  ///
  /// Пустой список — «подставляй что хочешь»: тема со своим шрифтом в ресурсах
  /// в запасе не нуждается.
  List<String> get fixedFallback;
}
