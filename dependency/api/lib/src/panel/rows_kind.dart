/// Чем набираются строки панели.
///
/// Вид сам говорит, что ему нужно: таблице и краткому виду — содержимое
/// каталога, дереву — развёрнутые ветви (`docs/spec/panel-node-list.md`, §3).
/// Ядро при этом не знает ни одного вида по имени: оно знает **набор строк**.
enum RowsKind {
  /// Один каталог: то, чем панель жила до сих пор.
  listing,

  /// Дерево: набор корней, развёрнутый построчно.
  tree,

  /// То же дерево, но в нём только каталоги.
  ///
  /// Левый столбец комбинированного вида: файлы живут в правом и второй раз не
  /// показываются (`docs/spec/panel-view-combined.md`, §4).
  branches;

  /// Набраны ли строки ветвями.
  ///
  /// Спрашивают это команды дерева: раскрыть, свернуть, сходить по ссылке — им
  /// всё равно, есть ли в ветвях файлы, важно лишь, что это ветви.
  bool get isTree => this == tree || this == branches;

  static RowsKind? byName(String value) {
    for (final kind in values) {
      if (kind.name == value) {
        return kind;
      }
    }
    return null;
  }
}
