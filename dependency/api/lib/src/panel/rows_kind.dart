/// Чем набираются строки панели.
///
/// Вид сам говорит, что ему нужно: таблице и краткому виду — содержимое
/// каталога, дереву — развёрнутые ветви (`docs/spec/panel-node-list.md`, §3).
/// Ядро при этом не знает ни одного вида по имени: оно знает **набор строк**.
enum RowsKind {
  /// Один каталог: то, чем панель жила до сих пор.
  listing,

  /// Дерево: набор корней, развёрнутый построчно.
  tree;

  static RowsKind? byName(String value) {
    for (final kind in values) {
      if (kind.name == value) {
        return kind;
      }
    }
    return null;
  }
}
