// Пока набросок и рабочий код живут рядом, одноимённое приезжает из обоих:
// у наброска свой [OperationState]. Уйдёт вместе с переносом.
// ViewportPosition и ViewportState уже переехали в настоящий API и берутся
// оттуда; у наброска остался свой OperationState — до своего переезда.
import 'package:fc_api/fc_api.dart' hide OperationState;
import 'package:flutter/widgets.dart';

import 'operation.dart';

/// Область на экране над функциональными клавишами.
abstract interface class ViewPort {
  ViewportPosition get position;

  /// Что показано сейчас: наложение, если оно есть, иначе панель-основание.
  ViewportState get state;

  /// Забирает ли область системный фокус, когда становится активной.
  ///
  /// Панелям он не нужен: какая область активна, знает приложение, а нажатия
  /// разбирает ранний обработчик. Редактору нужен — внутри поле ввода, и
  /// события должны до него доходить. Умолчания нет намеренно.
  bool get takesKeyboard;
}

/// Описание окна команды.
///
/// Раму, заголовок и затемнение рисует ядро; что внутри — решает тот, кто окно
/// показывает.
@immutable
class DialogSpec {
  const DialogSpec({
    required this.title,
    required this.content,
    this.area = DialogArea.window,
    this.takesFocus = false,
  });

  /// Заголовок в раме.
  ///
  /// Строка, а не геттер, — и это решено, а не забыто. Цена известна: при
  /// переключении языка (Б1) подписи внутри окна сменятся, а заголовок над
  /// ними — нет, до переоткрытия. Принято: язык меняют на экране настроек, а
  /// это экран, не окно, и заставать открытое окно ему обычно негде.
  final String title;

  final Widget content;

  /// Над какой частью окна приложения встаёт окно команды. «Открыть путь в
  /// левой» и «в правой» иначе неотличимы на вид.
  final DialogArea area;

  /// Ставит ли фокус содержимое само — например, в поле ввода.
  ///
  /// false — фокус получает первый элемент обхода: иначе клавиши уходили бы в
  /// панели, а окно осталось бы глухим к Enter и Esc.
  final bool takesFocus;
}

/// Рабочая область приложения: что где стоит и кому принадлежит ввод.
abstract interface class ApplicationView implements Listenable {
  /// Всплывающие сообщения: сказать о том, что случилось и уже закончилось.
  Toasts get toasts;

  /// Что показано в области; null — область пуста и не рисуется.
  ViewPort? viewportAt(ViewportPosition position);

  /// Панель, показанная в области **сейчас**, — верх её стопки; null, если
  /// там не панель.
  ///
  /// Верх, а не дно: наложение скрывает панель целиком. Пока поверх правой
  /// области показан просмотрщик, копировать туда нечего — и `F5` становится
  /// невыполнимой сам собой, без отдельной проверки. Что показано, то и есть.
  ///
  /// Отсюда команды берут источник и приёмник:
  /// `panelAt(view.sourceArea)` и `panelAt(view.sourceArea.opposite)`.
  /// Объекты, с которыми работать, даёт сама панель: помеченные, а если
  /// пометки нет — узел под курсором.
  ///
  /// «Панель есть» — это ещё не «в неё можно писать». Результаты поиска (Д) —
  /// обычная панель, и копировать **из** них можно; приёмником они быть не
  /// могут, потому что их провайдер записи не реализует и `Panel.editor` у них
  /// null. Возможность даёт интерфейс, а не флаг: про флаг можно соврать, про
  /// отсутствие метода нельзя. Команде остаётся проверить `editor` у
  /// приёмника, а не только у источника.
  Panel? panelAt(ViewportPosition position);

  /// Заменяет то, что стоит в области, — дно её стопки.
  ///
  /// Прежнее закрывается ([ViewportState.close]) и не возвращается: это выбор,
  /// а не временное перекрытие. Так меняют вид панели — таблица, дерево,
  /// миниатюры (Г5), — и потому же он живёт в настройках панели и переживает
  /// перезапуск.
  ///
  /// Наложения, если они были, снимаются вместе с прежним дном.
  void setViewportContent(ViewportPosition position, ViewportState state);

  /// Кладёт временное содержимое **поверх** того, что в области стоит.
  ///
  /// Под наложением всё живо: каталог, курсор, пометка, колонки, аренда, — и
  /// [popViewportContent] открывает ровно то, что было. Так показывают быстрый
  /// просмотр (Г4), результаты поиска (Д) и полноэкранные просмотрщик с
  /// редактором. Ничего из этого не сохраняется между запусками.
  ///
  /// У [ViewportPosition.fullscreen] стопка запоминает, какая область была
  /// активна до этого: полноэкранное по определению забирает ввод себе, а
  /// снявшись — обязано его вернуть. Иначе приложение перестаёт слышать
  /// клавиатуру целиком.
  ///
  /// У остальных областей активность не трогается: быстрый просмотр в
  /// противоположной панели ставят, не уводя курсор из файловой.
  void pushViewportContent(ViewportPosition position, ViewportState state);

  /// Снимает верхнее наложение и закрывает его.
  ///
  /// На дне не снимает ничего: у [ViewportPosition.left] и
  /// [ViewportPosition.right] панель убрать нельзя — только заменить.
  /// У [ViewportPosition.fullscreen] дна нет, и последний снятый слой
  /// оставляет область пустой.
  void popViewportContent(ViewportPosition position);

  /// Область, которой принадлежит ввод.
  ///
  /// Не системный фокус Flutter, а состояние приложения: панель рисует курсор
  /// активной, потому что она названа здесь. От неё же считается слой привязок
  /// клавиш.
  ViewportPosition get activeArea;

  /// Панель-источник: последняя из [ViewportPosition.left] и
  /// [ViewportPosition.right], которой принадлежал ввод.
  ///
  /// Отдельно от [activeArea], потому что ввод уходит и туда, где панели нет:
  /// в командную строку, в полноэкранный просмотрщик. Источник файловой
  /// операции при этом никуда не девается — иначе `F5`, нажатый из командной
  /// строки, оказался бы невыполнимым.
  ViewportPosition get sourceArea;

  /// Единственный вход: выставляет [activeArea] и просит системный фокус для
  /// виджета области.
  ///
  /// Двумя вызовами эти состояния разъедутся, поэтому вход один.
  ///
  /// Нажатие разбирается тремя уровнями, и порядок между ними существенен:
  ///
  /// 1. **Рано** (`FocusManager.addEarlyKeyEventHandler`) — привязки
  ///    приложения, в контексте содержимого активной области. Пока открыто
  ///    окно, этот уровень молчит: клавиши принадлежат окну. Пока панель
  ///    занята, действует только отмена.
  /// 2. **Дерево фокуса** — окно, поле ввода, прокрутка берут своё. Сюда же
  ///    попадает `Esc`, закрывающий верхнее окно, и печать в редакторе.
  /// 3. **Поздно** (корневой `Focus.onKeyEvent`, на всплытии) — `Esc`, который
  ///    никто не взял, гасится здесь и наружу не уходит. AppKit понимает
  ///    `Cmd+.` как «отменить» и присылает в ответ `Escape`; вернёшь его
  ///    неразобранным — получишь тридцать тысяч событий подряд, каждое из
  ///    которых отменяет начатое чтение каталога.
  ///
  /// Гасить `Esc` на первом уровне нельзя: тогда он никогда не дойдёт до окна
  /// и до вопроса. Все прочие непривязанные клавиши обязаны пройти все три
  /// уровня и уйти в ОС — `Cmd+Q` и меню Flutter спрашивает у приложения
  /// раньше строки меню, и «обработано» их отменяет.
  void setFocus(ViewportPosition position);

  /// Доля ширины окна под левой областью.
  double get leftRightSplitRatio;

  void setLeftRightSplitRatio(double value);

  /// Последняя известная геометрия окна.
  WindowGeometry? get windowGeometry;

  /// Показывает окно и возвращает его идентификатор.
  ///
  /// Идентификатор держит **состояние окна**: команда — прототип и хранить его
  /// не может. Присваивается сразу после вызова, до первого кадра:
  ///
  /// ```dart
  /// final state = CopyDialogState(…);
  /// state.dialogId = view.showDialog(DialogSpec(content: CopyDialog(state), …));
  /// ```
  ///
  /// Окна складываются в стопку (`CommandService.openDialogs`): окно вправе
  /// поднять дочернее — выбор каталога, подтверждение, — и клавиши принадлежат
  /// верхнему.
  ///
  /// Окно **не область**: ни [activeArea], ни [sourceArea] оно не меняет.
  /// Поэтому команда, запущенная из списка команд (А4), видит ту же панель,
  /// что и клавиша, — хотя ввод в этот момент был в окне списка.
  String showDialog(DialogSpec spec);

  /// Поднимает окно работы, которая встала и ждёт человека.
  ///
  /// Вид находится по типу того, что операция выставила
  /// ([InteractiveOperationStatus.request]), а не по тому, чья это работа, —
  /// поэтому поднять может кто угодно: кнопка в статусной области, панель,
  /// дожидающаяся чтения каталога, тест.
  ///
  /// Без этого вход в зашифрованный архив был бы невозможен: пароль спрашивает
  /// модуль архиватора, а ждёт чтения панель, и про архивы она ничего не знает.
  void showAttention(Operation operation);

  void closeDialog(String dialogId);
}

/// Приложение целиком — основное API для реализации команд, сервисов и операций.
abstract interface class Application implements Listenable {
  ApplicationView get view;

  /// Действия приложения и клавиши за ними. Через него модуль ставит свои
  /// команды, а нижний ряд кнопок узнаёт, что висит на `F5` прямо сейчас.
  CommandService get commands;

  /// Заведённые работы: их показывают статусные области.
  Operations get operations;

  /// Оформление приложения: какое есть и какое выбрано.
  ThemeService get theme;

  /// Ошибки, которые никто не поймал: показать человеку, а не только записать
  /// в журнал.
  Errors get errors;

  /// Текущее состояние приложения в виде сохраняемых настроек.
  AppSettings get settings;

  /// Раздел настроек модуля. Имя — идентификатор модуля.
  SettingsScope moduleSettings(String namespace);

  /// Запуск: восстановление окна и каталогов.
  Future<void> start();

  /// Завершение: сохранение настроек и остановка операций.
  Future<void> shutdown();
}
