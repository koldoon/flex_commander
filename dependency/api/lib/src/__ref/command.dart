import 'package:flutter/foundation.dart';

import 'package:fc_api/fc_api.dart' show KeyCombination, ViewportPosition, ViewportState;

import 'application.dart';

/// Как создать действие приложения. Зависимости в фабрику подставляет
/// контейнер.
///
/// Фабрика без аргументов: всё, что команде нужно снаружи, она получает при
/// создании — окружение модуля и само приложение.
typedef AppCommandFactory = AppCommand Function();

/// Значения, с которыми команда выполняется.
///
/// Их можно задать откуда угодно: из окна команды, из меню, из будущей
/// командной строки или из сценария. Аналог `IParameters` референса.
///
/// Это **аргументы**, а не контекст: условия («где курсор», «что помечено»)
/// команда читает из приложения живьём, а параметрами ей задают то, чего в
/// состоянии нет — какую область открыть, какой символ набрали.
class CommandParameters {
  final Map<String, Object?> _values = {};

  Map<String, Object?> get values => Map.unmodifiable(_values);

  void set(String name, Object? value) => _values[name] = value;

  T? get<T>(String name) {
    final value = _values[name];
    return value is T ? value : null;
  }
}

/// Один запуск команды.
///
/// На прототипе ([AppCommand]) этому места нет: `Cmd+F1` и `Cmd+F2`, нажатые
/// подряд, дадут два прогона с разными областями.
class CommandInvocation {
  const CommandInvocation({required this.parameters, this.operationId});

  /// Значения запуска: из привязки, из списка команд, из сценария.
  final CommandParameters parameters;

  /// Операция, к окну которой возвращаются, — кнопка у полоски прогресса в
  /// статусной области. null — обычный запуск.
  ///
  /// Одна и та же команда и заводит работу, и открывает окно уже идущей:
  /// найти операцию по идентификатору, собрать для неё окно и показать.
  final String? operationId;
}

/// Действие приложения.
///
/// **Прототип:** один долгоживущий объект на команду. Состояния прогона он не
/// держит — оно живёт в состоянии окна (пока форма не отправлена) и в операции
/// (после). Поэтому нижний ряд кнопок и список команд спрашивают у него
/// [label], [description] и [isExecutable] сколько угодно раз, ничего не
/// создавая.
///
/// **Команда не знает, чем её вызвали.** Условия она читает из приложения
/// живьём, значения запуска приходят в [CommandInvocation]. Ни привязок клавиш,
/// ни места в нижнем ряду она не объявляет.
///
/// **Окно — вещь необязательная.** Команду можно выполнить и без него: задать
/// значения и вызвать [execute]. Так её вызовут список команд, сценарий или
/// будущая командная строка. Окно только собирает те же самые значения и
/// заводит ту же самую работу.
///
/// **Составлять команды из команд пока нечем, и это намеренно.** Порт
/// командного фреймворка в API был, и за всё время им никто не воспользовался.
/// Когда понадобятся макросы, писать их придётся под то, что у команд есть на
/// самом деле: окно, вопросы по ходу работы и операцию со своей отменой.
abstract class AppCommand {
  /// Стабильный идентификатор для настроек, логов и поиска команды в коде:
  /// `panel.open`, `file.copy`. Пользователю не показывается.
  String get id;

  /// Название команды для пользователя: подпись кнопки внизу окна, заголовок
  /// её окна и строка в списке команд. В интерфейсе видно именно его — ни [id],
  /// ни имя класса наружу не показываются.
  ///
  /// Геттер, а не поле: прототип переживает переключение языка.
  String get label;

  /// Что команда делает — одной строкой, для списка команд и справки.
  ///
  /// Пустая строка допустима: у `Cursor up` объяснять нечего, и придумывать
  /// текст ради заполненной колонки незачем.
  String get description => '';

  /// Заголовок окна команды.
  ///
  /// По умолчанию — [label], но команде бывает что уточнить: «Copy «notes.txt»»
  /// понятнее, чем просто «Copy».
  String get dialogTitle => label;

  /// Вызывается один раз при установке прототипа. false — команда не
  /// устанавливается: нет PTY, нет внешнего 7z, платформа не та.
  bool init();

  /// Можно ли выполнить прямо сейчас.
  ///
  /// Проверяет текущее состояние приложения и возвращает true или false.
  /// Для команд, которые выполниться не могут, ядро обычно генерирует короткий
  /// звуковой сигнал.
  ///
  /// Зовётся часто и должна быть дешёвой: нижний ряд кнопок спрашивает на
  /// каждой перерисовке, а список команд — по всем командам на каждый
  /// набранный символ.
  bool isExecutable();

  /// Выполняет работу.
  ///
  /// Задачи команды:
  /// - собрать состояние окна из живых условий и показать окно через
  ///   [ApplicationView.showDialog] — дальше управление у окна;
  /// - либо, если задан [CommandInvocation.operationId], найти идущую операцию,
  ///   собрать для неё окно и показать так же;
  /// - либо отработать быстро и молча (передвинуть курсор) и завершиться.
  ///
  /// Саму работу заводит окно: оно создаёт операцию, регистрирует её и дальше
  /// показывает её ход. Окна в процессе своей жизни могут поднимать другие
  /// окна (подтверждения) и вообще менять состояние приложения.
  Future<void> execute(CommandInvocation invocation);
}

/// Привязка комбинации клавиш к команде.
///
/// Привязка не принадлежит команде: её ставит, хранит и разбирает реестр. Так
/// их можно менять из настроек, не трогая код команд, а сами команды остаются
/// самостоятельными действиями и не знают, чем их вызвали.
class KeyBinding {
  KeyBinding(
    this.keys,
    this.commandId, {
    this.parameters = const {},
    this.nameMatch,
    this.characterParam,
    this.inContent,
  });

  /// Действует, только когда в активной области содержимое типа [S].
  ///
  /// `KeyBinding.inState<ViewerState>('F5', 'text.format')` — «Format / Raw»
  /// в просмотрщике, при том что `F5` в панелях копирует.
  static KeyBinding inState<S extends ViewportState>(
    KeyCombination keys,
    String commandId, {
    Map<String, Object?> parameters = const {},
    RegExp? nameMatch,
    String? characterParam,
  }) => KeyBinding(
    keys,
    commandId,
    parameters: parameters,
    nameMatch: nameMatch,
    characterParam: characterParam,
    inContent: (state) => state is S,
  );

  final KeyCombination keys;

  /// Идентификатор команды, а не сама команда: привязки хранятся в настройках,
  /// где живут только идентификаторы.
  final String commandId;

  /// Значения, с которыми команда выполняется по этой привязке. Позволяет
  /// повесить одну команду на разные клавиши с разными значениями — например,
  /// «открыть путь» в названной области.
  final Map<String, Object?> parameters;

  /// Необязательный фильтр по имени объекта под курсором: разные команды на
  /// `Enter` для `*.app`, `*.zip` и обычных файлов. Это условие **выбора**
  /// команды, а не данные для неё.
  final RegExp? nameMatch;

  /// Имя параметра, в который кладётся набранный символ; null у обычных
  /// привязок. Переход к имени по первой букве обходится одной привязкой
  /// вместо сорока.
  final String? characterParam;

  /// Действует ли привязка при таком содержимом активной области;
  /// null — действует везде.
  ///
  /// Именно по **содержимому**, а не по позиции: в [ViewportPosition.fullscreen]
  /// бывает и просмотрщик, и редактор, и терминал, а одна и та же клавиша
  /// значит в них разное. Задаётся через [KeyBinding.inState].
  ///
  /// «Везде» — это в том числе там, где области нет вовсе: тест состояния,
  /// сценарий, командная строка. Контекст — про то, кому принадлежит клавиша,
  /// а не про то, можно ли выполнить команду; последнее решает
  /// [AppCommand.isExecutable].
  final bool Function(ViewportState state)? inContent;
}

/// Действия приложения и клавиши за ними.
abstract interface class CommandService implements Listenable {
  /// Все установленные команды: список команд (А4) и справка по `F1`.
  List<AppCommand> get all;

  AppCommand? byId(String id);

  /// Привязка, действующая прямо сейчас.
  ///
  /// Реестр перебирает их в порядке регистрации и берёт первую, чей контекст
  /// подходит **и** чья команда выполнима. На этом держится Г5: `Left` в
  /// кратком виде двигает курсор по колонкам, а там, где такой команды нет,
  /// срабатывает следующая привязка — «в начало строки». Никаких «если вид
  /// такой-то» внутри одной команды.
  KeyBinding? bindingFor(KeyCombination keys);

  /// Запускает команду — тем же путём, каким её запускает клавиша.
  ///
  /// Ошибку показывает тот, у кого есть где: окно команды держит её в своём
  /// состоянии, работа — в своём статусе, чтение каталога — в `Panel.error`.
  /// Всё, чему места не нашлось, уходит в `Errors`: молча проглоченная ошибка
  /// выглядит как «ничего не произошло», а это худшее, что может быть.
  Future<void> run(String id, CommandInvocation invocation);

  /// Какие клавиши висят на этой команде.
  ///
  /// Обратный поиск к [bindingFor]: список команд (А4) показывает клавишу
  /// рядом со строкой, а справка по `F1` — всю таблицу. Команда своих
  /// привязок не знает и знать не должна, поэтому спрашивают у реестра.
  List<KeyBinding> bindingsOf(String commandId);

  /// Открытые окна, сверху вниз: последнее показанное — первое.
  ///
  /// Стопка, а не список: окно может поднять дочернее (выбор каталога,
  /// подтверждение), и клавиши принадлежат верхнему. Пока стопка непуста,
  /// привязки приложения не действуют вовсе — иначе панель отзывалась бы на
  /// ввод из-под чужого окна.
  List<String> get openDialogs;
}
