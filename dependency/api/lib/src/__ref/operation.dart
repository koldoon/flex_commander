import 'dart:async';

import 'package:fc_api/fc_api.dart' show OperationOption;
import 'package:flutter/foundation.dart';

import 'application.dart';

/// Длительная работа.
///
/// Про приложение не знает ничего: ни областей, ни панелей, ни идентификатора
/// запуска. Идентификатор минтит реестр ([Operations.start]), он же помнит,
/// где показывать ход и какой командой открывать окно.
///
/// Операция, которую не зарегистрировали, просто идёт молча и нигде не
/// показывается: так читают файл для быстрого просмотра по движению курсора —
/// полоска прогресса на каждое нажатие стрелки была бы мусором.
abstract interface class Operation<P, R> {
  OperationStatus get status;

  Operation? get parent;

  /// Вход — только данные.
  ///
  /// Ни приложения, ни областей, ни панелей в типе [P] быть не должно: живое
  /// состояние читает команда, до запуска, а операция работает со снимком.
  /// Иначе фоновое копирование сломается, как только панель выйдет из архива.
  Future<R> execute(P params);
}

abstract interface class CancellableOperation<P, R> extends Operation<P, R> {
  /// Мягкая отмена: превращается в обычную заявку и потому останавливает
  /// работу — вопрос по своей природе её останавливает. Замечается на
  /// ближайшей контрольной точке, а не мгновенно.
  ///
  /// Это и есть `Esc` в окне идущей работы: не «спрятать», а «прервать?».
  /// Работа файлового менеджера необратима, а `Esc` нажимают не глядя, и когда
  /// его жмут посреди копирования, имеют в виду «останови», а не «убери с
  /// глаз». Спрятать — действие более редкое и осознанное, ему место на
  /// кнопке «в фон», которая отправляет работу в фон явно
  /// ([Operations.sendToBackground]), а не просто закрывает окно.
  Future<void> requestCancel();

  /// Жёсткая и молчаливая: закрытие окна, выход из приложения. Может занимать
  /// время (закрытие дескрипторов, завершение соединения), поэтому Future.
  Future<void> cancel();
}

/// Операция, включающая несколько этапов с индивидуальным статусом и выполняемые
/// последовательно. Например, упаковка zip архива с последующей перепаковкой
/// вышестоящего архива.
abstract interface class MultistageOperation<P, R> extends Operation<P, R> {
  /// Любые две операции могут объединяться в цепочку используя [Operation.parent],
  /// но stages отражает именно *видимые для пользователя* операции.
  ///
  /// Список может **расти по ходу**: второй этап появляется, только если в деле
  /// оказался пакетный приёмник, — заранее он не известен.
  List<StageOperationStatus> get stages;
}

enum OperationState {
  idle,
  pending,
  processing,

  /// Работа встала и ждёт человека. Ждёт столько, сколько нужно: ответа
  /// «по умолчанию» нет.
  userActionRequired,
  complete,
  canceled,
  error;

  bool get isFinished => this == complete || this == canceled || this == error;
}

/// Статус недетерминированной операции (нет детализации по прогрессу).
///
/// Этого хватает универсальному месту — компактной полоске в статусной области:
/// по [state] она понимает, показывать ли кнопку «нужен ответ», и до самой
/// заявки не добирается. Окно операции строит её команда, знает её тип и
/// приводит к нужному подтипу один раз.
abstract interface class OperationStatus implements Listenable {
  OperationState get state;

  /// Что происходит прямо сейчас — короткой строкой.
  String get message;

  // Троттлинг перерисовки — обязанность реализации, а не того, кто рисует:
  // копирование отчитывается на каждый блок, и уведомлять на каждый отчёт
  // значит положить окно. Принимать все отчёты, уведомлять не чаще ~50 мс,
  // последнее состояние досылать таймером.
}

/// Подтип говорит про **род** работы; null внутри — про «пока неизвестно».
///
/// Копирование измеримо по природе, поэтому тип правильный всегда. А есть ли
/// скорость прямо сейчас — факт времени выполнения: первые полсекунды считать
/// не из чего, и вернуть там 0 значило бы соврать.
abstract interface class ComputableOperationStatus extends OperationStatus {
  /// 0…100; null — прогресс неопределённый.
  num? get percentProgress;
}

abstract interface class MeasurableOperationStatus extends OperationStatus {
  /// В зависимости от контекста может иметь разные величины измерения:
  /// items/s | bytes/s. null — считать пока не из чего.
  num? get speed;

  /// Сколько ещё ждать; null — оценить не из чего.
  Duration? get remaining;
}

/// Статус операции по передаче для одного элемента.
abstract interface class SingleTransferOperationStatus extends ComputableOperationStatus {
  /// Объект, который обрабатывается прямо сейчас; пустая строка — работа
  /// не разбита на объекты.
  String get itemName;

  int get bytesTransferred;

  /// null — размер не известен и известен не будет: удаление в корзину,
  /// источник без размеров.
  int? get bytesTotal;
}

/// Статус операции для множества элементов.
abstract interface class MultipleTransferOperationStatus extends ComputableOperationStatus {
  int get itemsTransferred;

  /// null — ещё считается фоном. Обход большого дерева сам по себе долгий,
  /// и операции считают его, не задерживая начало работы.
  int? get itemsTotal;

  /// Досчитан ли [itemsTotal] до конца. Пока нет — это нижняя оценка, и
  /// показывать её как окончательную нельзя.
  bool get totalIsFinal;
}

abstract interface class StageOperationStatus extends OperationStatus {
  String get name;
}

/// То, из-за чего работа встала и ждёт человека.
///
/// Сам по себе — только **сигнал**: ни текста, ни полей, ни вариантов ответа
/// здесь нет. Всё это лежит в подтипе, который заводит тот, кто спрашивает, и
/// для которого он же регистрирует вид (`registry.view<T>()`). Так архиватор
/// спрашивает пароль формой из двух полей, движок переноса — конфликтом с
/// датами и размерами обоих файлов, а ядру не нужно знать ни про то, ни про
/// другое.
///
/// Поднять окно может кто угодно ([ApplicationView.showAttention]): вид
/// находится по типу, а не по тому, чья это работа. Иначе вход в зашифрованный
/// архив был бы невозможен — спрашивает модуль архиватора, а ждёт чтения
/// каталога панель, и про архивы она ничего не знает.
///
/// **Операция всегда ждёт ответа.** Ответа «по умолчанию, раз никто не
/// слушает» нет: решение принимает человек, иначе это не вопрос, а видимость
/// вопроса.
///
/// Работа, упёршаяся в вопрос при закрытом окне, показывает кнопку в статусной
/// области и **не** выпрыгивает окном сама: вырывать человека из другого дела
/// нельзя. Но и молчать нельзя — иначе работа стоит, а он этого не заметит,
/// поэтому в момент, когда она упёрлась впервые, показывается тост.
///
/// Отсюда правило для того, кто заводит работу: **спрашивать вправе только та
/// работа, которую ждут.** Ждут её либо через `await`, либо потому, что она
/// зарегистрирована и видна в статусной области. Работа, запущенная и
/// брошенная — определение типа по содержимому, подсчёт размеров, — спросить
/// не может: она повиснет навсегда и молча. Если ей нужно решение, она обязана
/// закончиться ошибкой.
abstract interface class UserActionRequest {}

/// Готовая заявка для простого вопроса: сообщение и кнопки.
///
/// Вид для неё рисует ядро, поэтому свой заводить не надо: перезаписать,
/// пропустить, повторить, прервать — всё это кнопки и строка.
class ChoiceRequest implements UserActionRequest {
  ChoiceRequest({
    required this.message,
    required this.options,
    required this.enterOption,
    this.escapeOption,
    this.inputLabel,
  }) : assert(options.isNotEmpty, 'Нужен хотя бы один вариант ответа');

  final String message;

  final List<OperationOption> options;

  /// Какую кнопку подсветить и нажать по Enter. У конфликта имён это Skip:
  /// молча затирать чужие файлы нельзя.
  ///
  /// Обязательный, а не «последний по умолчанию»: забыть его — ровно тот
  /// способ, которым однажды затрут чужие файлы. Это только про Enter;
  /// ответа «раз никто не слушает» не существует, операция всегда ждёт
  /// человека.
  final OperationOption enterOption;

  /// Что означает Esc; null — ничего, и вопрос придётся закрыть кнопкой.
  ///
  /// Отдельно от [enterOption], потому что совпадают они не всегда: у вопроса
  /// «прервать работу?» Enter прерывает, а Esc отказывается прерывать.
  final OperationOption? escapeOption;

  /// Подпись поля ввода; null — вопрос только из кнопок. Так спрашивают новое
  /// имя при конфликте. Пароли сюда не относятся: у них своя форма, и заводит
  /// её тот, кто спрашивает.
  final String? inputLabel;

  String get text => _text;
  String _text = '';

  final Completer<OperationOption> _answer = Completer<OperationOption>();

  Future<OperationOption> get answer => _answer.future;

  bool get isAnswered => _answer.isCompleted;

  void respond(OperationOption option, {String text = ''}) {
    if (_answer.isCompleted) {
      return;
    }
    // Записывается до ответа: тот, кто ждёт answer, читает text сразу же.
    _text = text;
    _answer.complete(option);
  }
}

/// Заведённая работа: сама операция и то, что про неё знает реестр.
class OperationRun {
  const OperationRun({required this.runId, required this.operation, required this.commandId, this.owner});

  final String runId;

  final Operation operation;

  /// Кем открыть окно **прогресса** этой работы.
  ///
  /// Команда получает `CommandInvocation.operationId`, находит работу и
  /// собирает для неё окно. Сама операция про команды ничего не знает.
  ///
  /// За вопросы он не отвечает: окно заявки поднимает
  /// [ApplicationView.showAttention], и вид там находится по типу заявки —
  /// спрашивать может модуль, к этой команде отношения не имеющий.
  final String commandId;

  /// Под какой панелью показывать полоску; null — работа не в фоне.
  ///
  /// Заведённая работа в статусной области **не** появляется: она идёт со
  /// своим окном. Полоска возникает только после
  /// [Operations.sendToBackground], и область называют там же — где показывать,
  /// имеет смысл только когда показывают.
  ///
  /// Привязка к позиции, а не к объекту панели: панель заменяема, позиция нет.
  final ViewportPosition? owner;

  bool get isInBackground => owner != null;

  OperationStatus get status => operation.status;
}

/// Заведённые работы.
abstract interface class Operations implements Listenable {
  /// Заводит работу и начинает её.
  ///
  /// Идентификатор минтит реестр: на самой операции его нет — иначе непонятно,
  /// кто присваивает. Заводят затем, чтобы работу можно было **найти**: собрать
  /// ей окно заново, поднять заявку, дождаться.
  ///
  /// В статусной области её после этого нет — для этого есть
  /// [sendToBackground]. Работа, которую и находить незачем (чтение файла для
  /// быстрого просмотра, определение типа по содержимому), не заводится вовсе:
  /// у неё просто зовут `execute`.
  String start<P, R>(Operation<P, R> operation, P params, {required String commandId});

  /// Убирает окно и оставляет работу идти: полоска появляется в статусной
  /// области под названной панелью.
  ///
  /// Отдельное действие, а не следствие закрытия окна: работа, идущая молча и
  /// невидимо, — худшее из состояний. Обычно это кнопка «в фон» в окне
  /// прогресса; предлагать её или нет, решает само окно — окну ввода прятаться
  /// некуда, оно ждёт ответа.
  ///
  /// Владельцем становится [ApplicationView.sourceArea] — та панель, с которой
  /// работу запустили. Отсюда ответ на «копирование left→right — чья колонка»:
  /// левая.
  void sendToBackground(String runId, {required ViewportPosition owner});

  /// Работы, которые показывает статусная область под этой панелью, — только
  /// ушедшие в фон.
  List<OperationRun> at(ViewportPosition position);

  OperationRun? byId(String runId);

  /// Убирает работу из списка: её полоска отжила своё.
  ///
  /// Зовёт ядро, когда состояние стало финальным, — а не тот, кто работу
  /// заводил: он мог уйти раньше, чем она кончилась, в этом весь смысл фона.
  void forget(String runId);
}
