import 'package:fc_api/fc_api.dart' show OperationStatus, StageOperationStatus, ViewportPosition;
import 'package:flutter/foundation.dart';

/// Длительная работа.
///
/// Про приложение не знает ничего: ни областей, ни панелей, ни идентификатора
/// запуска. Идентификатор минтит реестр ([Operations.start]), он же помнит,
/// где показывать ход и какой командой открывать окно.
///
/// Операция, которую не зарегистрировали, просто идёт молча и нигде не
/// показывается: так читают файл для быстрого просмотра по движению курсора —
/// полоска прогресса на каждое нажатие стрелки была бы мусором.
abstract interface class Operation<P, R> {
  OperationStatus get status;

  Operation? get parent;

  /// Вход — только данные.
  ///
  /// Ни приложения, ни областей, ни панелей в типе [P] быть не должно: живое
  /// состояние читает команда, до запуска, а операция работает со снимком.
  /// Иначе фоновое копирование сломается, как только панель выйдет из архива.
  Future<R> execute(P params);
}

abstract interface class CancellableOperation<P, R> extends Operation<P, R> {
  /// Мягкая отмена: превращается в обычную заявку и потому останавливает
  /// работу — вопрос по своей природе её останавливает. Замечается на
  /// ближайшей контрольной точке, а не мгновенно.
  ///
  /// Это и есть `Esc` в окне идущей работы: не «спрятать», а «прервать?».
  /// Работа файлового менеджера необратима, а `Esc` нажимают не глядя, и когда
  /// его жмут посреди копирования, имеют в виду «останови», а не «убери с
  /// глаз». Спрятать — действие более редкое и осознанное, ему место на
  /// кнопке «в фон», которая отправляет работу в фон явно
  /// ([Operations.sendToBackground]), а не просто закрывает окно.
  Future<void> requestCancel();

  /// Жёсткая и молчаливая: закрытие окна, выход из приложения. Может занимать
  /// время (закрытие дескрипторов, завершение соединения), поэтому Future.
  Future<void> cancel();
}

/// Операция, включающая несколько этапов с индивидуальным статусом и выполняемые
/// последовательно. Например, упаковка zip архива с последующей перепаковкой
/// вышестоящего архива.
abstract interface class MultistageOperation<P, R> extends Operation<P, R> {
  /// Любые две операции могут объединяться в цепочку используя [Operation.parent],
  /// но stages отражает именно *видимые для пользователя* операции.
  ///
  /// Список может **расти по ходу**: второй этап появляется, только если в деле
  /// оказался пакетный приёмник, — заранее он не известен.
  List<StageOperationStatus> get stages;
}

// Состояния и статусы — OperationState, OperationStatus и вся решётка
// подтипов — уже переехали в настоящий API и берутся оттуда.

// Заявки — UserActionRequest и OperationRequest — уже переехали в настоящий
// API и берутся оттуда. Правило, ради которого они здесь стояли: работа
// всегда ждёт человека, а спрашивать вправе только та работа, которую ждут.
// Запущенная и брошенная спросить не может — она повиснет навсегда и молча.

/// Заведённая работа: сама операция и то, что про неё знает реестр.
class OperationRun {
  const OperationRun({required this.runId, required this.operation, required this.commandId, this.owner});

  final String runId;

  final Operation operation;

  /// Кем открыть окно **прогресса** этой работы.
  ///
  /// Команда получает `CommandInvocation.operationId`, находит работу и
  /// собирает для неё окно. Сама операция про команды ничего не знает.
  ///
  /// За вопросы он не отвечает: окно заявки поднимает
  /// [ApplicationView.showAttention], и вид там находится по типу заявки —
  /// спрашивать может модуль, к этой команде отношения не имеющий.
  final String commandId;

  /// Под какой панелью показывать полоску; null — работа не в фоне.
  ///
  /// Заведённая работа в статусной области **не** появляется: она идёт со
  /// своим окном. Полоска возникает только после
  /// [Operations.sendToBackground], и область называют там же — где показывать,
  /// имеет смысл только когда показывают.
  ///
  /// Привязка к позиции, а не к объекту панели: панель заменяема, позиция нет.
  final ViewportPosition? owner;

  bool get isInBackground => owner != null;

  OperationStatus get status => operation.status;
}

/// Заведённые работы.
abstract interface class Operations implements Listenable {
  /// Заводит работу и начинает её.
  ///
  /// Идентификатор минтит реестр: на самой операции его нет — иначе непонятно,
  /// кто присваивает. Заводят затем, чтобы работу можно было **найти**: собрать
  /// ей окно заново, поднять заявку, дождаться.
  ///
  /// В статусной области её после этого нет — для этого есть
  /// [sendToBackground]. Работа, которую и находить незачем (чтение файла для
  /// быстрого просмотра, определение типа по содержимому), не заводится вовсе:
  /// у неё просто зовут `execute`.
  String start<P, R>(Operation<P, R> operation, P params, {required String commandId});

  /// Убирает окно и оставляет работу идти: полоска появляется в статусной
  /// области под названной панелью.
  ///
  /// Отдельное действие, а не следствие закрытия окна: работа, идущая молча и
  /// невидимо, — худшее из состояний. Обычно это кнопка «в фон» в окне
  /// прогресса; предлагать её или нет, решает само окно — окну ввода прятаться
  /// некуда, оно ждёт ответа.
  ///
  /// Владельцем становится [ApplicationView.sourceArea] — та панель, с которой
  /// работу запустили. Отсюда ответ на «копирование left→right — чья колонка»:
  /// левая.
  void sendToBackground(String runId, {required ViewportPosition owner});

  /// Работы, которые показывает статусная область под этой панелью, — только
  /// ушедшие в фон.
  List<OperationRun> at(ViewportPosition position);

  OperationRun? byId(String runId);

  /// Убирает работу из списка: её полоска отжила своё.
  ///
  /// Зовёт ядро, когда состояние стало финальным, — а не тот, кто работу
  /// заводил: он мог уйти раньше, чем она кончилась, в этом весь смысл фона.
  void forget(String runId);
}
