/// Разбор имени файла — строки, а не узла.
///
/// Расширения у файла **нет**. Есть имя, а расширение — его толкование, и у
/// каждого толкователя оно своё: реестру провайдеров нужно последнее (`a.tar.gz`
/// монтируется как `gz`, а `tar` разбирается внутри), просмотрщику — последнее
/// в нижнем регистре против своего списка, панели — то, что уместно показать в
/// колонке. Поэтому здесь разбор строки, а у узла его нет вовсе.
library;

/// То, что после последней точки; пусто — расширения нет.
///
/// Имя, начинающееся с точки, расширения не имеет: `.gitignore` — это имя
/// целиком, а не файл `gitignore` неизвестного рода.
///
/// Длину не ограничивает и пробелов не боится: этим спрашивают «что это», а не
/// «как показать». Просмотрщику всё равно, длинный ли хвост, — он сверяется со
/// своим списком, и `png` там либо есть, либо нет.
String extensionOf(String name) {
  final dot = name.lastIndexOf('.');
  return dot <= 0 ? '' : name.substring(dot + 1);
}

/// Как имя делится на имя и расширение **для показа**.
///
/// Отдельно от [extensionOf], потому что вопрос другой: не «что это за файл», а
/// «что написать в колонках». Отсюда и правила, которых у первого нет, —
/// разумная длина, а позже и словарь составных расширений.
abstract interface class FileNaming {
  /// Имя без расширения и само расширение без точки.
  ({String base, String extension}) split(String name);
}

/// Правило референса: расширение — то, что после последней точки, если оно не
/// длиннее двенадцати знаков и без пробелов.
///
/// Длина и пробелы здесь не придирка, а защита от ложных срабатываний:
/// `Some file.doc backup` — это имя с точкой посередине, а не документ, и
/// показывать «расширение `doc backup`» было бы враньём.
class ReferenceFileNaming implements FileNaming {
  const ReferenceFileNaming();

  static final RegExp _extension = RegExp(r'^([^\/*?|]+)\.([^\/*?|\s]{1,12})$');

  @override
  ({String base, String extension}) split(String name) {
    final match = _extension.firstMatch(name);
    if (match == null) {
      return (base: name, extension: '');
    }
    final extension = match.group(2)!;
    return (base: name.substring(0, name.length - extension.length - 1), extension: extension);
  }
}
