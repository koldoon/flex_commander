/// Содержимое файла — то, чем его читают на экранной стороне.
///
/// Байты живут за границей: файл лежит в архиве, на сервере или на диске, и
/// добраться до него может только та сторона. Сюда они приезжают потоком, а
/// открывает его тот, кто показывает: тексту нужны строки, картинке — байты и
/// декодер, и читающий за них неизбежно стал бы `switch` по видам файлов
/// (`docs/spec/client-server.md`, §6.2).
abstract interface class Content {
  /// Сколько байт всего; отрицательное — неизвестно.
  int get length;

  /// Байты потоком.
  ///
  /// [offset] — сколько пропустить от начала. Не роскошь: без него не будет
  /// докачки, а на сети она нужна.
  ///
  /// Ошибка чтения приходит ошибкой потока, а не исключением отсюда: открыть
  /// файл и читать его — разные моменты времени.
  Stream<List<int>> read({int offset = 0});
}
