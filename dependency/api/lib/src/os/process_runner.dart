/// Запуск внешних программ.
///
/// Здесь только контракт: сам запуск платформенный, и его реализация — дело
/// модуля локальной файловой системы. Отделён он не ради красоты, а ради
/// проверяемости: модуль, который зовёт программу напрямую, нельзя проверить
/// на машине, где этой программы нет, — а именно так живут архиваторы и
/// сетевые источники.
abstract interface class ProcessRunner {
  /// Запустить и дождаться конца, собрав весь вывод.
  ///
  /// Для коротких команд: оглавление архива, проверка версии. Вывод длинной
  /// работы так собирать нельзя — он целиком окажется в памяти.
  Future<ProcessOutcome> run(String executable, List<String> arguments, {String? workingDirectory});

  /// Запустить и читать вывод по мере поступления.
  ///
  /// Для того, что течёт: распаковка в поток, упаковка с ходом работы.
  Future<ProcessSession> start(String executable, List<String> arguments, {String? workingDirectory});

  /// Полный путь к программе или null, если её нет.
  ///
  /// [extraDirectories] просматриваются после `PATH`. Это не прихоть: на macOS
  /// приложение, запущенное из Finder, наследует куцый системный `PATH` без
  /// `/opt/homebrew/bin` — и программа, которая прекрасно находится в
  /// терминале, из приложения не находится вовсе.
  Future<String?> which(String executable, {Iterable<String> extraDirectories = const []});
}

/// Завершившаяся программа: код возврата и весь её вывод.
class ProcessOutcome {
  const ProcessOutcome({required this.exitCode, this.stdout = '', this.stderr = ''});

  final int exitCode;
  final String stdout;
  final String stderr;

  /// Ноль — и только он. Ненулевой код каждая программа толкует по-своему, и
  /// решать, что он значит, должен тот, кто её звал.
  bool get ok => exitCode == 0;

  @override
  String toString() => 'ProcessOutcome($exitCode)';
}

/// Запущенная программа, вывод которой читают по мере поступления.
///
/// Потоки одноразовые: подписаться на каждый можно единожды — так устроены
/// каналы процесса, и прятать это за буфером значило бы держать в памяти всё,
/// что программа успела сказать.
///
/// **Читать нужно оба потока.** Программа, чей вывод никто не забирает, встанет
/// на заполненном канале и не завершится никогда.
abstract interface class ProcessSession {
  Stream<List<int>> get stdout;

  Stream<List<int>> get stderr;

  /// Код возврата; ждёт конца программы.
  Future<int> get exitCode;

  /// Прервать работу. Программа, которую уже нельзя убить, — не ошибка.
  Future<void> kill();
}
