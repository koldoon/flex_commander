/// Системный буфер обмена.
///
/// Интерфейс, а не прямой вызов Flutter, по той же причине, что и у остального
/// платформенного в API: буфером будут пользоваться многие — просмотрщик
/// копирует выделенное, панель будет копировать путь и список имён, — а в
/// тестах он обязан быть подставным. Прогон, трогающий настоящий буфер машины,
/// незаметно портит работу человеку за ней.
abstract interface class ClipboardService {
  /// Кладёт текст в буфер, вытесняя то, что там было.
  Future<void> writeText(String text);

  /// Текст из буфера; null — там пусто или лежит не текст.
  Future<String?> readText();
}
