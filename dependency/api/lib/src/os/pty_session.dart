import 'dart:typed_data';

/// Программа в псевдотерминале — то немногое, что от неё видно с обеих сторон.
///
/// Живёт она в ядре: псевдотерминал платформенный, и заводит его тот, у кого
/// есть где выполнять ([ShellHost] в `fc_core_api`). А разбирать её вывод —
/// дело экрана: управляющие последовательности, буфер прокрутки, клавиши
/// обратно. Поэтому сам канал — общий язык обеих сторон, и по ту сторону
/// границы его держит зеркало, устроенное разговором
/// (`docs/spec/client-server.md`, §5.1.5).
///
abstract interface class PtySession {
  /// Всё, что программа вывела, — байтами.
  ///
  /// Байтами, а не строками: в терминале ходит не текст, а поток с
  /// управляющими последовательностями, и многобайтный символ вполне может
  /// приехать разорванным между двумя порциями. Собирать его — дело того, кто
  /// разбирает поток.
  Stream<Uint8List> get output;

  /// Отправить программе ввод — то, что она увидит как набранное с клавиатуры.
  void write(Uint8List data);

  /// Размер окна: программа внутри о нём спрашивает и по нему верстает.
  ///
  /// Сообщать обязательно: без этого `vim` и `htop` считают, что перед ними
  /// восемьдесят на двадцать четыре, чем бы оно ни было на самом деле.
  void resize({required int columns, required int rows});

  /// Код возврата; ждёт конца программы. Оболочку закрывают `exit`.
  Future<int> get exitCode;

  /// Прервать работу. Программа, которую уже нельзя убить, — не ошибка.
  Future<void> kill();
}

/// Открытая оболочка: сам канал и то, что о ней известно.
///
/// Значение, а не сессия: разбор вывода, лента прокрутки и клавиши — дело
/// экрана, и заводит он их сам. Отсюда только то, чего экрану самому не узнать.
class ShellChannel {
  const ShellChannel({required this.pty, required this.label, this.program = '', required this.fresh});

  /// Байты наружу, клавиши внутрь, размер окна, конец.
  final PtySession pty;

  /// Как место называется: `localhost` или `user@host`.
  final String label;

  /// Чем оболочка запущена; пусто — не знаем (так на той стороне `ssh`).
  final String program;

  /// Только что запустилась. Уже жившей уговор о метках второй раз не шлют.
  final bool fresh;
}
