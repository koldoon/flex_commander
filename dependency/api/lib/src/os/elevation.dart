import 'package:flutter/foundation.dart';

/// Что предлагается сделать от администратора.
@immutable
class ElevationRequest {
  const ElevationRequest({required this.action, required this.path, required this.where});

  /// Что именно делается: «Save», «Copy». Видно в окне.
  final String action;

  /// Над чем — полным путём. Соглашаются на конкретный объект, а не на
  /// «что-нибудь в системном каталоге».
  final String path;

  /// Где: `localhost` или `user@host` — та же подпись оболочки.
  ///
  /// В окне называется **всегда**, даже когда это своя машина: «записать
  /// /etc/hosts от администратора» здесь и на чужом сервере — разные по
  /// последствиям вещи, и различать их человек должен глазами, а не по памяти о
  /// том, где стоит панель.
  final String where;

  /// Ключ, под которым помнится пароль: у каждой машины свой.
  ///
  /// Один пароль на все серверы — это не удобство, а способ отправить свой
  /// пароль туда, где его не ждали.
  String get realm => 'sudo:$where';

  @override
  String toString() => 'ElevationRequest($action $path @ $where)';
}

/// Повышение прав — та половина, которую видит экран.
///
/// Спросить может только тот, у кого есть экран, а обнаруживает нужду тот, кто
/// до экрана не дотягивается. Отсюда и разрез: здесь вопрос и ответ, а само
/// действие — по ту сторону границы ([ElevatedWrites] в `fc_core_api`).
/// Устройство то же, что у [Credentials], и по той же причине.
///
/// **Повышается одно действие, а не весь процесс.** Панели, терминал и
/// остальной сеанс остаются вашими: файловый менеджер, целиком работающий под
/// администратором, — это способ потерять систему одним `F8`.
abstract interface class Elevation implements Listenable {
  /// Разрешено ли повышение вообще. Выключено настройкой — предложения нет, и
  /// отказ остаётся отказом. На общей машине это единственный честный ответ.
  bool get enabled;

  /// Что сейчас спрашивается; null — ничего.
  ElevationRequest? get pending;

  /// Ответ пользователя: согласился или нет.
  void answer(bool agreed);
}
