import 'dart:typed_data';

/// Запуск программы в псевдотерминале.
///
/// Здесь только контракт: сам псевдотерминал платформенный, и его реализация —
/// дело модуля локальной файловой системы, как у буфера обмена и запуска
/// программ. Отделено это ради проверяемости: модуль терминала не должен
/// требовать настоящей оболочки на машине, где идёт прогон.
///
/// Службы может не быть вовсе — на платформе, где псевдотерминала нет.
/// Отсутствие означает «терминал здесь не работает», а не поломку: модуль
/// устанавливается, строка показывается приглушённой и говорит, почему.
abstract interface class PtyLauncher {
  /// Запускает программу и сразу отдаёт сессию.
  ///
  /// Ждать здесь нечего: программа скажет тогда, когда ей будет что сказать, —
  /// оболочка, например, выведет приглашение.
  ///
  /// [environment] добавляется к окружению приложения, а не заменяет его:
  /// оболочке нужен и `PATH`, и `HOME`, и всё прочее, с чем её обычно
  /// запускают.
  PtySession start({
    required String executable,
    List<String> arguments = const [],
    String? workingDirectory,
    Map<String, String> environment = const {},
    int columns = 80,
    int rows = 24,
  });
}

/// Чем запускать оболочку на этой машине; пусто — тем, чем работает человек.
///
/// Служба, а не настройка в разделе локальной ФС, и причина в направлении
/// зависимостей. Выбор оболочки — вещь **пользовательская**, живёт он в
/// настройках терминала (`fc.terminal.shell`) и там же правится; а нужен он
/// тому, кто запускает, то есть локальной файловой системе. Служба и есть тот
/// канал, которым модули сообщаются, не зная друг о друге.
///
/// Спрашивается **необязательно** (`resolveAll`): без модуля терминала никто
/// её не объявит, и тогда оболочка берётся из `$SHELL` — то же умолчание, что
/// и при пустой настройке. Оболочка при этом работает: приложение запущено на
/// этой машине, и запускать ей есть чем.
///
/// На той стороне `ssh` всё это ни при чём: там оболочку выбирает сервер.
abstract interface class ShellPreference {
  /// Чем запускать; пусто — `$SHELL`.
  String get shell;
}

/// Оболочка, доступная через провайдера дерева.
///
/// Провайдер реализует его, если у его источника есть где выполнять команды:
/// локальная файловая система — на этой машине, `ssh` — на той стороне. Не
/// реализует — значит оболочки здесь нет, и командная строка приглушена, как
/// она приглушена сегодня внутри архива.
///
/// Необязательное умение, как `NodeEditor` и `WriteAccessCheck`: соврать о нём
/// нельзя, потому что спрашивают наличие самого интерфейса.
///
/// Наружу торчит **оболочка**, а не «программа в псевдотерминале»
/// ([PtyLauncher]), и это не переименование. С сервером ломаются оба конца
/// прежнего устройства: чем запускать — решает та сторона (свой пользователь,
/// свой `$SHELL`, свой `PATH`), а каталог перестаёт быть параметром запуска —
/// канал `ssh` начинается в домашнем, и сказать об этом можно только самой
/// оболочке.
abstract interface class ShellHost {
  /// Кому принадлежит оболочка: `localhost` или `user@host`.
  ///
  /// Это и приглашение в строке, и заголовок полноэкранной сессии, и ключ, по
  /// которому постоянные оболочки различаются между собой: человек должен
  /// видеть, где выполнится набранное, до того как нажмёт `Enter`.
  String get shellLabel;

  /// Одна команда: выполнить в [directory] и закончиться.
  ///
  /// Конец известен точно — по коду возврата, а не по виду приглашения; на
  /// этом держится показ вывода с ожиданием клавиши.
  PtySession run(String command, {String? directory, int columns, int rows});

  /// Постоянная оболочка — та, что под `Ctrl-O`.
  ///
  /// [directory] учитывается только при первом запуске: дальше её каталог
  /// принадлежит ей самой.
  PtySession shell({String? directory, int columns, int rows});
}

/// Программа, запущенная в псевдотерминале.
abstract interface class PtySession {
  /// Всё, что программа вывела, — байтами.
  ///
  /// Байтами, а не строками: в терминале ходит не текст, а поток с
  /// управляющими последовательностями, и многобайтный символ вполне может
  /// приехать разорванным между двумя порциями. Собирать его — дело того, кто
  /// разбирает поток.
  Stream<Uint8List> get output;

  /// Отправить программе ввод — то, что она увидит как набранное с клавиатуры.
  void write(Uint8List data);

  /// Размер окна: программа внутри о нём спрашивает и по нему верстает.
  ///
  /// Сообщать обязательно: без этого `vim` и `htop` считают, что перед ними
  /// восемьдесят на двадцать четыре, чем бы оно ни было на самом деле.
  void resize({required int columns, required int rows});

  /// Код возврата; ждёт конца программы. Оболочку закрывают `exit`.
  Future<int> get exitCode;

  /// Прервать работу. Программа, которую уже нельзя убить, — не ошибка.
  Future<void> kill();
}
