/// Место, где провайдер может разложить временные файлы.
///
/// Нужно там, где чужой файл приходится отдать тому, кто умеет работать только
/// с настоящим файлом на диске: zip читает оглавление с конца, поэтому архив
/// внутри архива или архив на сервере сперва оказывается временным файлом.
/// Тем же путём пойдут rar, ssh и ftp.
///
/// В API — только контракт: где именно лежат временные файлы и как они
/// создаются, знает модуль локальной файловой системы.
abstract interface class StagingArea {
  /// Открывает каталог под временные файлы одной работы.
  ///
  /// [prefix] попадает в имя каталога: по нему видно, кто наследил, если
  /// уборка почему-то не случилась.
  Future<StagedDirectory> open(String prefix);
}

/// Каталог временных файлов одной работы.
///
/// **Владеет тем, что в нём лежит.** Файлы живут ровно столько, сколько живёт
/// каталог, и [dispose] обязателен — в `finally` или в `dispose` того, кто
/// каталог завёл.
abstract interface class StagedDirectory {
  /// Путь каталога в локальной файловой системе.
  String get path;

  /// Записывает содержимое в файл [name] и возвращает путь к нему.
  ///
  /// Недописанный файл выглядит как целый, поэтому при ошибке он удаляется
  /// сразу, а не дожидается [dispose].
  Future<String> write(String name, Stream<List<int>> content);

  /// Убирает каталог со всем содержимым. Повторный вызов ничего не делает.
  Future<void> dispose();
}
