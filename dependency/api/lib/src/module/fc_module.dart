/// Часть приложения, подключаемая целиком: источник, набор команд, тема.
///
/// Модуль — это единица, которой приложение прирастает. Ядро о нём знает ровно
/// столько, сколько написано здесь: имя и название. Обратной зависимости нет —
/// модуль пишется против API и ничего не знает ни о ядре, ни о соседях.
///
/// Сам по себе этот интерфейс не объявляет ничего: объявления разошлись по
/// сторонам. Источники и работы модуль объявляет как [FcBackendModule]
/// (`fc_core_api`), команды и виды — как [FcFrontendModule] (`fc_ui_api`), а
/// модуль, у которого есть и то и другое, реализует оба
/// (`docs/spec/client-server.md`, §8).
abstract interface class FcModule {
  /// Устойчивый идентификатор: пространство имён настроек, адрес в журнале,
  /// ключ в списке модулей. `fc.zip_archiver`.
  ///
  /// Один и тот же у обеих половин модуля: раздел настроек у них общий, и в
  /// списке модулей он тоже один.
  String get id;

  /// Название для справки и списка модулей.
  String get title;
}

/// Модуль, которому есть что закрыть при выходе: соединение, файл, изолят.
abstract interface class FcModuleLifecycle {
  Future<void> dispose();
}

/// Что можно спросить у своей стороны, пока она ещё собирается.
///
/// Общий для обеих сторон: службы у каждой свои, а способ их спросить один.
abstract interface class FcServices {
  /// Единственная реализация типа. Бросает, если её нет.
  T resolve<T>();

  /// Все реализации типа; пустой список, если нет ни одной.
  List<T> resolveAll<T>();
}
