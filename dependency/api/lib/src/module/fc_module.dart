/// Часть приложения, подключаемая целиком: провайдер, набор команд, тема.
///
/// Модуль — это единица, которой приложение прирастает. Ядро о нём знает ровно
/// столько, сколько написано здесь: имя, название и то, что он предлагает.
/// Обратной зависимости нет — модуль пишется против API и ничего не знает ни о
/// ядре, ни о других модулях.
///
/// Интерфейс намеренно короткий: всё необязательное выражено отдельными
/// интерфейсами ([FcModuleLifecycle]) — про флаг можно соврать, про наличие
/// метода нельзя. Тем же приёмом устроены провайдеры ([NodeEditor],
/// [ProviderLifecycle]).
abstract interface class FcModule {
  /// Устойчивый идентификатор: пространство имён настроек, адрес в журнале,
  /// ключ в списке модулей. `fc.zip_archiver`.
  String get id;

  /// Название для справки и списка модулей.
  String get title;

  /// Объявление того, что модуль предлагает.
  ///
  /// Зовётся один раз при сборке приложения — **до** того, как появится
  /// [Application]. Здесь только объявления: никакой работы, никаких обращений
  /// к другим службам. Работа, которую нужно сделать при запуске, — это
  /// стартовая команда ([FcRegistry.startup]).
  void install(FcRegistry registry);
}

/// Модуль, которому есть что закрыть при выходе: соединение, файл, изолят.
abstract interface class FcModuleLifecycle {
  Future<void> dispose();
}

/// Куда модуль складывает то, что предлагает приложению.
///
/// Только запись: реестр объявлений существует ровно на время сборки. Читать
/// зависимости здесь нельзя — их ещё нет; для этого фабрикам приходит
/// [FcServices], а командам — [FcContext].
abstract interface class FcRegistry {
  /// Службы приложения.
  ///
  /// Обращаться к ним можно **только из фабрик**: во время [FcModule.install]
  /// их ещё нет, а к моменту, когда фабрику позовут, — уже есть.
  FcServices get services;

  /// Раздел настроек этого модуля — под его же именем.
  ///
  /// Как и службы, читается не во время объявления, а позже: настройки к тому
  /// моменту уже прочитаны с диска. Обычное место для этого — стартовая
  /// команда ([startup]).
  SettingsScope get settings;

  /// Корневой источник дерева — тот, с которого начинается любой путь.
  ///
  /// Ровно один на приложение: второй — ошибка сборки, а не молчаливая замена.
  void rootProvider(TreeProvider Function(FcServices services) factory);

  /// Вложенный источник: схема пути и расширения, которыми он открывается.
  void provider(String scheme, ProviderFactory factory, {Set<String> extensions = const {}});

  /// Источник, открываемый по адресу: `ssh://user@host/srv`.
  ///
  /// В отличие от вложенного, такому не над чем монтироваться — он сам себе
  /// корень, и панель встаёт на него целиком.
  void addressProvider(String scheme, AddressFactory factory);

  /// Действие приложения. Фабрика зовётся на каждый запуск: команда хранит
  /// состояние исполнения, поэтому экземпляр у запуска свой.
  void command(FcCommandFactory factory);

  /// Клавиша за действием.
  ///
  /// Порядок задаёт приоритет: раньше объявленная привязка выигрывает.
  /// Модули устанавливаются в порядке списка, привязки — в порядке вызовов.
  void binding(KeyBinding binding);

  /// Команда, которую ядро выполняет один раз при запуске — после сборки
  /// приложения и до первого кадра.
  ///
  /// Так модуль делает то, что нельзя сделать в [FcModule.install]: прочитать
  /// свои настройки, восстановить прошлое состояние, подключиться. Ошибка
  /// стартовой команды не роняет запуск.
  void startup(FcCommandFactory factory);

  /// Оформление.
  void theme(FcThemeSpec spec);

  /// Чем рисовать содержимое панели для провайдеров, объявивших этот вид.
  void viewport(String kind, PanelViewportBuilder builder);

  /// Служба для ядра и других модулей: разрешается по типу через [FcServices].
  void service<T extends Object>(T Function(FcServices services) factory);
}

/// Что можно спросить у ядра, пока приложение ещё собирается.
abstract interface class FcServices {
  /// Единственная реализация типа. Бросает, если её нет.
  T resolve<T>();

  /// Все реализации типа; пустой список, если нет ни одной.
  List<T> resolveAll<T>();
}

/// Что можно спросить во время работы. Приходит фабрикам команд.
///
/// Отдельный тип, а не флаг: до сборки приложения [app] не существует, и
/// обращение к нему из фабрики службы должно быть невозможно, а не
/// «нежелательно».
abstract interface class FcContext implements FcServices {
  Application get app;
}

/// Как создать действие модуля.
///
/// Не путать с [AppCommandFactory] реестра: та не принимает ничего и живёт уже
/// внутри собранного приложения. Модуль же пишет фабрику, которой нужны
/// зависимости, — их и приносит [FcContext].
typedef FcCommandFactory = AppCommand Function(FcContext context);
