/// Постоянные сессии оболочки — по одной на место, где они живут.
///
/// Служба, а не поле экрана: экран открывают и закрывают, а оболочка живёт всё
/// время работы приложения.
///
/// Сама оболочка живёт **в ядре**: там псевдотерминал и там же аренда места —
/// `htop`, запущенный на сервере, обязан дожить до своего конца, даже если
/// панель ушла оттуда сразу. Здесь остаётся то, что принадлежит экрану: разбор
/// вывода, лента прокрутки и клавиши обратно
/// (`docs/spec/client-server.md`, §5.1.5).
///
/// **Своя заводится заранее, серверная — по надобности.** Лень была общей и
/// стоила заметного: первый `Ctrl-O` и первая команда ждали запуска оболочки,
/// чтения `.zshrc`, уговора о метках и `clear` — до трёх секунд на тяжёлой
/// настройке, и всё это на глазах. Своя машина ничем за прогрев не платит:
/// процесс один, спит и ничего не делает. Сервер — платит походом по сети и,
/// случается, вопросом о пароле, поэтому его оболочка по-прежнему ждёт, пока
/// её попросят.
///
/// Сессий несколько, потому что мест несколько: своя машина и каждый сервер, на
/// который зашла панель. Ключ — [ShellHost.shellLabel], а не сам провайдер: два
/// соединения к одному серверу должны делить одну оболочку, иначе `Ctrl-O`
/// открывал бы новую всякий раз, когда панель перемонтировали. Локальная —
/// такая же запись в этой таблице, без особого случая.
class ShellSession extends ChangeNotifier {
  ShellSession({required this.settings});

  final TerminalSettings Function() settings;

  /// Оболочка **ушла** в другой каталог.
  ///
  /// Зовётся не на всякое приглашение, а только когда каталог с прошлого
  /// приглашения сменился: это и значит «человек сделал `cd`» — из строки или
  /// руками в развёрнутом терминале.
  ///
  /// **Первое приглашение переходом не считается.** Оболочка печатает его при
  /// запуске и говорит им, где её запустили, а не куда она ушла. Греют её при
  /// старте приложения, никого не спрашивая, и начинается она там, откуда
  /// запущен процесс, — для собранного приложения это `/`. Пойти за таким
  /// приглашением значит увести человека из каталога, который ему только что
  /// восстановили.
  ///
  /// Что делать с переходом, решает не таблица оболочек: она про сессии, а не
  /// про панели.
  void Function(String shellLabel, String directory)? onDirectory;

  /// Сколько ждать первого приглашения от свежей оболочки.
  ///
  /// Ждёт **тот, кто шлёт команду**, а не тот, кто открывает оболочку: `Ctrl-O`
  /// показывает её сразу, пусть и с пустым экраном, а вот команду до первого
  /// приглашения слать нельзя — её концом окажется приглашение, напечатанное
  /// оболочкой самой, ещё до неё.
  ///
  /// Ждать вечно тоже нельзя: оболочка может не понять уговора вовсе. Трёх
  /// секунд хватает и тяжёлому `.zshrc`, и походу по сети до сервера.
  static const Duration settleTimeout = Duration(seconds: 3);

  /// Каким терминал считает себя, пока его никто не показал.
  ///
  /// Размер оболочке сообщает вид, а вида до первого `Ctrl-O` нет вовсе — и
  /// оболочка считала бы себя шириной в 80 колонок. Всё, что печатается до
  /// показа (приглашения, наши служебные `cd`), переносилось бы по 80-й
  /// колонке, и в ленте оставались бы рваные строки — видно живьём.
  ///
  /// Щедро, а не «как окно»: настоящий размер всё равно назовёт вид, а до него
  /// важно одно — чтобы длинный путь в приглашении не переносился.
  static const int startColumns = 200;
  static const int startRows = 50;

  final Map<String, TerminalSession> _sessions = {};

  /// Оболочку этого места уже запускали.
  bool startedAt(String shellLabel) => _sessions.containsKey(shellLabel);

  /// Сессия этого места, если она уже живёт; null — не заводили.
  ///
  /// Синхронно и **не заводя новой**: строка команд спрашивает её на каждой
  /// перерисовке, чтобы показать приглашение, и заводить из-за показа оболочку
  /// нельзя — она заводится, когда есть что выполнять ([sessionIn]).
  TerminalSession? at(String shellLabel) => _sessions[shellLabel];

  /// Хоть какая-то оболочка жива.
  bool get started => _sessions.isNotEmpty;

  /// Сессия того места, где стоит панель; заводит её, если ещё не заводили.
  ///
  /// [panel] null — своя машина: так её греют заранее, когда панелей ещё нет.
  /// [directory] — откуда оболочка начнёт, и учитывается он только при первом
  /// запуске: дальше её каталог принадлежит ей самой.
  ///
  /// Аренды здесь больше нет: место держит ядро, пока жива оболочка.
  Future<TerminalSession> sessionIn(Application app, {Session? panel, String? directory}) {
    // Одно открытие на место. Просящих теперь несколько — прогрев при запуске,
    // `Ctrl-O`, команда из строки и показ приглашения, — и, начавшись разом,
    // они открыли бы два канала: второй тут же оказался бы лишним, а на той
    // стороне остался бы висеть процессом.
    //
    // Ключ — имя места у панели: то же, каким сессия потом и ляжет в таблицу.
    // Прогрев панели не называет вовсе, и ключ у него свой, пустой: он один и
    // случается раньше всех.
    final key = panel?.source.shellLabel ?? '';
    final live = _sessions[key];
    if (live != null) {
      return Future.value(live);
    }
    final opening = _opening[key];
    if (opening != null) {
      return opening;
    }
    final work = _openIn(app, panel: panel, directory: directory);
    _opening[key] = work;
    return work.whenComplete(() => _opening.remove(key));
  }

  final Map<String, Future<TerminalSession>> _opening = {};

  Future<TerminalSession> _openIn(Application app, {Session? panel, String? directory}) async {
    // Ждём: на сервере открытие канала — поход по сети, и не удаться оно
    // вполне может. Отказ уходит бедой тому, кто просил.
    final channel = await app.openShell(panel: panel, directory: directory, columns: startColumns, rows: startRows);
    final label = channel.label;
    final current = _sessions[label];
    if (current != null) {
      return current;
    }

    // Уговор о метках — первой же строкой в свежую оболочку. Без него конец
    // команды из строки останется незамеченным (`spec/single-shell-session.md`).
    // Уже жившей второй раз не шлём: она о себе и так рассказывает, а лишняя
    // строка встала бы поперёк того, что человек в ней делает.
    final agreement = ShellAgreement();
    final opened = TerminalSession.around(channel.pty, maxLines: settings().maxLines, agreement: agreement);
    final setup = channel.fresh ? agreement.setupFor(channel.program.isEmpty ? null : channel.program) : '';
    if (setup.isNotEmpty) {
      // `clear` **той же строкой**: сама строка уговора в ленте не нужна, а всё,
      // что после неё, — уже жизнь человека. Той же, а не следующей, потому что
      // отдельная строка осела бы в истории — уговор от неё как раз и прячется
      // (`docs/spec/single-shell-session.md`).
      opened.input('$setup; clear\n');
    }
    // Оболочка смертна: `exit`, `kill`, обрыв `ssh`. Умерла — уходит из
    // таблицы, и следующая команда заводит новую; держать мёртвую значило бы
    // слать команды в никуда.
    // Где оболочка была на прошлом приглашении; null — приглашений ещё не
    // было. Держится здесь, а не в сессии: сессия рассказывает о метках как
    // есть, а «переход это или нет» — вопрос к тому, кто за ним идёт.
    String? seenAt;
    opened.onMark = (mark) {
      if (mark.kind != ShellMarkKind.prompt || mark.directory.isEmpty) {
        return;
      }
      final was = seenAt;
      seenAt = mark.directory;
      // Первое приглашение — не переход, и приглашение на том же месте тоже:
      // команда, кончившаяся там же, где началась, панель не двигает.
      if (was == null || was == mark.directory) {
        return;
      }
      onDirectory?.call(label, mark.directory);
    };
    unawaited(
      opened.exited.then((_) {
        if (identical(_sessions[label], opened)) {
          _sessions.remove(label);
        }
      }),
    );

    _sessions[label] = opened;
    // Сессия завелась — об этом надо сказать: строка команд показывает её
    // приглашение, а заводится оболочка заранее и сама
    // (`docs/spec/shell-prompt.md`, §7).
    notifyListeners();
    return opened;
  }

  /// Место закрылось — закрылась и его оболочка.
  ///
  /// Зовётся, когда уходит провайдер: держать сессию сервера, с которого уже
  /// ушли, незачем — она всё равно оборвана.
  void closeAt(String shellLabel) {
    _sessions.remove(shellLabel)?.dispose();
    notifyListeners();
  }

  /// Приложение уходит — уходят и все оболочки.
  void close() {
    for (final session in _sessions.values) {
      session.dispose();
    }
    _sessions.clear();
  }
}
