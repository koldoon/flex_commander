/// Как зовут работу записи и её доводы.
///
/// Отдельным файлом, потому что имена нужны **обеим** сторонам: экран собирает
/// заявку, ядро по ней узнаёт свою работу. Здесь только строки — ни дерева, ни
/// провайдеров, — и потому этот файл видят обе половины модуля, не таща за
/// собой чужой половины (`docs/spec/client-server.md`, §8).
abstract final class EditorWork {
  /// Имя работы: под ним её и зовут из команды.
  static const String kind = 'editor.save';

  /// Что записать — текстом целиком.
  ///
  /// Целиком, а не кусками: правят его в памяти, и редактор всё равно держит
  /// весь файл. Кусочная запись с подтверждением понадобится тому, кто пишет
  /// больше, чем помещается, — а такой сегодня один, сборка архивов, и она
  /// целиком по эту сторону границы.
  static const String textOption = 'text';
}
