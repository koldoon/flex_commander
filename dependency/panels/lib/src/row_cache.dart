import 'package:flutter/widgets.dart';

/// Память готовых строк: та же строка отдаётся тем же виджетом.
///
/// Спецификация — `docs/spec/panel-redraw.md`.
///
/// Список пересобирается на каждое сообщение панели, а меняются в нём две
/// строки — та, с которой курсор ушёл, и та, на которую встал. Пропустить
/// пересборку каркас умеет только у **того же самого** виджета: `Widget.==`
/// переопределить нельзя (он `@nonVirtual`), и равенство у виджетов всегда по
/// экземпляру. Значит, неизменившуюся строку надо отдавать прежним экземпляром,
/// а не собирать заново равную.
///
/// Одна на все виды панели: правило у таблицы, дерева, краткого, значков и
/// столбцов одно, а пять копий одного правила однажды разойдутся.
class RowCache {
  /// Строки, спрошенные на этой сборке, и на прошлой.
  ///
  /// Две карты, а не одна: иначе в памяти осело бы столько строк, сколько их в
  /// каталоге, — а каталог бывает на сто тысяч записей. Здесь остаётся
  /// примерно удвоенное число спрошенных за кадр.
  Map<int, _Row> _now = {};
  Map<int, _Row> _past = {};

  List<Object?>? _marks;

  /// Общее на весь список: тема, раскладка, размеры, сам список строк.
  ///
  /// Разошлось — прежние строки ни о чём: они нарисованы другой темой, другой
  /// ширины или вовсе из другого каталога.
  ///
  /// Зовётся один раз на сборку списка, до первой [of].
  void frame(List<Object?> marks) {
    if (_marks != null && _same(_marks!, marks)) {
      // Кадр тот же — прошлое становится позапрошлым и уходит.
      _past = _now;
      _now = {};
      return;
    }
    _marks = marks;
    _past = {};
    _now = {};
  }

  /// Строка по номеру; [build] зовётся, только если приметы изменились.
  ///
  /// Приметы — то, чем строка отличается от себя же вчерашней: она сама,
  /// пометка, курсор, активность панели. Обработчик нажатия в них не входит:
  /// замыкание помнит номер, а номер значит ту же строку, пока список тот же, —
  /// сменился список, и память сброшена целиком.
  Widget of(int index, List<Object?> marks, Widget Function() build) {
    final ready = _now[index] ?? _past[index];
    if (ready != null && _same(ready.marks, marks)) {
      return (_now[index] = ready).widget;
    }
    final made = _Row(marks, build());
    _now[index] = made;
    return made.widget;
  }

  /// Забыть всё: список больше не тот.
  void clear() {
    _marks = null;
    _past = {};
    _now = {};
  }

  /// Приметы сверяются поэлементно: у чисел, флагов и текста это значение, у
  /// строки списка, раскладки и списка ширин — экземпляр, чего нам и надо.
  static bool _same(List<Object?> a, List<Object?> b) {
    if (a.length != b.length) {
      return false;
    }
    for (var at = 0; at < a.length; at++) {
      if (a[at] != b[at]) {
        return false;
      }
    }
    return true;
  }
}

class _Row {
  const _Row(this.marks, this.widget);

  final List<Object?> marks;
  final Widget widget;
}
