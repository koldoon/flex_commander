import 'app_version.dart';

/// Что приложение знает о самом себе: версия, место на диске, процессор.
///
/// **Платформенное за интерфейсом.** Версия лежит в `Info.plist`, путь
/// считается от исполняемого файла, а проверка «можно ли туда писать» — это
/// файловая система. Ни одно из трёх не должно попадать в решение об
/// обновлении: тест не трогает настоящий `.app`
/// (`docs/spec/self-update.md`, §7).
abstract interface class AppBuild {
  /// Своя версия; null — узнать не вышло.
  ///
  /// У сборки с машины разработчика здесь `1.0.0` из `pubspec.yaml` — она
  /// новее любого выпуска, и обновление ей само собой не предлагается.
  AppVersion? get version;

  /// Каталог `.app`, который придётся подменить; пусто — приложение запущено
  /// не из бандла (так бывает в проверках и при `flutter run`).
  String get bundlePath;

  /// `arm64` или `x64` — то, чем подписан нужный нам файл выпуска.
  String get architecture;

  /// Можно ли подменить себя: бандл лежит на томе для записи и принадлежит
  /// нам.
  ///
  /// Спрашивается **до** загрузки: узнать, что ставить некуда, после двадцати
  /// четырёх мегабайт — значит потратить чужое время впустую.
  bool get canReplaceItself;
}
