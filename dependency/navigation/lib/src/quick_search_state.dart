import 'package:fc_ui_api/fc_ui_api.dart';
import 'package:flutter/foundation.dart';

/// Быстрый поиск: набранное и панель, по которой идут.
///
/// **Содержимое статусной области, а не поле панели.** Под панелью для такого и
/// заведено место (`leftStatus`/`rightStatus`), и стопка там выкладывается
/// столбцом: идёт работа — под ней поиск, и одно другого не прячет. Панель при
/// этом остаётся панелью: её высота, её курсор, её строка состояния про то, что
/// под курсором.
///
/// Само присутствие этого состояния и есть «режим включён»: отдельного признака
/// нет, и рассогласовать их поэтому невозможно.
class QuickSearchState extends ChangeNotifier implements TransientContent {
  QuickSearchState({required this.panel, required this.onLeave, required Set<String> keeps})
    : _keeps = keeps,
      _directory = panel.directory?.pathString {
    panel.addListener(_watchPanel);
  }

  final Panel panel;

  /// Команды, при которых полоса остаётся, — её собственные.
  ///
  /// Приходят снаружи, а не спрашиваются у команд: список составляет тот, кто
  /// эти команды и объявил, — модуль. Иначе состоянию пришлось бы знать о
  /// командах, которые знают о нём.
  final Set<String> _keeps;

  /// Как уйти: убрать себя из области. Зовётся и по `Esc`, и когда панель
  /// сменила каталог.
  final void Function() onLeave;

  /// Набранное целиком — и то, что нашлось, и то, что нет.
  String get pattern => '$_matched$_tail';

  /// Часть образца, которой отвечает имя в списке: по ней и стоит курсор.
  String get matched => _matched;

  /// Набранное сверх найденного: ни одно имя так не начинается.
  ///
  /// Хвост показывается выделенным и стирается **разом**, одним `Bsp`. Раньше
  /// такая буква просто не принималась, и человек оставался без ответа: поле
  /// на экране, курсор в нём, нажатия уходят в никуда — а звонка у нас нет.
  /// Чаще всего виновата раскладка, и увидеть это надо глазами.
  ///
  /// Длиннее одной буквы хвост бывает потому, что печатать мы не мешаем:
  /// набравший вслепую целое слово увидит его целиком и сотрёт одним нажатием.
  String get tail => _tail;

  String _matched = '';
  String _tail = '';

  String? _directory;

  /// Меняет образец целиком: найденную часть и хвост сразу.
  ///
  /// Двумя кусками, а не одной строкой с числом: рассогласовать «сколько
  /// нашлось» и «что набрано» так невозможно, а показ и стирание смотрят ровно
  /// на эти два поля.
  void setPattern({required String matched, required String tail}) {
    if (_matched == matched && _tail == tail) {
      return;
    }
    _matched = matched;
    _tail = tail;
    notifyListeners();
  }

  /// Панель ушла в другой каталог — искать больше не в чем.
  ///
  /// Образец относится к **тому** списку: в новом он ничего не значит и вводил
  /// бы в заблуждение.
  void _watchPanel() {
    final now = panel.directory?.pathString;
    if (now != _directory) {
      _directory = now;
      onLeave();
    }
  }

  /// Любая чужая команда снимает полосу — стрелка, `Tab`, `F5`, что угодно.
  ///
  /// Так ведёт себя `mc`, и так правило остаётся простым: полоса живёт, пока
  /// идут её собственные команды. Помнить, какие клавиши её оставляют, а какие
  /// нет, человеку не приходится.
  @override
  bool survivesCommand(String commandId) => _keeps.contains(commandId);

  /// Клавиши принадлежат поиску, пока полоса на экране.
  ///
  /// На системный фокус это не влияет: статусная область активной не бывает, а
  /// шелл фокусирует только активную. Зато по этому свойству другие узнают, что
  /// набор занят, — так командная строка в режиме `mc` уступает поиску буквы,
  /// не зная о нём ничего.
  @override
  bool get takesKeyboard => true;

  @override
  void close() {
    panel.removeListener(_watchPanel);
    dispose();
  }
}
