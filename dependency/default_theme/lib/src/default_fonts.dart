import 'package:fc_api/fc_api.dart';

/// Шрифты оформления по умолчанию — те же, что в референсе
/// (`resources/styles/typo.css`), но возит приложение с собой не все.
///
/// Интерфейсный лежит в `assets/fonts`: Ubuntu свободен (Ubuntu Font Licence
/// 1.0), и с ним интерфейс выглядит одинаково на любой системе.
///
/// **Шрифт списка берётся из системы.** Consolas принадлежит Microsoft и
/// лицензируется только вместе с тем продуктом, в котором поставлен, — класть
/// его в чужой дистрибутив нельзя. Имя при этом остаётся прежним: у кого
/// стоит Office или сам Windows, тот увидит ровно то оформление, ради которого
/// шрифт и выбирался.
///
/// [fixedFallback] — для всех остальных: без него подстановку делает система, а
/// она берёт обычный пропорциональный шрифт, и столбцы размеров и дат
/// разъезжаются. Menlo стоит на каждой macOS с 10.6 и по строке совпадает с
/// Consolas точь-в-точь (15.0 точки при кегле 13.09), так что сетка списка от
/// подстановки не едет; знак у него шире на десятую долю (7.88 против 7.20), и
/// на той же ширине колонка имён вмещает примерно на девять процентов меньше
/// символов.
///
/// Список короткий и macOS-овский, потому что и приложение пока только под
/// macOS; другим системам понадобятся свои имена (`DejaVu Sans Mono`,
/// `Liberation Mono`). Настоящий же ответ — этап В3 дорожной карты: тема
/// станет редактируемой, шрифт выберет человек, и гадать за него не придётся.
class DefaultFonts extends FcFonts {
  const DefaultFonts({this.ui = 'Ubuntu', this.fixed = 'Consolas', this.fixedFallback = const ['Menlo']});

  @override
  final String ui;

  @override
  final String fixed;

  @override
  final List<String> fixedFallback;
}
