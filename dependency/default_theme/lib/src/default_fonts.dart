import 'package:fc_api/fc_api.dart';

/// Шрифты оформления по умолчанию.
///
/// Интерфейсный шрифт — тот же, что в референсе (`resources/styles/typo.css`):
/// он свободный (Ubuntu Font Licence 1.0) и лежит в `assets/fonts` приложения,
/// поэтому интерфейс выглядит одинаково на любой системе.
///
/// Моноширинный — **системный**, а не свой. Референсный Consolas принадлежит
/// Microsoft и лицензируется только вместе с тем продуктом, в котором
/// поставлен, — распространять его в чужом дистрибутиве нельзя. Menlo стоит на
/// каждой macOS с 10.6 и по строке совпадает с Consolas точь-в-точь (15.0
/// точки при кегле 13.09), так что сетка списка от замены не поехала; знак у
/// него шире на десятую долю (7.88 против 7.20), и колонка имён на том же
/// месте вмещает примерно на девять процентов меньше символов.
///
/// Имя жёсткое, потому что и приложение пока только под macOS. Придут другие
/// системы — им нужны свои имена (`Consolas` на Windows, `DejaVu Sans Mono` на
/// Linux), а выбор шрифта человеком закрывает этап В3 дорожной карты: тема
/// станет редактируемой, и отвечать за чужие шрифты приложению не придётся
/// вовсе.
class DefaultFonts extends FcFonts {
  const DefaultFonts({this.ui = 'Ubuntu', this.fixed = 'Menlo'});

  @override
  final String ui;

  @override
  final String fixed;
}
